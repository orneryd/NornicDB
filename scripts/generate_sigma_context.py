#!/usr/bin/env python3
"""Regenerate the pinned sigma-context delta from captured runtime properties.

This generates context data, not Unicode case mappings or a Java iterator.
Snapshots: Neo4j 5.26.30 image 174ca8edaafb / JDK 21.0.12; Go Unicode17.
The exhaustive Go test verifies the resulting runtime classifier against the
pinned snapshots. Changing Go's Unicode tables requires a new Go snapshot and
review of the regenerated delta. No network or runtime Java dependency.
"""
from pathlib import Path
import argparse, gzip, hashlib, json, subprocess

root=Path(__file__).resolve().parents[1]
data=root/'pkg/cypher/fn/testdata/sigma'
parser=argparse.ArgumentParser()
parser.add_argument('--snapshots',required=True,type=Path,help='external pinned profile snapshot directory')
args=parser.parse_args()
manifest=json.loads((data/'profile.json').read_text())
def read(name):
 raw=(args.snapshots/name).read_bytes()
 assert hashlib.sha256(raw).hexdigest()==manifest['snapshots'][name], name
 return gzip.decompress(raw)
categories=read('java-break-context.bin.gz')
java=read('java-context.bin.gz')
go=read('go-context.bin.gz')
classes={1:3,4:1,12:2,11:3,255:4,5:5,2:6,8:6,18:7,21:7,19:8,6:9}
def cased_extra(n):
 return 0x2b0<=n<=0x2b8 or 0x2c0<=n<=0x2c1 or 0x2e0<=n<=0x2e4 or n in (0x345,0x37a) or 0x1d2c<=n<=0x1d61 or 0x2160<=n<=0x217f or 0x24b6<=n<=0x24e9

def baseline(n):
 m=go[n]
 if m&16:c=4
 elif m&8:c=3
 elif n in (0x964,0x965):c=5

 elif m&3:c=1
 elif m&4:c=2
 elif n in (34,39,46):c=6
 elif m&32 or n==0x2027:c=7
 elif n in (44,0x66b):c=8
 elif n in (37,38,0xa2,0x66a,0x2030,0x2031):c=9
 else:c=0
 return c | (128 if m&64 else 0)

ranges=[]
for n in range(len(java)):
 value=classes.get(categories[n],0)|(128 if java[n]&64 or cased_extra(n) else 0)
 if value!=baseline(n):
  if ranges and ranges[-1][1]+1==n and ranges[-1][2]==value:ranges[-1][1]=n
  else:ranges.append([n,n,value])
header='''// Code generated by scripts/generate_sigma_context.py; DO NOT EDIT.
// Context profile: Neo4j 5.26.30 / JDK 21.0.12, Go Unicode17 baseline.
// Provenance and immutable snapshot hashes: testdata/sigma/profile.json.
package fn

var sigmaContextDeltas = [...]struct {
 lo, hi rune
 value byte
}{
'''
source=header+''.join('\t{0x%x, 0x%x, %d},\n'%tuple(row) for row in ranges)+'}\n'
source=subprocess.check_output(['gofmt'],input=source.encode()).decode()
(root/'pkg/cypher/fn/sigma_context_table.go').write_text(source)
print('generated',len(ranges),'ranges')
