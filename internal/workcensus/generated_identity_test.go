func TestGeneratedBlankOccurrenceIdentity(t *testing.T) {
	const source = "// Code generated by fixture; DO NOT EDIT.\npackage sample\nvar _ int\nvar _ string\nvar _ bool\n"
	for _, typed := range []bool{false, true} {
		t.Run(map[bool]string{false: "syntax", true: "typed"}[typed], func(t *testing.T) {
			c := declarationIdentityConfig(t, typed, source)
			if typed {
				c.SourceOnly = true
			}
			c.Selectors = []Selector{{Kind: "definition", Node: "declaration", Reachability: "all"}}
			base := mustExtract(t, c)
			assertUniqueEntities(t, base)
			if len(base.Members) != 3 {
				t.Fatalf("blank population=%d", len(base.Members))
			}
			removed := strings.Replace(source, "var _ int", strings.Repeat(" ", len("var _ int")), 1)
			c.Overlay = map[string][]byte{filepath.Join(c.Dir, "source.go"): []byte(removed)}
			actual := mustExtract(t, c)
			assertUniqueEntities(t, actual)
			for _, old := range base.Members {
				if old.Code == "_ int" {
					continue
				}
				found := false
				for _, now := range actual.Members {
					if old.Code == now.Code {
						found = true
						if old.ID != now.ID || old.SiteID != now.SiteID || old.OwnerID != now.OwnerID {
							t.Errorf("retained entity changed after another blank was removed: %s -> %s", old.ID, now.ID)
						}
					}
				}
				if !found {
					t.Fatal("retained blank was dropped", old.Code)
				}
			}
		})
	}
}

func assertUniqueEntities(t *testing.T, inv Inventory) {
	t.Helper()
	ids := map[string]bool{}
	for _, m := range inv.Members {
		if m.ID == "" || ids[m.ID] {
			t.Fatal("duplicate/empty member ID", m.ID)
		}
		ids[m.ID] = true
	}
	ids = map[string]bool{}
	for _, d := range inv.Definitions {
		if d.ID == "" || ids[d.ID] {
			t.Fatal("duplicate/empty owner ID", d.ID)
		}
		ids[d.ID] = true
	}
}

