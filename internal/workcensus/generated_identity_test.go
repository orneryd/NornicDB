func TestGeneratedSourceIdentityAcrossCacheLocations(t *testing.T) {
	repo := t.TempDir()
	const source = "// Code generated by fixture; DO NOT EDIT.\npackage generated\n//line diagnostic.go:999\nvar _ int\nvar _ string\nvar _ bool\n"
	var base Inventory
	for _, name := range []string{"cache-a", "cache-b"} {
		path := filepath.Join(t.TempDir(), name+"-d")
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
		c := Config{Dir: repo, Documents: []Document{{Path: path, Language: "go"}}, Selectors: []Selector{{Kind: "definition", Node: "declaration", Reachability: "all"}}}
		actual := mustExtract(t, c)
		assertUniqueEntities(t, actual)
		for _, m := range actual.Members {
			if m.Line < 4 || m.Line > 6 {
				t.Error("diagnostic directive replaced physical source coordinates", m.Line)
			}
		}
		if len(base.Members) == 0 {
			base = actual
			continue
		}
		for i, m := range actual.Members {
			if m.ID != base.Members[i].ID || m.SiteID != base.Members[i].SiteID {
				t.Error("identical compiler-generated source changed identity with its cache directory", base.Members[i].ID, m.ID)
			}
		}
	}
}

func TestAnonymousOwnerOccurrenceIdentity(t *testing.T) {
	const source = "package sample\nfunc Owner(){_ = func(){for range 1{}};_ = func(){for range 2{}}}\n"
	for _, typed := range []bool{false, true} {
		t.Run(map[bool]string{false: "syntax", true: "typed"}[typed], func(t *testing.T) {
			c := declarationIdentityConfig(t, typed, source)
			if typed {
				c.SourceOnly = true
			}
			c.Selectors = []Selector{{Kind: "definition", Node: "declaration", Reachability: "all"}}
			base := mustExtract(t, c)
			first := "_ = func(){for range 1{}};"
			c.Overlay = map[string][]byte{filepath.Join(c.Dir, "source.go"): []byte(strings.Replace(source, first, strings.Repeat(" ", len(first)), 1))}
			actual := mustExtract(t, c)
			assertUniqueEntities(t, actual)
			found := false
			for _, old := range base.Members {
				if old.Declaration != "closure" || !strings.Contains(old.Code, "range 2") {
					continue
				}
				for _, now := range actual.Members {
					if now.Code == old.Code {
						found = true
						if now.ID != old.ID || now.SiteID != old.SiteID || now.OwnerID != old.OwnerID {
							t.Error("anonymous identity reassigned after another literal removal", old.ID, now.ID)
						}
					}
				}
			}
			if !found {
				t.Fatal("retained literal missing")
			}
		})
	}
}

func TestDistinctGeneratedUnitsWithIdenticalContents(t *testing.T) {
	repo := t.TempDir()
	const source = "// Code generated by fixture; DO NOT EDIT.\npackage generated\nvar _ int\nvar _ string\nvar _ bool\n"
	c := Config{Dir: repo, Selectors: []Selector{{Kind: "definition", Node: "declaration", Reachability: "all"}}}
	for _, name := range []string{"one-d", "two-d"} {
		path := filepath.Join(t.TempDir(), name)
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
		c.Documents = append(c.Documents, Document{Path: path, Language: "go"})
	}
	actual := mustExtract(t, c)
	assertUniqueEntities(t, actual)
	if len(actual.Members) != 6 || len(actual.Definitions) != 6 || len(actual.Sources) != 2 {
		t.Fatalf("distinct generated units collapsed by content: members=%d owners=%d sources=%d", len(actual.Members), len(actual.Definitions), len(actual.Sources))
	}
}
