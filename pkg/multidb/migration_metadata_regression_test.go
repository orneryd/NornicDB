package multidb

import (
	"reflect"
	"testing"
	"time"

	"github.com/orneryd/nornicdb/pkg/storage"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestLegacyMigrationPreservesEveryEntityField(t *testing.T) {
	inner := newLegacyTestEngine(t)
	created := time.Date(2026, 1, 2, 3, 4, 5, 123, time.UTC)
	node := &storage.Node{ID: "a", Labels: []string{"Doc"}, Properties: map[string]any{"integer": int64(9007199254740993)}, CreatedAt: created, UpdatedAt: created.Add(time.Hour), ChunkEmbeddings: [][]float32{{1, 2}}, NamedEmbeddings: map[string][]float32{"title": {3, 4}}, EmbedMeta: map[string]any{"chunks": int64(1)}, EmbeddingsStoredSeparately: true, VisibilitySuppressed: true}
	edge := &storage.Edge{ID: "e", StartNode: "a", EndNode: "b", Type: "LINKS", Properties: map[string]any{"integer": int64(9007199254740993)}, CreatedAt: created, UpdatedAt: created.Add(time.Hour), Confidence: 0.7, AutoGenerated: true, VisibilitySuppressed: true}
	_, err := inner.CreateNode(node)
	require.NoError(t, err)
	_, err = inner.CreateNode(&storage.Node{ID: "b"})
	require.NoError(t, err)
	require.NoError(t, inner.CreateEdge(edge))
	manager, err := NewDatabaseManager(t.Context(), inner, nil)
	require.NoError(t, err)
	t.Cleanup(func() { _ = manager.Close() })
	got, err := inner.GetNode("nornic:a")
	require.NoError(t, err)
	want := *storage.CopyNode(node)
	want.ID = "nornic:a"
	assertMigratedExportedEntityFields(t, &want, got)
	gotEdge, err := inner.GetEdge("nornic:e")
	require.NoError(t, err)
	wantEdge := *storage.CopyEdge(edge)
	wantEdge.ID = "nornic:e"
	wantEdge.StartNode = "nornic:a"
	wantEdge.EndNode = "nornic:b"
	assertMigratedExportedEntityFields(t, &wantEdge, gotEdge)
	_, err = inner.GetNode("a")
	assert.ErrorIs(t, err, storage.ErrNotFound)
	assert.Equal(t, storage.NodeID("a"), node.ID, "migration must not rewrite caller-owned originals")
	assert.True(t, node.VisibilitySuppressed)
}

// Compare every exported field, including future additions. Native read views
// attach private transient provenance, which is not persisted entity data.
func assertMigratedExportedEntityFields(t *testing.T, want, got interface{}) {
	t.Helper()
	expected, actual := reflect.ValueOf(want).Elem(), reflect.ValueOf(got).Elem()
	require.Equal(t, expected.Type(), actual.Type())
	for index := 0; index < expected.NumField(); index++ {
		field := expected.Type().Field(index)
		if !field.IsExported() {
			continue
		}
		left, right := expected.Field(index).Interface(), actual.Field(index).Interface()
		if field.Name == "EmbeddingsStoredSeparately" {
			assert.Equal(t, false, right, "native hydrated node exposes its materialized embedding body")
			continue
		}
		if instant, ok := left.(time.Time); ok {
			assert.True(t, instant.Equal(right.(time.Time)), "%s timestamp: expected %v, got %v", field.Name, left, right)
			continue
		}
		assert.Equal(t, left, right, "migration must preserve exported field %s", field.Name)
	}
}
