func historicalGobCommand(t *testing.T, value any) []byte {
	t.Helper()
	var out bytes.Buffer
	require.NoError(t, gob.NewEncoder(&out).Encode(value))
	return out.Bytes()
}

func TestV4ReplicationWALConvertsDirectAndBulkEntityCommands(t *testing.T) {
	// These structures reproduce the old on-disk gob payloads; they must not
	// call the current command encoder, which is the object of this test.
	node := historicalGobCommand(t, struct {
		ID              string
		Labels          []string
		Properties      map[string]any
		NamedEmbeddings map[string][]float32
		ChunkEmbeddings [][]float32
		CreatedAtUnixNs int64
		UpdatedAtUnixNs int64
	}{ID: "test:n", Labels: []string{"Item"}, Properties: map[string]any{"ids": []int64{7, 8}}, NamedEmbeddings: map[string][]float32{"vector": {1, 2}}})
	edge := historicalGobCommand(t, struct {
		ID, StartNode, EndNode, Type string
		Properties                   map[string]any
		CreatedAt                    int64
		Confidence                   float64
		AutoGenerated                bool
	}{ID: "test:e", StartNode: "test:n", EndNode: "test:other", Type: "LINK", Properties: map[string]any{"weight": int64(7)}, Confidence: 0.75})
	cases := []struct {
		name     string
		kind     CommandType
		payload  []byte
		wantType storage.OperationType
	}{
		{"node create", CmdCreateNode, node, storage.OpCreateNode},
		{"node update", CmdUpdateNode, node, storage.OpUpdateNode},
		{"node delete", CmdDeleteNode, []byte("test:n"), storage.OpDeleteNode},
		{"edge create", CmdCreateEdge, edge, storage.OpCreateEdge},
		{"edge update", CmdUpdateEdge, edge, storage.OpUpdateEdge},
		{"edge delete", CmdDeleteEdge, historicalGobCommand(t, struct{ EdgeID string }{"test:e"}), storage.OpDeleteEdge},
		{"bulk nodes", CmdBulkCreateNodes, historicalGobCommand(t, [][]byte{node}), storage.OpCreateNode},
		{"bulk edges", CmdBulkCreateEdges, historicalGobCommand(t, [][]byte{edge}), storage.OpCreateEdge},
		{"bulk delete nodes", CmdBulkDeleteNodes, historicalGobCommand(t, []storage.NodeID{"test:n"}), storage.OpDeleteNode},
		{"bulk delete edges", CmdBulkDeleteEdges, historicalGobCommand(t, []storage.EdgeID{"test:e"}), storage.OpDeleteEdge},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			original := replicationWALRecord{Timestamp: 7, Command: &Command{Type: tc.kind, Data: tc.payload, RequestID: "request", Timestamp: time.Unix(7, 0).UTC()}}
			data, err := json.Marshal(original)
			require.NoError(t, err)
			converted, err := TranscodeV4WALPayload(5, "replication_command", data)
			require.NoError(t, err)
			var got replicationWALRecord
			require.NoError(t, json.Unmarshal(converted, &got))
			require.Equal(t, original.Timestamp, got.Timestamp)
			require.Equal(t, original.Command.Type, got.Command.Type)
			require.Equal(t, original.Command.RequestID, got.Command.RequestID)
			if tc.kind != CmdDeleteNode {
				ok, err, trailing := singleMessagePackValue(got.Command.Data)
				require.NoError(t, err)
				require.Zero(t, trailing, "converted command must not contain historical gob bytes")
				require.True(t, ok)
			}
			ops, handled, err := decodeEntityCommandOperations(got.Command.Type, got.Command.Data)
			require.NoError(t, err)
			require.True(t, handled)
			require.Len(t, ops, 1)
			require.Equal(t, tc.wantType, ops[0].Type)
			if ops[0].Node != nil {
				require.Equal(t, []int64{7, 8}, ops[0].Node.Properties["ids"])
				require.Equal(t, []float32{1, 2}, ops[0].Node.NamedEmbeddings["vector"])
			}
			if ops[0].Edge != nil {
				require.Equal(t, int64(7), ops[0].Edge.Properties["weight"])
				require.Equal(t, 0.75, ops[0].Edge.Confidence)
			}
		})
	}
}

func TestV4ReplicationWALRejectsRetiredAndUnknownCommands(t *testing.T) {
	for _, kind := range []CommandType{cmdRetiredSetProperty, cmdRetiredBatchWrite, cmdRetiredCypher, CommandType(255)} {
		data, err := json.Marshal(replicationWALRecord{Command: &Command{Type: kind, Data: []byte("old-payload")}})
		require.NoError(t, err)
		_, err = TranscodeV4WALPayload(5, "replication_command", data)
		require.ErrorContains(t, err, "unsupported historical replication command")
	}
}
