func TestReplicationSnapshotRoundTripsStoredImages(t *testing.T) {
	source := fixtureowner.Own(t, fixtureowner.Track(t, storage.NewMemoryEngine(), storage.ErrStorageClosed))
	target := fixtureowner.Own(t, fixtureowner.Track(t, storage.NewMemoryEngine(), storage.ErrStorageClosed))
	created := time.Date(2026, 3, 4, 5, 6, 7, 123456789, time.UTC)
	updated := created.Add(time.Minute)
	node := transportContractNode(created, updated)
	edge := transportContractEdge(created, updated)
	_, err := source.CreateNode(node)
	require.NoError(t, err)
	_, err = source.CreateNode(&storage.Node{ID: edge.EndNode})
	require.NoError(t, err)
	require.NoError(t, source.CreateEdge(edge))
	first, err := NewStorageAdapterWithWAL(source, t.TempDir())
	require.NoError(t, err)
	fixtureowner.Own(t, first)
	second, err := NewStorageAdapterWithWAL(target, t.TempDir())
	require.NoError(t, err)
	fixtureowner.Own(t, second)
	var snapshot bytes.Buffer
	require.NoError(t, first.WriteSnapshot(&snapshot))
	require.NoError(t, second.RestoreSnapshot(bytes.NewReader(snapshot.Bytes())))
	wantNode, err := source.GetNode(node.ID)
	require.NoError(t, err)
	gotNode, err := target.GetNode(node.ID)
	require.NoError(t, err)
	require.Equal(t, wantNode.Properties, gotNode.Properties)
	require.Equal(t, wantNode.NamedEmbeddings, gotNode.NamedEmbeddings)
	require.Equal(t, wantNode.ChunkEmbeddings, gotNode.ChunkEmbeddings)
	require.Equal(t, wantNode.RuntimeMetadata().VisibilitySuppressed, gotNode.RuntimeMetadata().VisibilitySuppressed)
	wantEdge, err := source.GetEdge(edge.ID)
	require.NoError(t, err)
	gotEdge, err := target.GetEdge(edge.ID)
	require.NoError(t, err)
	require.Equal(t, wantEdge.Properties, gotEdge.Properties)
	require.Equal(t, wantEdge.Confidence, gotEdge.Confidence)
	require.Equal(t, wantEdge.VisibilitySuppressed, gotEdge.VisibilitySuppressed)
}

// snapshotPayload uses the same typed payload as the public adapter paths.
type snapshotPayload = storage.ReplicationSnapshot

// transportContractNode builds one stored node carrying every value shape the
// replication transport must survive: int64, int32, homogeneous []int64,
// []float32, bytes, a nested map, time.Time, named and chunked embeddings, and
// the visibility-suppression flag. All values are bounded literals.
func transportContractNode(createdAt, updatedAt time.Time) *storage.Node {
	node := &storage.Node{
		ID:     storage.NodeID("test:contract-node-1"),
		Labels: []string{"Doc", "Chunk"},
		Properties: map[string]any{
			"count":  int64(9007199254740993),
			"small":  int32(2147483647),
			"scores": []int64{7, -2, 3000000000},
			"vector": []float32{0.5, 1.5, -2.5},
			"blob":   []byte{0x00, 0x01, 0xfe, 0xff},
			"nested": map[string]any{"inner": []any{"x", int64(7), true}},
			"when":   createdAt.Add(2 * time.Second),
		},
		CreatedAt:       createdAt,
		UpdatedAt:       updatedAt,
		NamedEmbeddings: map[string][]float32{"title": {0.25, -0.5}, "body": {1}},
		ChunkEmbeddings: [][]float32{{0.125, 0.25}, {-0.75}},
	}
	node.SetRuntimeMetadata(storage.NodeRuntimeMetadata{VisibilitySuppressed: true})
	return node
}

// transportContractEdge builds the stored edge paired with transportContractNode.
func transportContractEdge(createdAt, updatedAt time.Time) *storage.Edge {
	return &storage.Edge{
		ID:        storage.EdgeID("test:contract-edge-1"),
		StartNode: storage.NodeID("test:contract-node-1"),
		EndNode:   storage.NodeID("test:contract-node-2"),
		Type:      "SIMILAR_TO",
		Properties: map[string]any{
			"weight": int64(42),
		},
		CreatedAt:            createdAt.Add(time.Minute),
		UpdatedAt:            updatedAt.Add(-time.Minute),
		Confidence:           0.875,
		AutoGenerated:        true,
		VisibilitySuppressed: true,
	}
}

// historicalGobNode freezes the exported node fields of the previous gob
// transport. It must not track changes to the current runtime Go API.
type historicalGobNode struct {
	Database                   string
	ID                         storage.NodeID
	Labels                     []string
	Properties                 map[string]any
	CreatedAt                  time.Time
	UpdatedAt                  time.Time
	NamedEmbeddings            map[string][]float32
	ChunkEmbeddings            [][]float32
	EmbedMeta                  map[string]any
	EmbeddingsStoredSeparately bool
	VisibilitySuppressed       bool
}

// gobSnapshotBaseline retains the actual historical gob field contract and
// its dynamic-value decoding, independently of the current in-memory Node.
type historicalSnapshot struct {
	WALPosition uint64
	Nodes       []*historicalGobNode
	Edges       []*storage.Edge
}

func historicalGobSnapshotBytes(t *testing.T, fixture snapshotPayload) []byte {
	t.Helper()
	historical := historicalSnapshot{WALPosition: fixture.WALPosition, Edges: fixture.Edges}
	if fixture.Nodes != nil {
		historical.Nodes = make([]*historicalGobNode, len(fixture.Nodes))
	}
	for i, node := range fixture.Nodes {
		if node == nil {
			continue
		}
		metadata := node.RuntimeMetadata()
		historical.Nodes[i] = &historicalGobNode{Database: metadata.Database, ID: node.ID,
			Labels: node.Labels, Properties: node.Properties, CreatedAt: node.CreatedAt, UpdatedAt: node.UpdatedAt,
			NamedEmbeddings: node.NamedEmbeddings, ChunkEmbeddings: node.ChunkEmbeddings, EmbedMeta: node.EmbedMeta,
			EmbeddingsStoredSeparately: metadata.EmbeddingsStoredSeparately, VisibilitySuppressed: metadata.VisibilitySuppressed}
	}
	var encoded bytes.Buffer
	require.NoError(t, gob.NewEncoder(&encoded).Encode(historical))
	return encoded.Bytes()
}

func gobSnapshotBaseline(t *testing.T, fixture snapshotPayload) snapshotPayload {
	t.Helper()
	var decoded historicalSnapshot
	require.NoError(t, gob.NewDecoder(bytes.NewReader(historicalGobSnapshotBytes(t, fixture))).Decode(&decoded))
	baseline := snapshotPayload{WALPosition: decoded.WALPosition, Edges: decoded.Edges}
	if decoded.Nodes != nil {
		baseline.Nodes = make([]*storage.Node, len(decoded.Nodes))
	}
	for i, node := range decoded.Nodes {
		if node == nil {
			continue
		}
		baseline.Nodes[i] = &storage.Node{ID: node.ID, Labels: node.Labels, Properties: node.Properties,
			CreatedAt: node.CreatedAt, UpdatedAt: node.UpdatedAt, NamedEmbeddings: node.NamedEmbeddings,
			ChunkEmbeddings: node.ChunkEmbeddings, EmbedMeta: node.EmbedMeta}
		baseline.Nodes[i].SetRuntimeMetadata(storage.NodeRuntimeMetadata{Database: node.Database,
			EmbeddingsStoredSeparately: node.EmbeddingsStoredSeparately, VisibilitySuppressed: node.VisibilitySuppressed})
	}
	return baseline
}

// singleMessagePackValue reports whether data is exactly one complete
// MessagePack value. The leading value is decoded, then the remaining bytes are
// drained: the whole output must be consumed, so no second value and no
// undecodable remainder followed the first one.
func singleMessagePackValue(data []byte) (ok bool, decodeErr error, trailing int) {
	reader := bytes.NewReader(data)
	decoder := msgpack.NewDecoder(reader)
	var leading any
	if decodeErr := decoder.Decode(&leading); decodeErr != nil {
		return false, decodeErr, 0
	}
	return reader.Len() == 0, nil, reader.Len()
}

// TestMessagePackSingleValueGuardIsSensitive proves the guard used by the
// transport contract test rejects a non-MessagePack encoding that only appears
// to contain one value, and that it rejects a real second value. Gob output
// starts with a two-byte length that MessagePack reads as a fixed integer, so a
// leading-value-only check would pass on gob; the trailing-data check is what
// catches it, and this test pins that behaviour in both directions.
func TestMessagePackSingleValueGuardIsSensitive(t *testing.T) {
	var gobPayload bytes.Buffer
	err := gob.NewEncoder(&gobPayload).Encode(snapshotPayload{
		WALPosition: 42,
		Nodes:       []*storage.Node{transportContractNode(time.Unix(0, 0), time.Unix(0, 1))},
	})
	require.NoError(t, err)

	ok, decodeErr, trailing := singleMessagePackValue(gobPayload.Bytes())
	require.False(t, ok, "gob output must not satisfy the single MessagePack value guard")
	require.NoError(t, decodeErr, "gob output coincidentally decodes as a leading MessagePack integer")
	require.Positive(t, trailing, "gob output must leave trailing bytes after the leading MessagePack value")

	oneValue, err := msgpack.Marshal(map[string]any{"WALPosition": uint64(42), "Nodes": []any{}, "Edges": []any{}})
	require.NoError(t, err)
	ok, decodeErr, trailing = singleMessagePackValue(oneValue)
	require.True(t, ok, "a single MessagePack value must satisfy the guard")
	require.NoError(t, decodeErr)
	require.Zero(t, trailing)

	ok, decodeErr, trailing = singleMessagePackValue(append(append([]byte{}, oneValue...), 0xc0))
	require.False(t, ok, "a second MessagePack value must be rejected as trailing data")
	require.NoError(t, decodeErr)
	require.Equal(t, 1, trailing)
}

// TestCommandPayloadEncodesOneMessagePackValuePreservingGobDecodedSnapshot
// covers the replication transport/snapshot boundary.
//
// It demands two things of storage.EncodeCommandPayload and
// storage.DecodeCommandPayload: the encoding is exactly one complete
// MessagePack value with no trailing bytes, and decoding reproduces the
// snapshot values the previous gob codec produced.
func TestCommandPayloadEncodesOneMessagePackValuePreservingGobDecodedSnapshot(t *testing.T) {
	createdAt := time.Date(2026, 3, 4, 5, 6, 7, 123456789, time.UTC)
	updatedAt := time.Date(2026, 3, 4, 5, 6, 8, 987654321, time.UTC)

	fixture := snapshotPayload{
		WALPosition: 42,
		Nodes:       []*storage.Node{transportContractNode(createdAt, updatedAt)},
		Edges:       []*storage.Edge{transportContractEdge(createdAt, updatedAt)},
	}
	expected := gobSnapshotBaseline(t, fixture)

	data, err := storage.EncodeCommandPayload(fixture)
	require.NoError(t, err, "EncodeCommandPayload must encode the snapshot payload")

	ok, decodeErr, trailing := singleMessagePackValue(data)
	require.NoError(t, decodeErr, "EncodeCommandPayload output must decode as MessagePack")
	require.Zero(t, trailing, "EncodeCommandPayload wrote %d trailing byte(s) after one MessagePack value", trailing)
	require.True(t, ok, "EncodeCommandPayload output must be exactly one MessagePack value")

	var decoded snapshotPayload
	require.NoError(t, storage.DecodeCommandPayload(data, &decoded), "DecodeCommandPayload must decode the encoded snapshot")

	// Node values.
	require.Len(t, decoded.Nodes, len(expected.Nodes), "decoded node count must match the gob baseline")
	gotNode := decoded.Nodes[0]
	wantNode := expected.Nodes[0]
	require.Equal(t, wantNode.ID, gotNode.ID)
	require.Equal(t, wantNode.Labels, gotNode.Labels)
	require.True(t, wantNode.CreatedAt.Equal(gotNode.CreatedAt), "node CreatedAt: want %v, got %v", wantNode.CreatedAt, gotNode.CreatedAt)
	require.True(t, wantNode.UpdatedAt.Equal(gotNode.UpdatedAt), "node UpdatedAt: want %v, got %v", wantNode.UpdatedAt, gotNode.UpdatedAt)
	require.Equal(t, wantNode.NamedEmbeddings, gotNode.NamedEmbeddings, "named embeddings must survive the transport")
	require.Equal(t, wantNode.ChunkEmbeddings, gotNode.ChunkEmbeddings, "chunk embeddings must survive the transport")
	require.Equal(t, wantNode.RuntimeMetadata().VisibilitySuppressed, gotNode.RuntimeMetadata().VisibilitySuppressed, "node visibility suppression must survive the transport")
	require.Equal(t, wantNode.RuntimeMetadata().EmbeddingsStoredSeparately, gotNode.RuntimeMetadata().EmbeddingsStoredSeparately)
	require.Equal(t, wantNode.EmbedMeta, gotNode.EmbedMeta)
	require.Equal(t, wantNode.Properties, gotNode.Properties, "property values must match the gob-decoded baseline")
	require.Len(t, gotNode.Properties, len(wantNode.Properties))

	// Interface-typed properties: compare dynamic Go types, not only values.
	for key, want := range wantNode.Properties {
		got, ok := gotNode.Properties[key]
		require.True(t, ok, "property %q missing after decode", key)
		require.Equalf(t, want, got, "property %q value", key)
		require.Equalf(t, dynamicTypeOf(want), dynamicTypeOf(got), "property %q dynamic type", key)
	}
	nestedWant, ok := wantNode.Properties["nested"].(map[string]any)
	require.True(t, ok, "baseline nested property must decode as map[string]any")
	nestedGot, ok := gotNode.Properties["nested"].(map[string]any)
	require.True(t, ok, "nested property must decode as map[string]any")
	innerWant, ok := nestedWant["inner"].([]any)
	require.True(t, ok, "baseline nested inner list must decode as []any")
	innerGot, ok := nestedGot["inner"].([]any)
	require.True(t, ok, "nested inner list must decode as []any")
	require.Len(t, innerGot, len(innerWant))
	for i := range innerWant {
		require.Equal(t, innerWant[i], innerGot[i], "nested inner[%d] value", i)
		require.Equal(t, dynamicTypeOf(innerWant[i]), dynamicTypeOf(innerGot[i]), "nested inner[%d] dynamic type", i)
	}

	// Edge values.
	require.Len(t, decoded.Edges, len(expected.Edges), "decoded edge count must match the gob baseline")
	gotEdge := decoded.Edges[0]
	wantEdge := expected.Edges[0]
	require.Equal(t, wantEdge.ID, gotEdge.ID)
	require.Equal(t, wantEdge.StartNode, gotEdge.StartNode)
	require.Equal(t, wantEdge.EndNode, gotEdge.EndNode)
	require.Equal(t, wantEdge.Type, gotEdge.Type)
	require.True(t, wantEdge.CreatedAt.Equal(gotEdge.CreatedAt), "edge CreatedAt: want %v, got %v", wantEdge.CreatedAt, gotEdge.CreatedAt)
	require.True(t, wantEdge.UpdatedAt.Equal(gotEdge.UpdatedAt), "edge UpdatedAt: want %v, got %v", wantEdge.UpdatedAt, gotEdge.UpdatedAt)
	require.Equal(t, wantEdge.Confidence, gotEdge.Confidence, "edge confidence must survive the transport")
	require.Equal(t, wantEdge.AutoGenerated, gotEdge.AutoGenerated)
	require.Equal(t, wantEdge.VisibilitySuppressed, gotEdge.VisibilitySuppressed, "edge visibility suppression must survive the transport")
	require.Equal(t, wantEdge.Properties, gotEdge.Properties)
	require.Len(t, gotEdge.Properties, len(wantEdge.Properties))
	for key, want := range wantEdge.Properties {
		got, ok := gotEdge.Properties[key]
		require.True(t, ok, "edge property %q missing after decode", key)
		require.Equalf(t, want, got, "edge property %q value", key)
		require.Equalf(t, dynamicTypeOf(want), dynamicTypeOf(got), "edge property %q dynamic type", key)
	}

	require.Equal(t, expected.WALPosition, decoded.WALPosition, "WAL position must survive the transport")
}

// dynamicTypeOf reports the dynamic Go type of an interface value for diagnostics.
func dynamicTypeOf(v any) string {
	if v == nil {
		return "<nil>"
	}
	return fmt.Sprintf("%T", v)
}
