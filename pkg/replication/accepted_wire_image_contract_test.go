// NOR-288/NOR-303 accepted wire image regression coverage.
//
// The semantic transaction codec and the native storage bodies have their own
// focused owners. Neither crosses the boundary this file proves: a leader
// applies one encoded accepted node+relationship transaction through
// StorageAdapter.ApplyCommand, the adapter's own serialized replication WAL
// record is read back, and that record is applied to a second, fresh adapter
// and native engine — the path a peer takes. The complete user/stored image must
// arrive unchanged: unset, Unix-epoch and one-nanosecond timestamp boundaries
// per entity and per field, plus node embedding metadata.
//
// This proves the replication-adapter hop plus serialized recovery, not a
// distributed cluster rollout.
package replication

import (
	"strings"
	"testing"
	"time"

	"github.com/orneryd/nornicdb/pkg/storage"
	"github.com/stretchr/testify/require"
)

const (
	wireImageNamespace = "test"
	wireImageLogicalID = "accepted-wire-image"
	wireImageNodeID    = storage.NodeID("test:accepted-wire-node")
	wireImageEdgeID    = storage.EdgeID("test:accepted-wire-edge")
)

// wireImageNormal is a distinct ordinary instant. A boundary value in one
// timestamp field must leave the other field at this instant, so a default
// shared by both fields is caught instead of hidden.
var wireImageNormal = time.Date(2024, time.March, 4, 5, 6, 7, 123456789, time.UTC)

// wireImageStored is what both sides of one hop stored.
type wireImageStored struct {
	leaderNode, peerNode *storage.Node
	leaderEdge, peerEdge *storage.Edge
}

// storedNodeFieldsOf removes only process-local embedding identity from a
// copy. Every stored field and public runtime metadata remains comparable.
func storedNodeFieldsOf(node *storage.Node) storage.Node {
	image := *node
	image.CopyEmbeddingIdentityFrom(nil)
	return image
}

// storedEdgeFields is the complete stored contract of a replicated
// relationship. Edge.Database is not a body field: a stored read derives it
// from the key, so comparing it would compare engine bookkeeping.
type storedEdgeFields struct {
	ID                   storage.EdgeID
	StartNode            storage.NodeID
	EndNode              storage.NodeID
	Type                 string
	Properties           map[string]any
	CreatedAt            time.Time
	UpdatedAt            time.Time
	Confidence           float64
	AutoGenerated        bool
	VisibilitySuppressed bool
}

func storedEdgeFieldsOf(edge *storage.Edge) storedEdgeFields {
	return storedEdgeFields{
		ID:                   edge.ID,
		StartNode:            edge.StartNode,
		EndNode:              edge.EndNode,
		Type:                 edge.Type,
		Properties:           edge.Properties,
		CreatedAt:            edge.CreatedAt,
		UpdatedAt:            edge.UpdatedAt,
		Confidence:           edge.Confidence,
		AutoGenerated:        edge.AutoGenerated,
		VisibilitySuppressed: edge.VisibilitySuppressed,
	}
}

// wireStoredView is the ID a namespaced stored read reports for a transaction
// ID: the fixture engine's user view strips the database prefix exactly as
// production reads do, so the same entity carries a namespace-relative ID.
func wireStoredView(id string) string {
	return strings.TrimPrefix(id, wireImageNamespace+":")
}

func newWireImageNode(createdAt, updatedAt time.Time) *storage.Node {
	return &storage.Node{
		ID:     wireImageNodeID,
		Labels: []string{"Doc", "Person"},
		Properties: map[string]any{
			"text":   "alpha",
			"score":  0.75,
			"active": true,
			"tags":   []string{"one", "two"},
		},
		CreatedAt: createdAt,
		UpdatedAt: updatedAt,
	}
}

func newWireImageEdge(createdAt, updatedAt time.Time) *storage.Edge {
	return &storage.Edge{
		ID:            wireImageEdgeID,
		StartNode:     wireImageNodeID,
		EndNode:       wireImageNodeID,
		Type:          "RELATES_TO",
		Properties:    map[string]any{"since": "2024-03-04", "weight": 0.5, "confirmed": true},
		CreatedAt:     createdAt,
		UpdatedAt:     updatedAt,
		Confidence:    0.75,
		AutoGenerated: true,
	}
}

// applyThroughWire reproduces one hop: leader application of the encoded
// accepted transaction, the leader's own serialized WAL record, then
// application of that record by a second fresh adapter and native engine.
func applyThroughWire(t *testing.T, node *storage.Node, edge *storage.Edge) *wireImageStored {
	t.Helper()
	leader := setupTestAdapter(t)
	peer := setupTestAdapter(t)

	payload, err := storage.EncodeEntityTransaction(storage.EntityTransactionRequest{
		Namespace: wireImageNamespace,
		LogicalID: wireImageLogicalID,
		Operations: []storage.Operation{
			{Type: storage.OpCreateNode, Node: node},
			{Type: storage.OpCreateEdge, Edge: edge},
		},
	})
	require.NoError(t, err)

	command := &Command{
		Type:      CmdCommitTransaction,
		Data:      payload,
		Timestamp: time.Unix(1700000000, 123456789).UTC(),
		RequestID: wireImageLogicalID,
	}
	publication, err := leader.adapter.ApplyCommand(t.Context(), command, WALPublished)
	require.NoError(t, err, "the leader must apply the accepted transaction")
	require.NotZero(t, publication.Position, "WALPublished reports the record's own physical position")
	// Make the durable bytes a peer reads current before reading them.
	require.NoError(t, leader.adapter.FlushWAL())

	entries, err := leader.adapter.GetWALEntries(0, 10)
	require.NoError(t, err)
	require.Len(t, entries, 1, "one accepted transaction is one replication WAL record")
	record := entries[0]
	require.Equal(t, publication.Position, record.Position)
	require.Equal(t, command.Timestamp.UnixNano(), record.Timestamp)
	require.Equal(t, CmdCommitTransaction, record.Command.Type)
	require.Equal(t, command.RequestID, record.Command.RequestID)
	require.Equal(t, payload, record.Command.Data, "the serialized record carries the exact accepted semantic image")
	require.NotSame(t, command, record.Command, "the peer path must read the serialized record, not the leader's in-memory append")
	require.Nil(t, record.Command.accepted, "local accepted authority never travels on the WAL record; the peer materializes the payload itself")

	// The peer's existing nonwaiting native-result contract applies the decoded
	// accepted transaction to its own fresh engine.
	require.NoError(t, applyQueued(t, peer.adapter, record.Command), "the peer must apply the recovered record")

	requireWireCounts(t, "leader", leader.adapter.Engine())
	requireWireCounts(t, "peer", peer.adapter.Engine())
	return &wireImageStored{
		leaderNode: requireWireStoredNode(t, leader.adapter.Engine()),
		peerNode:   requireWireStoredNode(t, peer.adapter.Engine()),
		leaderEdge: requireWireStoredEdge(t, leader.adapter.Engine()),
		peerEdge:   requireWireStoredEdge(t, peer.adapter.Engine()),
	}
}

func requireWireCounts(t *testing.T, side string, engine storage.Engine) {
	t.Helper()
	nodes, err := engine.NodeCount(t.Context())
	require.NoError(t, err)
	require.EqualValues(t, 1, nodes, "%s stores exactly the one replicated node", side)
	edges, err := engine.EdgeCount(t.Context())
	require.NoError(t, err)
	require.EqualValues(t, 1, edges, "%s stores exactly the one replicated relationship", side)
}

func requireWireStoredNode(t *testing.T, engine storage.Engine) *storage.Node {
	t.Helper()
	node, err := storage.GetStoredNode(t.Context(), engine, wireImageNodeID)
	require.NoError(t, err, "the replicated node must be stored")
	return node
}

func requireWireStoredEdge(t *testing.T, engine storage.Engine) *storage.Edge {
	t.Helper()
	edge, err := storage.GetStoredEdge(t.Context(), engine, wireImageEdgeID)
	require.NoError(t, err, "the replicated relationship must be stored")
	return edge
}

// requireWireTime asserts one stored timestamp against the requested instant.
// Unset is a distinct value, not a missing instant to be defaulted.
func requireWireTime(t *testing.T, field string, want, got time.Time) {
	t.Helper()
	require.Equal(t, want.IsZero(), got.IsZero(),
		"%s: an unset timestamp must stay unset and a set timestamp must stay set (want %s, got %s)",
		field, wireInstant(want), wireInstant(got))
	require.True(t, want.Equal(got), "%s: want instant %s, got %s", field, wireInstant(want), wireInstant(got))
}

func wireInstant(at time.Time) string {
	if at.IsZero() {
		return "unset"
	}
	return at.UTC().Format(time.RFC3339Nano)
}

// requireWireNodeStored asserts the leader and the peer each stored want's
// complete node image.
func requireWireNodeStored(t *testing.T, stored *wireImageStored, want *storage.Node) {
	t.Helper()
	for _, side := range []struct {
		name string
		node *storage.Node
	}{
		{"leader", stored.leaderNode},
		{"peer", stored.peerNode},
	} {
		requireWireTime(t, side.name+" node CreatedAt", want.CreatedAt, side.node.CreatedAt)
		requireWireTime(t, side.name+" node UpdatedAt", want.UpdatedAt, side.node.UpdatedAt)
		require.Equal(t, wireStoredView(string(want.ID)), string(side.node.ID), "%s stores the replicated node", side.name)
		require.Equal(t, want.Labels, side.node.Labels)
		require.Equal(t, want.Properties, side.node.Properties)
		require.Equal(t, want.EmbedMeta, side.node.EmbedMeta,
			"%s node EmbedMeta must arrive exactly: nil stays nil, empty stays empty", side.name)
		require.False(t, side.node.RuntimeMetadata().VisibilitySuppressed)
	}
	require.Equal(t, storedNodeFieldsOf(stored.leaderNode), storedNodeFieldsOf(stored.peerNode),
		"the peer stores the leader's complete node image")
}

// requireWireEdgeStored asserts the leader and the peer each stored want's
// complete relationship image.
func requireWireEdgeStored(t *testing.T, stored *wireImageStored, want *storage.Edge) {
	t.Helper()
	for _, side := range []struct {
		name string
		edge *storage.Edge
	}{
		{"leader", stored.leaderEdge},
		{"peer", stored.peerEdge},
	} {
		requireWireTime(t, side.name+" relationship CreatedAt", want.CreatedAt, side.edge.CreatedAt)
		requireWireTime(t, side.name+" relationship UpdatedAt", want.UpdatedAt, side.edge.UpdatedAt)
		require.Equal(t, wireStoredView(string(want.ID)), string(side.edge.ID), "%s stores the replicated relationship", side.name)
		require.Equal(t, wireStoredView(string(want.StartNode)), string(side.edge.StartNode))
		require.Equal(t, wireStoredView(string(want.EndNode)), string(side.edge.EndNode))
		require.Equal(t, want.Type, side.edge.Type)
		require.Equal(t, want.Properties, side.edge.Properties)
		require.Equal(t, want.Confidence, side.edge.Confidence)
		require.Equal(t, want.AutoGenerated, side.edge.AutoGenerated)
		require.False(t, side.edge.VisibilitySuppressed)
	}
	require.Equal(t, storedEdgeFieldsOf(stored.leaderEdge), storedEdgeFieldsOf(stored.peerEdge),
		"the peer stores the leader's complete relationship image")
}

// TestAcceptedWireImagePreservesNodeTimestamps asserts each node timestamp
// distinction independently through the real adapter hop: while one field
// carries the boundary value, the other stays at a distinct ordinary instant.
func TestAcceptedWireImagePreservesNodeTimestamps(t *testing.T) {
	boundaries := []struct {
		name string
		at   time.Time
	}{
		{"unset", time.Time{}},
		{"epoch", time.Unix(0, 0)},
		{"one nanosecond before epoch", time.Unix(0, -1)},
		{"one nanosecond after epoch", time.Unix(0, 1)},
	}
	for _, boundary := range boundaries {
		t.Run(boundary.name+" on created at", func(t *testing.T) {
			node := newWireImageNode(boundary.at, wireImageNormal)
			stored := applyThroughWire(t, node, newWireImageEdge(wireImageNormal, wireImageNormal))
			requireWireNodeStored(t, stored, node)
		})
		t.Run(boundary.name+" on updated at", func(t *testing.T) {
			node := newWireImageNode(wireImageNormal, boundary.at)
			stored := applyThroughWire(t, node, newWireImageEdge(wireImageNormal, wireImageNormal))
			requireWireNodeStored(t, stored, node)
		})
	}
}

