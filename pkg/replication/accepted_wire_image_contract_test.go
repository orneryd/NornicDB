// TestAcceptedWireImagePreservesNodeEmbedMeta asserts node embedding metadata
// arrives exactly: absent, present-but-empty and populated metadata stay
// distinct, without normalizing nil to empty on either side.
func TestAcceptedWireImagePreservesNodeEmbedMeta(t *testing.T) {
	cases := []struct {
		name    string
		meta    map[string]any
		wantNil bool
		wantLen int
	}{
		{name: "nil metadata", meta: nil, wantNil: true},
		{name: "empty metadata", meta: map[string]any{}},
		{
			name: "populated metadata",
			meta: map[string]any{
				"embedding_model": "accepted-wire-model",
				"chunk_count":     int64(2),
				"has_chunks":      true,
				"dimensions":      0.75,
				"chunk_texts":     []any{"alpha", "beta"},
				"source":          map[string]any{"kind": "properties"},
			},
			wantLen: 6,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			node := newWireImageNode(wireImageNormal, wireImageNormal)
			node.EmbedMeta = tc.meta
			stored := applyThroughWire(t, node, newWireImageEdge(wireImageNormal, wireImageNormal))
			for _, side := range []struct {
				name string
				node *storage.Node
			}{
				{"leader", stored.leaderNode},
				{"peer", stored.peerNode},
			} {
				if tc.wantNil {
					require.Nil(t, side.node.EmbedMeta, "%s must store absent node metadata as absent", side.name)
				} else {
					require.NotNil(t, side.node.EmbedMeta, "%s must store present node metadata as present", side.name)
					require.Len(t, side.node.EmbedMeta, tc.wantLen)
				}
				require.Equal(t, tc.meta, side.node.EmbedMeta, "%s must store the exact node metadata", side.name)
			}
			require.Equal(t, storedNodeFieldsOf(stored.leaderNode), storedNodeFieldsOf(stored.peerNode),
				"the peer stores the leader's complete node image")
		})
	}
}
