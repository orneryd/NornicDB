func gapQ07Vector(r *rand.Rand) []float64 {
	v := make([]float64, gapQ07Dims)
	for i := range v {
		v[i] = float64(int(r.Float64()*10000)) / 10000
	}
	return v
}

func gapQ07Text(r *rand.Rand, n int) string {
	parts := make([]string, n)
	for i := range parts {
		parts[i] = gapQ07Words[r.Intn(len(gapQ07Words))]
	}
	return strings.Join(parts, " ")
}

var gapQ07Embeddings bool

func gapQ07Config() *nornicdb.Config {
	c := nornicdb.DefaultConfig()
	c.Database.AsyncWritesEnabled = false
	c.Database.WALAutoCompactionEnabled = false
	c.Database.PersistSearchIndexes = false
	c.Memory.DecayEnabled = false
	c.Memory.EmbeddingEnabled = gapQ07Embeddings
	c.Memory.AutoLinksEnabled = false
	c.Memory.EmbeddingDimensions = gapQ07Dims
	return c
}

func gapQ07Env(t *testing.T) {
	t.Setenv("NORNICDB_GPU_BACKEND", "cpu")
	t.Setenv("NORNICDB_HNSW_BUILD_GPU_ENABLED", "false")
	t.Setenv("NORNICDB_EMBEDDING_ENABLED", fmt.Sprint(gapQ07Embeddings))
	t.Setenv("NORNICDB_AUTO_LINKS_ENABLED", "false")
	t.Setenv("NORNICDB_DECAY_ENABLED", "false")
}

// gapQ07Seed writes the store and closes it.
func gapQ07Seed(t *testing.T, dir string) {
	t.Helper()
	ctx := context.Background()
	db, err := nornicdb.Open(dir, gapQ07Config())
	if err != nil {
		t.Fatalf("seed Open: %v", err)
	}
	for _, q := range []string{
		"CREATE FULLTEXT INDEX doc_text IF NOT EXISTS FOR (n:Searchable) ON EACH [n.text]",
		"CREATE VECTOR INDEX doc_vec IF NOT EXISTS FOR (n:Searchable) ON (n.embedding) OPTIONS {indexConfig: {`vector.dimensions`: 64, `vector.similarity_function`: 'cosine'}}",
		"CREATE INDEX searchable_id IF NOT EXISTS FOR (s:Searchable) ON (s.id)",
	} {
		if _, err := db.ExecuteCypher(ctx, q, nil); err != nil {
			_ = db.Close()
			t.Fatalf("seed schema %q: %v", q, err)
		}
	}
	r := rand.New(rand.NewSource(11))
	for start := 0; start < gapQ07Nodes; start += gapQ07Batch {
		rows := make([]any, 0, gapQ07Batch)
		for i := start; i < start+gapQ07Batch && i < gapQ07Nodes; i++ {
			text := gapQ07Text(r, gapQ07TextWords) // the text is drawn before the vector
			rows = append(rows, map[string]any{"id": fmt.Sprintf("s%d", i), "text": text, "e": gapQ07Vector(r)})
		}
		if _, err := db.ExecuteCypher(ctx, "UNWIND $rows AS r CREATE (s:Searchable {id: r.id, text: r.text, current: true, embedding: r.e})", map[string]any{"rows": rows}); err != nil {
			_ = db.Close()
			t.Fatalf("seed rows from %d: %v", start, err)
		}
	}
	if err := db.Close(); err != nil {
		t.Fatalf("seed Close: %v", err)
	}
}

type gapQ07Outcome struct {
	variant         string
	sawBuilding     bool
	writeLatency    time.Duration
	writeErr        error
	writeTimedOut   bool
	writeSentToDone time.Duration // write sent -> build done
	buildEndedFirst bool          // the build ended before the write returned
	duringSearches  []time.Duration
	afterSearches   []time.Duration
	found           any
	stackRefresh    bool // a goroutine was in readLockOrQueue while the write was in flight
	stackMVCCFloor  bool // a goroutine was in recoverNamespaceMVCCFloor while the write was in flight
	stackSample     string
	dimsFixed       string
}

func gapQ07Ms(ds []time.Duration) []string {
	out := make([]string, len(ds))
	for i, d := range ds {
		out[i] = fmt.Sprintf("%.1f", float64(d.Microseconds())/1000)
	}
	return out
}

// gapQ07DimsFixed reads search.Service.vectorDimensionsFixed (atomic.Bool).
func gapQ07DimsFixed(svc *search.Service) string {
	f := reflect.ValueOf(svc).Elem().FieldByName("vectorDimensionsFixed")
	if !f.IsValid() {
		return "unknown(no field)"
	}
	v := f.FieldByName("v")
	if !v.IsValid() {
		return "unknown(no v)"
	}
	if v.Kind() == reflect.Struct {
		v = v.FieldByName("v")
	}
	if !v.IsValid() {
		return "unknown"
	}
	return fmt.Sprint(v.Uint() != 0)
}

func gapQ07Median(ds []time.Duration) time.Duration {
	if len(ds) == 0 {
		return 0
	}
	c := append([]time.Duration(nil), ds...)
	sort.Slice(c, func(i, j int) bool { return c[i] < c[j] })
	return c[len(c)/2]
}

func (o gapQ07Outcome) String() string {
	return fmt.Sprintf("dims_fixed=%s searches_during_ms=%v searches_after_ms=%v after_median=%v ", o.dimsFixed, gapQ07Ms(o.duringSearches), gapQ07Ms(o.afterSearches), gapQ07Median(o.afterSearches)) + fmt.Sprintf("variant=%s saw_building=%v write_latency=%v write_err=%v write_timed_out=%v build_done_after_send=%v build_ended_before_write_returned=%v searches_during_build=%d median=%v searches_after=%v found_after=%v stack_readLockOrQueue=%v stack_recoverNamespaceMVCCFloor=%v",
		o.variant, o.sawBuilding, o.writeLatency, o.writeErr, o.writeTimedOut, o.writeSentToDone, o.buildEndedFirst, len(o.duringSearches), gapQ07Median(o.duringSearches), o.afterSearches, o.found, o.stackRefresh, o.stackMVCCFloor)
}

// gapQ07Restart opens the stopped store, waits until the start-up build is
// seen running, sends the write at once, times vector searches until the
// build is done and three after it, and samples goroutine stacks while the
// write is in flight.
func gapQ07Restart(t *testing.T, dir, variant string, softLimit bool) gapQ07Outcome {
	t.Helper()
	ctx := context.Background()
	out := gapQ07Outcome{variant: variant}
	if softLimit {
		prev := debug.SetMemoryLimit(-1)
		runtime.GC()
		var ms runtime.MemStats
		runtime.ReadMemStats(&ms)
		debug.SetMemoryLimit(int64(ms.HeapAlloc))
		defer debug.SetMemoryLimit(prev)
	}
	db, err := nornicdb.Open(dir, gapQ07Config())
	if err != nil {
		t.Fatalf("%s: Open: %v", variant, err)
	}
	defer func() { _ = db.Close() }()
	if _, err := db.ExecuteCypher(ctx, "RETURN 1 AS one", nil); err != nil {
		t.Fatalf("%s: RETURN 1: %v", variant, err)
	}
	svc, err := db.GetOrCreateSearchService("nornic", db.GetStorage())
	if err != nil {
		t.Fatalf("%s: GetOrCreateSearchService: %v", variant, err)
	}
	out.dimsFixed = gapQ07DimsFixed(svc)
	deadline := time.Now().Add(60 * time.Second)
	for time.Now().Before(deadline) {
		if svc.BuildInProgress() {
			out.sawBuilding = true
			break
		}
		if svc.IsReady() {
			break
		}
		time.Sleep(2 * time.Millisecond)
	}

	r := rand.New(rand.NewSource(7))
	writeVec := gapQ07Vector(r)
	type writeResult struct {
		err     error
		elapsed time.Duration
		at      time.Time
	}
	writeDone := make(chan writeResult, 1)
	sent := time.Now()
	go func() {
		wctx, cancel := context.WithTimeout(ctx, gapQ07WriteTimeout)
		defer cancel()
		start := time.Now()
		_, err := db.ExecuteCypher(wctx, "CREATE (:Searchable {id: 'during-build', text: 'newly written', embedding: $v})", map[string]any{"v": writeVec})
		writeDone <- writeResult{err: err, elapsed: time.Since(start), at: time.Now()}
	}()

	buildDone := make(chan time.Time, 1)
	go func() {
		for {
			if svc.IsReady() && !svc.BuildInProgress() {
				buildDone <- time.Now()
				return
			}
			if time.Since(sent) > gapQ07WriteTimeout+time.Minute {
				close(buildDone)
				return
			}
			time.Sleep(10 * time.Millisecond)
		}
	}()

	sampleStacks := func() {
		buf := make([]byte, 16<<20)
		n := runtime.Stack(buf, true)
		s := string(buf[:n])
		if strings.Contains(s, "readLockOrQueue") {
			out.stackRefresh = true
			if out.stackSample == "" {
				for _, g := range strings.Split(s, "\n\n") {
					if strings.Contains(g, "readLockOrQueue") {
						out.stackSample = g
						break
					}
				}
			}
		}
		if strings.Contains(s, "recoverNamespaceMVCCFloor") {
			out.stackMVCCFloor = true
		}
	}

	var wr *writeResult
	var buildEnd time.Time
	buildEndKnown := false
	query := "CALL db.index.vector.queryNodes('doc_vec', 300, $v) YIELD node, score RETURN node.id AS id, score"
	lastSample := time.Now()
	bd := (<-chan time.Time)(buildDone)
	for wr == nil || !buildEndKnown {
		select {
		case res := <-writeDone:
			wr = &res
			continue
		case at, ok := <-bd:
			if ok {
				buildEnd = at
			}
			buildEndKnown = true
			bd = nil
			continue
		default:
		}
		if wr == nil && time.Since(lastSample) >= 500*time.Millisecond {
			sampleStacks()
			lastSample = time.Now()
		}
		if !buildEndKnown {
			qctx, cancel := context.WithTimeout(ctx, 2*time.Minute)
			start := time.Now()
			_, qerr := db.ExecuteCypher(qctx, query, map[string]any{"v": gapQ07Vector(r)})
			cancel()
			if qerr == nil {
				out.duringSearches = append(out.duringSearches, time.Since(start))
			}
		} else {
			time.Sleep(10 * time.Millisecond)
		}
	}
	out.writeErr, out.writeLatency = wr.err, wr.elapsed
	out.writeTimedOut = wr.err != nil && wr.elapsed >= gapQ07WriteTimeout-time.Second
	if !buildEnd.IsZero() {
		out.writeSentToDone = buildEnd.Sub(sent)
		out.buildEndedFirst = !buildEnd.After(wr.at.Add(200 * time.Millisecond))
	}
	for i := 0; i < 20; i++ {
		start := time.Now()
		if _, err := db.ExecuteCypher(ctx, query, map[string]any{"v": gapQ07Vector(r)}); err == nil {
			out.afterSearches = append(out.afterSearches, time.Since(start))
		}
	}
	if res, err := db.ExecuteCypher(ctx, "MATCH (n:Searchable {id: 'during-build'}) RETURN count(n)", nil); err == nil && len(res.Rows) > 0 && len(res.Rows[0]) > 0 {
		out.found = res.Rows[0][0]
	}
	return out
}

// gapQ07Waited: the write waited for the build.
func gapQ07Waited(o gapQ07Outcome) bool {
	return o.writeTimedOut || (o.writeLatency >= gapQ07WaitThreshold && o.buildEndedFirst)
}

func TestGapQ07EmbeddingsOnBuildWait(t *testing.T) {
	for _, emb := range []bool{false, true} {
		gapQ07Embeddings = emb
		gapQ07Env(t)
		dir := filepath.Join(t.TempDir(), "data")
		gapQ07Seed(t, dir)
		for _, v := range []struct {
			name      string
			softLimit bool
		}{{"plain-process", false}, {"soft-memory-limit-at-live-heap", true}} {
			name := fmt.Sprintf("embeddings=%t/%s", emb, v.name)
			o := gapQ07Restart(t, dir, name, v.softLimit)
			t.Logf("GAPQ07 waited_for_build=%t %s", gapQ07Waited(o), o)
			if o.stackSample != "" {
				t.Logf("GAPQ07 %s stack in readLockOrQueue: %s", name, o.stackSample)
			}
		}
	}
	gapQ07Embeddings = false
}
