type inferenceContextEdgeEngine struct {
	storage.Engine
	entered chan context.Context
	release <-chan struct{}
}

func (e *inferenceContextEdgeEngine) CreateEdge(ctx context.Context, _ *storage.Edge) error {
	e.entered <- ctx
	<-e.release
	return nil
}

type staticTestEmbedder struct {
	dims int
}

var _ embed.Embedder = (*staticTestEmbedder)(nil)

func (e *staticTestEmbedder) Embed(ctx context.Context, text string) ([]float32, error) {
	_ = ctx
	vec := make([]float32, e.dims)
	if len(vec) > 0 {
		vec[0] = float32(len(text))
	}
	if len(vec) > 1 {
		vec[1] = 1
	}
	return vec, nil
}

func (e *staticTestEmbedder) EmbedBatch(ctx context.Context, texts []string) ([][]float32, error) {
	_ = ctx
	out := make([][]float32, len(texts))
	for i, t := range texts {
		vec, _ := e.Embed(ctx, t)
		out[i] = vec
	}
	return out, nil
}

