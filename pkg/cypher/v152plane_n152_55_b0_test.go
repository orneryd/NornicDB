package cypher

// NOR-170 reproduction and visibility controls.
//
// The maintained Neo4j migration scripts
// (scripts/migration/neo4j/migrate.go, migrate.py, migrate.mjs) all emit the
// same two batches, and every implementation leaves the documented
// label-promotion pass to the operator. These tests drive those exact
// statements and the documented promotion statement through the public
// Execute path under both parser configurations.
//
// The completed-workflow tests assert the documented contract (source labels,
// properties, relationship endpoints and idempotent rerun). They currently
// fail; that failure is the reproducible defect, not a regression introduced
// by this file. The control tests pin the current intermediate state and the
// genuine system-node visibility controls that a correction must preserve.

import (
	"context"
	"sort"
	"testing"

	"github.com/orneryd/nornicdb/pkg/config"
	"github.com/orneryd/nornicdb/pkg/storage"
	"github.com/stretchr/testify/require"
)

// Exact node batch from scripts/migration/neo4j/migrate.go (nodeUpsertCypher),
// migrate.py (NODE_UPSERT_CYPHER) and migrate.mjs (NODE_UPSERT_CYPHER).
const nor170NodeUpsertCypher = "UNWIND $rows AS row\n" +
	"MERGE (n:_Migrated {_neo4j_id: row.id})\n" +
	"SET n += row.props\n" +
	"SET n._neo4j_labels = row.labels\n"

// Exact edge batch generated by edgeCreateCypher (Go/JS) and
// edge_create_cypher (Python) for relationship type KNOWS.
const nor170EdgeCreateCypher = "UNWIND $rows AS row " +
	"MATCH (a:_Migrated {_neo4j_id: row.startId}) " +
	"MATCH (b:_Migrated {_neo4j_id: row.endId}) " +
	"CREATE (a)-[:`KNOWS` {_neo4j_id: row.id}]->(b)"

// Exact edge-property batch generated by edgePropsCypher (Go/JS) and
// edge_props_cypher (Python).
const nor170EdgePropsCypher = "UNWIND $rows AS row " +
	"MATCH (a:_Migrated {_neo4j_id: row.startId})-[r:`KNOWS` " +
	"{_neo4j_id: row.id}]->(b:_Migrated {_neo4j_id: row.endId}) " +
	"SET r += row.props"

// Documented label promotion (docs/skills/neo4j-migration.skill.md and
// scripts/migration/neo4j/README.md): one statement per source label.
func nor170Promotion(label string) string {
	return "MATCH (n:_Migrated)\n" +
		"WHERE '" + label + "' IN n._neo4j_labels\n" +
		"SET n:" + label + "\n" +
		"REMOVE n:_Migrated\n" +
		"REMOVE n._neo4j_labels"
}

// nor170EdgeCreate builds the same generated edge statement over a bridge
// label. It is used only as a control that isolates the underscore-label
// visibility decision from the shape of the generated statement.
func nor170EdgeCreate(label string) string {
	return "UNWIND $rows AS row " +
		"MATCH (a:" + label + " {_neo4j_id: row.startId}) " +
		"MATCH (b:" + label + " {_neo4j_id: row.endId}) " +
		"CREATE (a)-[:`KNOWS` {_neo4j_id: row.id}]->(b)"
}

// nor170NodeRows is the two-node, one-relationship source population from the
// NOR-170 test matrix. Node n1 carries two source labels, so a completed
// migration must preserve both.
func nor170NodeRows() []map[string]any {
	return []map[string]any{
		{
			"id":     "n1",
			"labels": []any{"Person", "Employee"},
			"props":  map[string]any{"name": "Alice", "team": "platform"},
		},
		{
			"id":     "n2",
			"labels": []any{"Person"},
			"props":  map[string]any{"name": "Bob"},
		},
	}
}

func nor170EdgeRows() []map[string]any {
	return []map[string]any{
		{
			"id":      "e1",
			"startId": "n1",
			"endId":   "n2",
			"props":   map[string]any{"since": int64(2020), "weight": 1.5},
		},
	}
}

func nor170Executor(t *testing.T, parser string) (*StorageExecutor, storage.Engine) {
	t.Helper()
	previous := config.GetParserType()
	config.SetParserType(parser)
	t.Cleanup(func() { config.SetParserType(previous) })

	store := storage.NewNamespacedEngine(newTestMemoryEngine(t), "nor170")
	return NewStorageExecutor(store), store
}

func nor170RunMigrationBatches(t *testing.T, ctx context.Context, exec *StorageExecutor) {
	t.Helper()
	_, err := exec.Execute(ctx, nor170NodeUpsertCypher, map[string]any{"rows": nor170NodeRows()})
	require.NoError(t, err, "node batch")
	_, err = exec.Execute(ctx, nor170EdgeCreateCypher, map[string]any{"rows": nor170EdgeRows()})
	require.NoError(t, err, "edge create batch")
	_, err = exec.Execute(ctx, nor170EdgePropsCypher, map[string]any{"rows": nor170EdgeRows()})
	require.NoError(t, err, "edge property batch")
}

func nor170RawNodes(t *testing.T, ctx context.Context, store storage.Engine, label string) []*storage.Node {
	t.Helper()
	nodes, err := store.GetNodesByLabel(ctx, label)
	require.NoError(t, err)
	return nodes
}

func nor170NodeBySourceID(t *testing.T, nodes []*storage.Node, sourceID string) *storage.Node {
	t.Helper()
	for _, node := range nodes {
		if node.Properties["_neo4j_id"] == sourceID {
			return node
		}
	}
	require.FailNowf(t, "source node missing", "no node with _neo4j_id=%q", sourceID)
	return nil
}

func nor170Strings(t *testing.T, value any) []string {
	t.Helper()
	switch typed := value.(type) {
	case []string:
		return typed
	case []any:
		out := make([]string, 0, len(typed))
		for _, item := range typed {
			text, ok := item.(string)
			require.Truef(t, ok, "label value %T is not a string", item)
			out = append(out, text)
		}
		return out
	default:
		require.FailNowf(t, "unexpected label container", "%T", value)
		return nil
	}
}

func nor170Int64(t *testing.T, value any) int64 {
	t.Helper()
	switch typed := value.(type) {
	case int64:
		return typed
	case int:
		return int64(typed)
	default:
		require.FailNowf(t, "unexpected integer type", "%T", value)
		return 0
	}
}

// TestNOR170MigratedNodesAreHiddenAndPromotionMatchesNothing establishes the
// intermediate state the ticket requires us not to dismiss: the node batch
// persists both nodes, the edge batch silently persists no relationship, and
// the documented promotion statement matches zero rows because every
// `_Migrated` node carries an underscore-prefixed label. The visible-label
// control proves the underscore prefix, not the statement shape, is the cause.
func TestNOR170MigratedNodesAreHiddenAndPromotionMatchesNothing(t *testing.T) {
	ctx := context.Background()
	for _, parser := range []string{config.ParserTypeNornic, config.ParserTypeANTLR} {
		t.Run(parser, func(t *testing.T) {
			exec, store := nor170Executor(t, parser)
			nor170RunMigrationBatches(t, ctx, exec)

			// The migration did write the two source nodes.
			raw := nor170RawNodes(t, ctx, store, "_Migrated")
			require.Len(t, raw, 2)
			for _, node := range raw {
				require.Equal(t, []string{"_Migrated"}, node.Labels)
				require.NotEmpty(t, node.Properties["_neo4j_id"])
			}
			alice := nor170NodeBySourceID(t, raw, "n1")
			require.Equal(t, "Alice", alice.Properties["name"])
			require.ElementsMatch(t, []string{"Person", "Employee"}, nor170Strings(t, alice.Properties["_neo4j_labels"]))
			bob := nor170NodeBySourceID(t, raw, "n2")
			require.Equal(t, "Bob", bob.Properties["name"])
			require.Equal(t, []string{"Person"}, nor170Strings(t, bob.Properties["_neo4j_labels"]))

			// The edge batch silently created nothing: its endpoint MATCH
			// applies the same visibility rule.
			edges, err := store.AllEdges(ctx)
			require.NoError(t, err)
			require.Empty(t, edges, "edge CREATE produced no rows and no error")

			// Ordinary MATCH cannot see any of it.
			for _, query := range []string{
				"MATCH (n:_Migrated) RETURN n._neo4j_id AS id ORDER BY id",
				"MATCH (n:_Migrated {_neo4j_id: 'n1'}) RETURN n._neo4j_id AS id",
				"MATCH (n) RETURN n._neo4j_id AS id ORDER BY id",
			} {
				result, err := exec.Execute(ctx, query, nil)
				require.NoError(t, err, query)
				require.Empty(t, result.Rows, query)
			}
			result, err := exec.Execute(ctx, "MATCH (n:_Migrated) RETURN count(n) AS c", nil)
			require.NoError(t, err)
			require.Equal(t, int64(0), nor170Int64(t, result.Rows[0][0]),
				"public count hides the two nodes the raw label scan returns")

			// The documented promotion reports success while changing nothing.
			result, err = exec.Execute(ctx, nor170Promotion("Person"), nil)
			require.NoError(t, err)
			require.NotNil(t, result.Stats)
			require.Zero(t, result.Stats.LabelsAdded)
			require.Zero(t, result.Stats.LabelsRemoved)
			require.Zero(t, result.Stats.PropertiesSet)
			require.Empty(t, nor170RawNodes(t, ctx, store, "Person"))

			// Control: the same statement shape over a label without the
			// underscore prefix reaches and promotes its nodes.
			controlExec, controlStore := nor170Executor(t, parser)
			controlNode := "UNWIND $rows AS row\n" +
				"MERGE (n:Bridge {_neo4j_id: row.id})\n" +
				"SET n += row.props\n" +
				"SET n._neo4j_labels = row.labels\n"
			_, err = controlExec.Execute(ctx, controlNode, map[string]any{"rows": nor170NodeRows()})
			require.NoError(t, err)
			result, err = controlExec.Execute(ctx, "MATCH (n:Bridge) RETURN count(n) AS c", nil)
			require.NoError(t, err)
			require.Equal(t, int64(2), nor170Int64(t, result.Rows[0][0]))

			controlPromotion := "MATCH (n:Bridge)\n" +
				"WHERE 'Person' IN n._neo4j_labels\n" +
				"SET n:Person\n" +
				"REMOVE n:Bridge\n" +
				"REMOVE n._neo4j_labels"
			result, err = controlExec.Execute(ctx, controlPromotion, nil)
			require.NoError(t, err)
			require.Equal(t, 2, result.Stats.LabelsAdded)
			require.Len(t, nor170RawNodes(t, ctx, controlStore, "Person"), 2)
			require.Empty(t, nor170RawNodes(t, ctx, controlStore, "Bridge"))
		})
	}
}

// TestNOR170CompletedMigrationContract is the completed-workflow
// reproduction: migrate, run the documented promotion for every source label,
// then read the graph with ordinary MATCH. It asserts the documented contract
// and therefore fails while the defect stands.
func TestNOR170CompletedMigrationContract(t *testing.T) {
	ctx := context.Background()
	for _, parser := range []string{config.ParserTypeNornic, config.ParserTypeANTLR} {
		t.Run(parser, func(t *testing.T) {
			exec, store := nor170Executor(t, parser)
			nor170RunMigrationBatches(t, ctx, exec)
			for _, label := range []string{"Person", "Employee"} {
				_, err := exec.Execute(ctx, nor170Promotion(label), nil)
				require.NoError(t, err)
			}

			t.Run("nodes keep every source label and property", func(t *testing.T) {
				result, err := exec.Execute(ctx,
					"MATCH (n:Person) RETURN n._neo4j_id AS id, n.name AS name, labels(n) AS labels, n._neo4j_labels AS bookkeeping ORDER BY id", nil)
				require.NoError(t, err)
				require.Len(t, result.Rows, 2, "both migrated nodes are visible under their source label")
				require.Equal(t, "n1", result.Rows[0][0])
				require.Equal(t, "Alice", result.Rows[0][1])
				require.ElementsMatch(t, []string{"Person", "Employee"}, nor170Strings(t, result.Rows[0][2]))
				require.Nil(t, result.Rows[0][3], "promotion removes the bookkeeping label list")
				require.Equal(t, "n2", result.Rows[1][0])
				require.Equal(t, "Bob", result.Rows[1][1])
				require.Equal(t, []string{"Person"}, nor170Strings(t, result.Rows[1][2]))

				// The promotion must not leave the migration bridge label.
				result, err = exec.Execute(ctx, "MATCH (n:_Migrated) RETURN count(n) AS c", nil)
				require.NoError(t, err)
				require.Equal(t, int64(0), nor170Int64(t, result.Rows[0][0]))
				require.Empty(t, nor170RawNodes(t, ctx, store, "_Migrated"))
			})

			t.Run("relationship and endpoints are visible with properties", func(t *testing.T) {
				result, err := exec.Execute(ctx,
					"MATCH (a:Person)-[r:KNOWS]->(b:Person) RETURN a.name AS a, type(r) AS t, b.name AS b, r.since AS since", nil)
				require.NoError(t, err)
				require.Equal(t, [][]interface{}{{"Alice", "KNOWS", "Bob", int64(2020)}}, result.Rows)

				edges, err := store.AllEdges(ctx)
				require.NoError(t, err)
				require.Len(t, edges, 1, "the documented edge batch creates the one migrated relationship")
				require.Equal(t, "KNOWS", edges[0].Type)
				require.Equal(t, int64(2020), edges[0].Properties["since"])
				require.Equal(t, 1.5, edges[0].Properties["weight"])
			})

			t.Run("rerun does not duplicate nodes or relationships", func(t *testing.T) {
				nor170RunMigrationBatches(t, ctx, exec)
				for _, label := range []string{"Person", "Employee"} {
					_, err := exec.Execute(ctx, nor170Promotion(label), nil)
					require.NoError(t, err)
				}
				result, err := exec.Execute(ctx, "MATCH (n:Person) RETURN count(n) AS c", nil)
				require.NoError(t, err)
				require.Equal(t, int64(2), nor170Int64(t, result.Rows[0][0]))
				result, err = exec.Execute(ctx, "MATCH ()-[r:KNOWS]->() RETURN count(r) AS c", nil)
				require.NoError(t, err)
				require.Equal(t, int64(1), nor170Int64(t, result.Rows[0][0]))
			})
		})
	}
}

// TestNOR170PromotionPreservesEverySourceLabel isolates the promotion
// statement from the visibility defect by using a visible bridge label. Even
// with every node reachable, the documented "one statement per source label"
// pass removes `_Migrated` and `_neo4j_labels` on the first label and then
// cannot find the node for its remaining labels. It asserts the documented
// multi-label contract and therefore fails.
func TestNOR170PromotionPreservesEverySourceLabel(t *testing.T) {
	ctx := context.Background()
	for _, parser := range []string{config.ParserTypeNornic, config.ParserTypeANTLR} {
		t.Run(parser, func(t *testing.T) {
			exec, store := nor170Executor(t, parser)
			bridgeNode := "UNWIND $rows AS row\n" +
				"MERGE (n:Bridge {_neo4j_id: row.id})\n" +
				"SET n += row.props\n" +
				"SET n._neo4j_labels = row.labels\n"
			_, err := exec.Execute(ctx, bridgeNode, map[string]any{"rows": nor170NodeRows()})
			require.NoError(t, err)

			for _, label := range []string{"Person", "Employee"} {
				promotion := "MATCH (n:Bridge)\n" +
					"WHERE '" + label + "' IN n._neo4j_labels\n" +
					"SET n:" + label + "\n" +
					"REMOVE n:Bridge\n" +
					"REMOVE n._neo4j_labels"
				_, err := exec.Execute(ctx, promotion, nil)
				require.NoError(t, err)
			}

			nodes := nor170RawNodes(t, ctx, store, "Person")
			require.Len(t, nodes, 2)
			alice := nor170NodeBySourceID(t, nodes, "n1")
			labels := append([]string(nil), alice.Labels...)
			sort.Strings(labels)
			require.Equal(t, []string{"Employee", "Person"}, labels,
				"a completed per-label promotion must keep Employee on the multi-label node")
			require.Len(t, nor170RawNodes(t, ctx, store, "Employee"), 1)
		})
	}
}

// TestNOR170InterruptedPromotionIsIndistinguishableFromCleanCompletion pins
// the actual interruption contract: stopping before promotion leaves the
// documented completion check (`count(n:_Migrated) = 0`) passing, because the
// same visibility rule hides the unfinished nodes. Rerunning the node batch is
// the only supported resume action, and it is idempotent.
func TestNOR170InterruptedPromotionIsIndistinguishableFromCleanCompletion(t *testing.T) {
	ctx := context.Background()
	for _, parser := range []string{config.ParserTypeNornic, config.ParserTypeANTLR} {
		t.Run(parser, func(t *testing.T) {
			exec, store := nor170Executor(t, parser)
			nor170RunMigrationBatches(t, ctx, exec)

			result, err := exec.Execute(ctx, "MATCH (n:_Migrated) RETURN count(n) AS c", nil)
			require.NoError(t, err)
			require.Equal(t, int64(0), nor170Int64(t, result.Rows[0][0]),
				"the documented clean-completion check answers 0 on an interrupted migration")

			// The unfinished work is still in storage.
			require.Len(t, nor170RawNodes(t, ctx, store, "_Migrated"), 2)
			require.Empty(t, nor170RawNodes(t, ctx, store, "Person"))
			edges, err := store.AllEdges(ctx)
			require.NoError(t, err)
			require.Empty(t, edges)

			// Resume action: rerun the node batch. It refreshes the same two
			// nodes and creates no third node.
			rerunRows := nor170NodeRows()
			rerunRows[0]["props"] = map[string]any{"name": "Alice Updated", "team": "platform"}
			_, err = exec.Execute(ctx, nor170NodeUpsertCypher, map[string]any{"rows": rerunRows})
			require.NoError(t, err)
			raw := nor170RawNodes(t, ctx, store, "_Migrated")
			require.Len(t, raw, 2)
			require.Equal(t, "Alice Updated", nor170NodeBySourceID(t, raw, "n1").Properties["name"])

			// Promotion still cannot move the nodes, so the interrupted state
			// remains indistinguishable from a completed migration.
			result, err = exec.Execute(ctx, nor170Promotion("Person"), nil)
			require.NoError(t, err)
			require.Zero(t, result.Stats.LabelsAdded)
			require.Empty(t, nor170RawNodes(t, ctx, store, "Person"))
		})
	}
}

// TestNOR170NodeRerunIsIdempotentAndEdgeCreateIsNot establishes which rerun
// guarantees the generated batches actually provide. The node batch is a MERGE
// keyed on `_neo4j_id` and is idempotent. The edge batch is a bare CREATE: its
// `_Migrated` endpoint MATCH currently creates nothing, and the visible-label
// control shows that the same statement creates a duplicate relationship each
// time it runs once the endpoints are reachable.
func TestNOR170NodeRerunIsIdempotentAndEdgeCreateIsNot(t *testing.T) {
	ctx := context.Background()
	for _, parser := range []string{config.ParserTypeNornic, config.ParserTypeANTLR} {
		t.Run(parser, func(t *testing.T) {
			exec, store := nor170Executor(t, parser)
			_, err := exec.Execute(ctx, nor170NodeUpsertCypher, map[string]any{"rows": nor170NodeRows()})
			require.NoError(t, err)
			first := nor170RawNodes(t, ctx, store, "_Migrated")
			require.Len(t, first, 2)
			firstIDs := map[string]storage.NodeID{}
			for _, node := range first {
				firstIDs[node.Properties["_neo4j_id"].(string)] = node.ID
			}

			_, err = exec.Execute(ctx, nor170NodeUpsertCypher, map[string]any{"rows": nor170NodeRows()})
			require.NoError(t, err)
			second := nor170RawNodes(t, ctx, store, "_Migrated")
			require.Len(t, second, 2, "the MERGE node batch is idempotent")
			for _, node := range second {
				require.Equal(t, firstIDs[node.Properties["_neo4j_id"].(string)], node.ID)
			}

			// The documented edge batch against `_Migrated` endpoints runs
			// twice without error and without creating a relationship.
			for run := 0; run < 2; run++ {
				_, err = exec.Execute(ctx, nor170EdgeCreateCypher, map[string]any{"rows": nor170EdgeRows()})
				require.NoError(t, err)
			}
			edges, err := store.AllEdges(ctx)
			require.NoError(t, err)
			require.Empty(t, edges)

			// Control: the same generated CREATE shape over a visible bridge
			// label duplicates on the second run.
			bridgeNode := "UNWIND $rows AS row\n" +
				"MERGE (n:Bridge {_neo4j_id: row.id})\n" +
				"SET n += row.props\n" +
				"SET n._neo4j_labels = row.labels\n"
			_, err = exec.Execute(ctx, bridgeNode, map[string]any{"rows": nor170NodeRows()})
			require.NoError(t, err)
			for run := 0; run < 2; run++ {
				_, err = exec.Execute(ctx, nor170EdgeCreate("Bridge"), map[string]any{"rows": nor170EdgeRows()})
				require.NoError(t, err)
			}
			edges, err = store.AllEdges(ctx)
			require.NoError(t, err)
			require.Len(t, edges, 2, "a bare CREATE edge batch is not idempotent once endpoints are visible")
			require.Equal(t, "KNOWS", edges[0].Type)
			require.Equal(t, "KNOWS", edges[1].Type)
		})
	}
}

// TestNOR170SystemNodeVisibilityControlsPreserved pins the genuine system-node
// controls a correction must not weaken: underscore-labelled records stay
// hidden on a user database, remain visible to the system database, and the
// internal point read used by writers still returns them.
func TestNOR170SystemNodeVisibilityControlsPreserved(t *testing.T) {
	ctx := context.Background()
	for _, parser := range []string{config.ParserTypeNornic, config.ParserTypeANTLR} {
		t.Run(parser, func(t *testing.T) {
			exec, store := nor170Executor(t, parser)
			_, err := exec.Execute(ctx,
				"CREATE (:NOR170UserRecord {id: 1}), (:NOR170UserRecord:_internal {id: 2})", nil)
			require.NoError(t, err)

			result, err := exec.Execute(ctx,
				"MATCH (n:NOR170UserRecord) RETURN n.id AS id ORDER BY id", nil)
			require.NoError(t, err)
			require.Equal(t, [][]interface{}{{int64(1)}}, result.Rows,
				"a genuine internal node stays hidden from ordinary MATCH")

			require.True(t, shouldHideSystemNodes(store))
			require.False(t, shouldHideSystemNodes(storage.NewNamespacedEngine(newTestMemoryEngine(t), "system")))
			require.True(t, shouldHideSystemNodes(storage.NewNamespacedEngine(newTestMemoryEngine(t), "nor170")))

			internal := &storage.Node{
				ID:         "nor170:hidden",
				Labels:     []string{"NOR170UserRecord", "_internal"},
				Properties: map[string]interface{}{"id": int64(3)},
			}
			pattern := nodePatternInfo{variable: "n", labels: []string{"NOR170UserRecord"}}
			system := NewStorageExecutor(storage.NewNamespacedEngine(newTestMemoryEngine(t), "system"))
			require.True(t, system.pipelineNodeMatchesPattern(ctx, internal, pattern))
			require.False(t, exec.pipelineNodeMatchesPattern(ctx, internal, pattern))

			// The canonical point read used by writers keeps returning the
			// internal record; hiding belongs to MATCH row admission only.
			_, err = store.CreateNode(ctx, internal)
			require.NoError(t, err)
			read, err := exec.getQueryNode(ctx, store, internal.ID)
			require.NoError(t, err)
			require.NotNil(t, read)
			require.True(t, isSystemNode(read))
		})
	}
}
