// This carrier uses release APIs only. The same bytes run on d663 and head.
// Recording mode emits the release oracle; qualification mode requires the
// committed oracle, including explicitly enumerated NOR-294 permitted sets.
type fulltextContractOutcome struct {
	Columns []string `json:"columns"`
	Rows    []any    `json:"rows"`
	Nil     bool     `json:"nil_result"`
	Errors  []any    `json:"errors"`
}
type fulltextContractOracle struct {
	Author   string                               `json:"author"`
	Source   string                               `json:"source"`
	Outcomes map[string][]fulltextContractOutcome `json:"outcomes"`
}

func fulltextContractValue(value any) any {
	switch v := value.(type) {
	case float64:
		return fmt.Sprintf("float64:%016x", math.Float64bits(v))
	case *storage.Node:
		runtime := v.RuntimeMetadata()
		return map[string]any{"node": v, "database": runtime.Database, "created": v.CreatedAt, "updated": v.UpdatedAt, "embeddings": v.NamedEmbeddings, "chunks": v.ChunkEmbeddings, "embedding_meta": v.EmbedMeta, "suppressed": runtime.VisibilitySuppressed}
	case *storage.Edge:
		return map[string]any{"edge": v, "database": v.Database, "created": v.CreatedAt, "updated": v.UpdatedAt, "confidence": v.Confidence, "auto": v.AutoGenerated, "suppressed": v.VisibilitySuppressed}
	default:
		return v
	}
}

func fulltextContractObserve(result *ExecuteResult, err error) fulltextContractOutcome {
	out := fulltextContractOutcome{Nil: result == nil, Rows: []any{}, Errors: []any{}}
	if result != nil {
		out.Columns = result.Columns
		for _, row := range result.Rows {
			values := make([]any, len(row))
			for i, value := range row {
				values[i] = fulltextContractValue(value)
			}
			out.Rows = append(out.Rows, values)
		}
	}
	for err != nil {
		status := ""
		if coded, ok := err.(interface{ BoltErrorCode() string }); ok {
			status = coded.BoltErrorCode()
		}
		detail := ""
		if coded, ok := err.(interface{ BoltErrorDetail() string }); ok {
			detail = coded.BoltErrorDetail()
		}
		out.Errors = append(out.Errors, map[string]any{"type": fmt.Sprintf("%T", err), "message": err.Error(), "status": status, "detail": detail, "structured": err})
		err = errors.Unwrap(err)
	}
	return out
}

func fulltextContractRecorder(t *testing.T) func(string, *StorageExecutor, string, map[string]any) {
	t.Helper()
	record := os.Getenv("NOR148_RECORD_RELEASE") == "1"
	oracle := fulltextContractOracle{}
	if !record {
		parser := "default"
		if os.Getenv("NORNICDB_PARSER") == "antlr" {
			parser = "antlr"
		}
		data, err := os.ReadFile("testdata/fulltext_release_contract_" + parser + ".json")
		require.NoError(t, err, "release oracle must be recorded on the pushed d663 product")
		require.NoError(t, json.Unmarshal(data, &oracle))
	}
	seen := map[string]bool{}
	t.Cleanup(func() {
		if !record {
			require.Len(t, seen, len(oracle.Outcomes), "oracle rows must all be consumed")
		}
	})
	return func(key string, exec *StorageExecutor, query string, params map[string]any) {
		t.Helper()
		require.False(t, seen[key], "duplicate oracle key %s", key)
		seen[key] = true
		result, err := exec.Execute(context.Background(), query, params)
		outcome := fulltextContractObserve(result, err)
		data, marshalErr := json.Marshal(outcome)
		require.NoError(t, marshalErr)
		var canonical any
		require.NoError(t, json.Unmarshal(data, &canonical))
		data, marshalErr = json.Marshal(canonical)
		require.NoError(t, marshalErr)
		if record {
			t.Logf("NOR148_ORACLE %s %s", key, data)
			return
		}
		permitted, exists := oracle.Outcomes[key]
		require.True(t, exists, "missing oracle key %s", key)
		for _, want := range permitted {
			encoded, e := json.Marshal(want)
			require.NoError(t, e)
			var decoded any
			require.NoError(t, json.Unmarshal(encoded, &decoded))
			encoded, e = json.Marshal(decoded)
			require.NoError(t, e)
			if bytes.Equal(data, encoded) {
				return
			}
		}
		t.Errorf("release differential %s: got %s; permitted %v", key, data, permitted)
	}
}

