var fulltextContractTime = time.Unix(1234567890, 0).UTC()

func fulltextContractSeed(t *testing.T, store storage.Engine) {
	t.Helper()
	properties := []map[string]any{
		{"text": "hotel services hotel", "title": "routine", "other": "secret", "current": true},
		{"Text": "hotel", "title": "routine", "other": "hotel", "current": false},
		{"text": " hotel ", "title": "", "current": true},
		{"text": "\thotel\nservices\u2003", "title": "alpha"},
		{"text": nil, "title": "routine"}, {"title": ""}, {"text": "   "}, {},
		{"text": int64(42), "title": true}, {"text": []any{"hotel", int64(7)}, "title": "list"},
		{"text": "HÔTEL ÄBC", "title": "École", "ÄKey": "hotel"},
		{"text": "hotel-service path\\name", "title": "zulu"},
	}
	for i, props := range properties {
		id := fmt.Sprintf("d%02d", i)
		_, err := store.CreateNode(&storage.Node{ID: storage.NodeID(id), Labels: []string{"Doc"}, Properties: props, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime})
		require.NoError(t, err)
		require.NoError(t, store.CreateEdge(&storage.Edge{ID: storage.EdgeID(id), StartNode: "d00", EndNode: storage.NodeID(id), Type: "LINK", Properties: props, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime, Confidence: .75}))
	}
	_, err := store.CreateNode(&storage.Node{ID: "outside", Labels: []string{"Outside"}, Properties: map[string]any{"text": "hotel"}, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime})
	require.NoError(t, err)
	require.NoError(t, store.CreateEdge(&storage.Edge{ID: "outside", StartNode: "d00", EndNode: "outside", Type: "OTHER", Properties: map[string]any{"text": "hotel"}, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime}))
}

