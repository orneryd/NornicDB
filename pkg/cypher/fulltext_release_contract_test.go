func TestFulltextReleaseContract(t *testing.T) {
	observe := fulltextContractRecorder(t)
	base, store := fulltextContractStore(t)
	fulltextContractSeed(t, store)
	// TracedEngine is a real non-streaming forwarder, so unranked relationships
	// must preserve its AllEdges fallback, including error precedence.
	shapes := []struct {
		name   string
		engine storage.Engine
	}{{"native", store}, {"fallback", storage.NewTracedEngine(store)}}
	queries := []string{"hotel", `" hotel "`, "text:hotel", "Text:hotel", "other:hotel", "*:hotel", "+hotel -routine", "hotel AND title:routine", "hotel OR absent", "NOT hotel", "(text:hotel OR other:hotel)^2", "title:* AND hotel", "text:hot*", "text:/ho.el/", "text:hotel~1", "text:[A TO z]", "text:{A TO z}", "*", "*:*", "text:*", "Text:*", "unknown:*", "", " ", `"`, "hotel^2", `path\\name`, "ÄKey:hotel"}
	for _, shape := range shapes {
		exec := NewStorageExecutor(shape.engine, QueryCachePolicy{MaxEntries: 0})
		if shape.name == "native" {
			fulltextContractIndexes(t, exec)
		}
		for _, entity := range []string{"nodes", "edges"} {
			procedure := "queryNodes"
			column := "node"
			if entity == "edges" {
				procedure = "queryRelationships"
				column = "relationship"
			}
			for _, index := range []string{entity, "reverse_" + entity} {
				for round := 0; round < 2; round++ {
					for qi, text := range queries {
						for oi, opts := range []map[string]any{{}, {"skip": int64(1), "limit": int64(2)}, {"limit": int64(0)}} {
							q := fmt.Sprintf("CALL db.index.fulltext.%s('%s',$q,$opts) YIELD %s,score RETURN %s,score", procedure, index, column, column)
							observe(fmt.Sprintf("representation/%s/%s/%s/%d/%02d/%d", shape.name, entity, index, round, qi, oi), exec, q, map[string]any{"q": text, "opts": opts})
						}
					}
				}
			}
		}
		for i, args := range []string{"'missing',''", "'missing','hotel'", "'nodes',42", "'nodes','hotel',{skip:-1}", "'nodes','hotel',{limit:0.5}", "'nodes','hotel',42"} {
			for _, proc := range []string{"queryNodes", "queryRelationships"} {
				observe(fmt.Sprintf("arguments/%s/%s/%d", shape.name, proc, i), exec, "CALL db.index.fulltext."+proc+"("+args+")", nil)
			}
		}
	}
	exec := NewStorageExecutor(store, QueryCachePolicy{MaxEntries: 0})
	for stage := 0; stage < 4; stage++ {
		if stage == 1 {
			node, err := store.GetNode("d01")
			require.NoError(t, err)
			node.Properties = map[string]any{"text": "hotel novel", "title": "changed"}
			node.UpdatedAt = fulltextContractTime
			require.NoError(t, store.UpdateNode(storage.NodeUpdateRequest{After: node}))
			edge, err := store.GetEdge("d01")
			require.NoError(t, err)
			edge.Properties = node.Properties
			edge.UpdatedAt = fulltextContractTime
			require.NoError(t, store.UpdateEdge(storage.EdgeUpdateRequest{After: edge}))
		}
		if stage == 2 {
			require.NoError(t, store.DeleteEdge("d01"))
			require.NoError(t, store.DeleteNode("d01"))
		}
		if stage == 3 {
			for i := 0; i < 40; i++ {
				id := storage.NodeID(fmt.Sprintf("overflow%d", i))
				_, err := store.CreateNode(&storage.Node{ID: id})
				require.NoError(t, err)
				require.NoError(t, store.DeleteNode(id))
			}
		}
		for _, entity := range []string{"nodes", "edges"} {
			proc, col := "queryNodes", "node"
			if entity == "edges" {
				proc, col = "queryRelationships", "relationship"
			}
			for qi, text := range []string{"*", "novel", "text:*", "hotel", "other:hotel", "hotel OR routine"} {
				observe(fmt.Sprintf("maintenance/%d/%s/%d", stage, entity, qi), exec, fmt.Sprintf("CALL db.index.fulltext.%s('%s',$q) YIELD %s,score RETURN %s,score", proc, entity, col, col), map[string]any{"q": text})
			}
		}
	}
	// Public restore is a physical replacement, including caches and revisions.
	backup := filepath.Join(t.TempDir(), "backup")
	require.NoError(t, base.Backup(backup))
	require.NoError(t, base.Restore(backup))
	observe("maintenance/restore", exec, "CALL db.index.fulltext.queryNodes('nodes','hotel') YIELD node,score RETURN node,score", nil)
	fulltextContractUnstable(t, observe)
	fulltextContractErrors(t, observe)
	fulltextContractReaderOutcomes(t, observe)
	fulltextContractSchemaIdentity(t, observe)
}

// These issued readers deliberately change acquisition policy. Promoted
// snapshot methods must not bypass their public AllNodes/AllEdges contracts.
type fulltextContractMaterialized struct {
	*storage.NamespacedEngine
	fail      bool
	duplicate bool
}

var fulltextContractReadError = errors.New("contract reader failure")

func (s *fulltextContractMaterialized) AllNodes() ([]*storage.Node, error) {
	rows, err := s.NamespacedEngine.AllNodes()
	if err != nil {
		return nil, err
	}
	if s.fail {
		return rows, fmt.Errorf("materialized nodes: %w", fulltextContractReadError)
	}
	if s.duplicate && len(rows) > 0 {
		rows = append(rows, storage.CopyNode(rows[0]))
	}
	return rows, nil
}
func (s *fulltextContractMaterialized) AllEdges() ([]*storage.Edge, error) {
	rows, err := s.NamespacedEngine.AllEdges()
	if err != nil {
		return nil, err
	}
	if s.fail {
		return rows, fmt.Errorf("materialized edges: %w", fulltextContractReadError)
	}
	if s.duplicate && len(rows) > 0 {
		rows = append(rows, storage.CopyEdge(rows[0]))
	}
	return rows, nil
}

type fulltextContractStream struct {
	storage.StreamingEngine
	after   int
	wrapped bool
}

func (s *fulltextContractStream) StreamEdges(ctx context.Context, visit func(*storage.Edge) error) error {
	n := 0
	err := s.StreamingEngine.StreamEdges(ctx, func(edge *storage.Edge) error {
		if n == s.after {
			return fulltextContractReadError
		}
		n++
		return visit(edge)
	})
	if err == fulltextContractReadError && s.wrapped {
		return fmt.Errorf("stream tail: %w", storage.ErrIterationStopped)
	}
	return err
}
func fulltextContractReaderOutcomes(t *testing.T, observe func(string, *StorageExecutor, string, map[string]any)) {
	_, store := fulltextContractStore(t)
	fulltextContractSeed(t, store)
	exec := NewStorageExecutor(store, QueryCachePolicy{MaxEntries: 0})
	fulltextContractIndexes(t, exec)
	for _, shape := range []struct {
		name   string
		engine storage.Engine
	}{
		{"materialized_error", &fulltextContractMaterialized{NamespacedEngine: store, fail: true}},
		{"duplicate", &fulltextContractMaterialized{NamespacedEngine: store, duplicate: true}},
		{"stream_before", &fulltextContractStream{StreamingEngine: store, after: 0}},
		{"stream_after", &fulltextContractStream{StreamingEngine: store, after: 3}},
		{"stream_wrapped_stop", &fulltextContractStream{StreamingEngine: store, after: 3, wrapped: true}},
	} {
		// The explicit non-streaming wrapper selects materialized fallback for the
		// materialized decorators, rather than their promoted native stream method.
		engine := shape.engine
		if _, ok := engine.(*fulltextContractMaterialized); ok {
			engine = storage.NewTracedEngine(engine)
		}
		reader := NewStorageExecutor(engine, QueryCachePolicy{MaxEntries: 0})
		for _, entity := range []string{"nodes", "edges"} {
			proc := "queryNodes"
			if entity == "edges" {
				proc = "queryRelationships"
			}
			for qi, text := range []string{"*", "text:*", "hotel", `"`, " "} {
				for oi, opts := range []map[string]any{{}, {"limit": int64(1)}, {"skip": int64(2), "limit": int64(1)}, {"limit": int64(0)}} {
					observe(fmt.Sprintf("reader/%s/%s/%d/%d", shape.name, entity, qi, oi), reader, fmt.Sprintf("CALL db.index.fulltext.%s('%s',$q,$opts)", proc, entity), map[string]any{"q": text, "opts": opts})
				}
			}
		}
	}
}

func fulltextContractUnstable(t *testing.T, observe func(string, *StorageExecutor, string, map[string]any)) {
	for _, entity := range []string{"nodes", "edges"} {
		_, store := fulltextContractStore(t)
		_, err := store.CreateNode(&storage.Node{ID: "one", Labels: []string{"Doc"}, Properties: map[string]any{"text": "quiet", "Text": "hotel"}, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime})
		require.NoError(t, err)
		require.NoError(t, store.CreateEdge(&storage.Edge{ID: "one", StartNode: "one", EndNode: "one", Type: "LINK", Properties: map[string]any{"text": "quiet", "Text": "hotel"}, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime}))
		exec := NewStorageExecutor(store, QueryCachePolicy{MaxEntries: 0})
		fulltextContractIndexes(t, exec)
		proc := "queryNodes"
		if entity == "edges" {
			proc = "queryRelationships"
		}
		for _, text := range []string{"hotel", "quiet", "text:[h TO i]", "text:* AND hotel"} {
			for repeat := 0; repeat < 12; repeat++ {
				observe(fmt.Sprintf("NOR294/collision/%s/%s/%d", entity, text, repeat), exec, fmt.Sprintf("CALL db.index.fulltext.%s('%s',$q) YIELD score RETURN score", proc, entity), map[string]any{"q": text})
			}
		}
		// Equal values remove the collision's traversal dependence while keeping
		// its one-word scoring body. This public release observation supplies
		// the exact quiet score for the permitted-outcome ledger.
		node, err := store.GetNode("one")
		require.NoError(t, err)
		node.Properties["Text"] = "quiet"
		node.UpdatedAt = fulltextContractTime
		require.NoError(t, store.UpdateNode(storage.NodeUpdateRequest{After: node}))
		edge, err := store.GetEdge("one")
		require.NoError(t, err)
		edge.Properties["Text"] = "quiet"
		edge.UpdatedAt = fulltextContractTime
		require.NoError(t, store.UpdateEdge(storage.EdgeUpdateRequest{After: edge}))
		observe("NOR294/collision_control/"+entity, exec, fmt.Sprintf("CALL db.index.fulltext.%s('%s','quiet') YIELD score RETURN score", proc, entity), nil)
	}
	// Exactly two values means the release-permitted bodies are these two orders.
	for _, pair := range []struct {
		name  string
		props map[string]any
	}{{"map", map[string]any{"a": "hotel", "b": "services"}}, {"forward", map[string]any{"a": "hotel services"}}, {"reverse", map[string]any{"a": "services hotel"}}} {
		_, store := fulltextContractStore(t)
		_, err := store.CreateNode(&storage.Node{ID: "one"})
		require.NoError(t, err)
		require.NoError(t, store.CreateEdge(&storage.Edge{ID: "one", StartNode: "one", EndNode: "one", Type: "LINK", Properties: pair.props, CreatedAt: fulltextContractTime, UpdatedAt: fulltextContractTime}))
		exec := NewStorageExecutor(store, QueryCachePolicy{MaxEntries: 0})
		for qi, text := range []string{`"hotel services"`, `"services hotel"`, "hotel AND services", "*"} {
			for repeat := 0; repeat < 12; repeat++ {
				observe(fmt.Sprintf("NOR294/body/%s/%d/%d", pair.name, qi, repeat), exec, "CALL db.index.fulltext.queryRelationships('default',$q) YIELD score RETURN score", map[string]any{"q": text})
			}
		}
	}
}

// Change only a portable backup's entity body. No writes go through the raw DB
// handle, and public Restore remains the committed replacement owner.
func fulltextContractCorruptBackup(t *testing.T, base *storage.BadgerEngine, key []byte) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "backup")
	require.NoError(t, base.Backup(path))
	data, err := os.ReadFile(path)
	require.NoError(t, err)
	input := bytes.NewReader(data)
	var output bytes.Buffer
	changed := 0
	for {
		var size uint64
		err := binary.Read(input, binary.LittleEndian, &size)
		if err == io.EOF {
			break
		}
		require.NoError(t, err)
		raw := make([]byte, size)
		_, err = io.ReadFull(input, raw)
		require.NoError(t, err)
		list := &pb.KVList{}
		require.NoError(t, proto.Unmarshal(raw, list))
		for _, kv := range list.Kv {
			if bytes.Equal(kv.Key, key) {
				kv.Value = []byte{0xff}
				changed++
			}
		}
		raw, err = proto.Marshal(list)
		require.NoError(t, err)
		require.NoError(t, binary.Write(&output, binary.LittleEndian, uint64(len(raw))))
		_, err = output.Write(raw)
		require.NoError(t, err)
	}
	require.Greater(t, changed, 0, "corruption fixture must change an actual entity body")
	require.NoError(t, os.WriteFile(path, output.Bytes(), 0600))
	return path
}

