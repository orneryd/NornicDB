#!/usr/bin/env python3
"""Generate query-body container identities from their grammar productions."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent
lexer = (root / "CypherLexer.g4").read_text()
grammar = (root / "CypherParser.g4").read_text()
grammar = re.sub(r"/\*.*?\*/|//[^\n]*", "", grammar, flags=re.S)
literals = dict(re.findall(r"(?m)^([A-Z_][A-Z0-9_]*)\s*:\s*'([A-Z]+)'\s*;", lexer))
rules = dict(re.findall(r"(?m)^\s*([a-z]\w*)\s*:([^;]*);", grammar))
containers = {}
for rule, body in rules.items():
    for opening in re.finditer(r"\bLBRACE\b", body):
        closing = body.find("RBRACE", opening.end())
        if closing < 0 or not re.search(r"\b(subqueryBody|regularQuery)\b", body[opening.end():closing]):
            continue
        words = [word for word in re.findall(r"\b[A-Z_]+\b", body[:opening.start()]) if word in literals]
        if not words:
            raise SystemExit("body-bearing rule has no container word: " + rule)
        word = literals[words[-1]]
        if rule in containers and containers[rule] != word:
            raise SystemExit("ambiguous query-body container identity: " + rule)
        containers[rule] = word
if not containers:
    raise SystemExit("no query-body containers found")
source = '// Code generated by generate_vocabulary.py from CypherParser.g4; DO NOT EDIT.\n\npackage antlr\n\n'
source += 'var queryBodyContainerByRule = map[int]string{\n'
for rule, word in sorted(containers.items()):
    source += '\tCypherParserRULE_' + rule + ': "' + word + '",\n'
source += '}\n'
# Expression containers are reachable from expression without crossing into
# the query held by a container. A CALL nested inside that query is not an
# expression container of the outer expression.
reachable = set()
pending = ['expression']
while pending:
    rule = pending.pop()
    if rule in reachable or rule in {'regularQuery', 'subqueryBody'}:
        continue
    reachable.add(rule)
    pending.extend(name for name in re.findall(r'\b[a-z]\w*\b', rules.get(rule, '')) if name in rules)
source += '\nvar expressionQueryBodyRules = map[int]bool{\n'
for rule in sorted(containers.keys() & reachable):
    source += '\tCypherParserRULE_' + rule + ': true,\n'
source += '}\n'
# A grammar production's literal vocabulary is separate from its semantic
# interpretation (for example, which version permits PROPERTY UNIQUE).
def words_in_rule(rule, seen):
    if rule in seen:
        return set()
    seen.add(rule)
    words = set()
    for name in re.findall(r'\b[A-Za-z_]\w*\b', rules.get(rule, '')):
        if name in literals:
            words.add(literals[name])
        elif name in rules:
            words.update(words_in_rule(name, seen))
    return words
source += '\nvar showConstraintKindVocabulary = []string{\n'
for word in sorted(words_in_rule('showConstraintKind', set())):
    source += '\t"' + word + '",\n'
source += '}\n'
(root / 'query_body_vocabulary_generated.go').write_text(source)

# FIRST sets must start at each production's entry. Unioning the lookahead of
# its internal ATN decisions is different (and omits rules without decisions).
# Parse the grammar's EBNF, then compute FIRST and nullability to a fixed point.
# This text-only generator does not load or execute product code.
class Production:
    def __init__(self, body):
        body = re.sub(r'\{[^{}]*\}\??', '', body)  # predicates consume no token
        body = re.sub(r'\b[a-z]\w*\s*\+?=', '', body)  # element labels
        self.tokens = re.findall(r'[A-Za-z_]\w*|[()|?*+.]', body)
        residue = re.sub(r'[A-Za-z_]\w*|[()|?*+.]|\s+', '', body)
        if residue:
            raise ValueError('unsupported grammar syntax: ' + residue)
        self.at = 0
        self.tree = self.alternatives()
        if self.at != len(self.tokens):
            raise ValueError('unconsumed grammar tokens')

    def alternatives(self):
        branches = [self.sequence()]
        while self.at < len(self.tokens) and self.tokens[self.at] == '|':
            self.at += 1
            branches.append(self.sequence())
        return ('alt', branches)

    def sequence(self):
        parts = []
        while self.at < len(self.tokens) and self.tokens[self.at] not in {')', '|'}:
            token = self.tokens[self.at]
            self.at += 1
            if token == '(':
                node = self.alternatives()
                if self.tokens[self.at] != ')':
                    raise ValueError('unclosed grammar group')
                self.at += 1
            else:
                node = ('name', token)
            if self.at < len(self.tokens) and self.tokens[self.at] in {'?', '*', '+'}:
                node = (self.tokens[self.at], node)
                self.at += 1
                # Non-greedy wildcard repetition has the same FIRST set.
                if self.at < len(self.tokens) and self.tokens[self.at] == '?':
                    self.at += 1
            parts.append(node)
        return ('seq', parts)

def first_of(node, first, nullable):
    kind, value = node
    if kind == 'name':
        if value in rules:
            return first[value], nullable[value]
        return {value}, False
    if kind in {'?', '*', '+'}:
        words, empty = first_of(value, first, nullable)
        return words, kind != '+' or empty
    words, empty = set(), kind == 'seq'
    for child in value:
        child_words, child_empty = first_of(child, first, nullable)
        words |= child_words
        if kind == 'seq':
            empty &= child_empty
            if not child_empty:
                break
        else:
            empty |= child_empty
    return words, empty

trees = {rule: Production(body).tree for rule, body in rules.items()}
first, nullable = {rule: set() for rule in rules}, {rule: False for rule in rules}
while True:
    updates = {rule: first_of(tree, first, nullable) for rule, tree in trees.items()}
    if all(words == first[rule] and empty == nullable[rule] for rule, (words, empty) in updates.items()):
        break
    first = {rule: words for rule, (words, _) in updates.items()}
    nullable = {rule: empty for rule, (_, empty) in updates.items()}

# Generator controls exercise entry sequencing, alternation and nullability.
assert first_of(Production('RETURN expression orderSt?').tree, first, nullable)[0] == {'RETURN'}
assert first_of(Production('OPTIONAL? MATCH pattern').tree, first, nullable)[0] == {'OPTIONAL', 'MATCH'}
assert first_of(Production('(where | orderSt)? limitSt').tree, first, nullable)[0] == {'WHERE', 'ORDER', 'LIMIT'}
for rule, token in [('where', 'WHERE'), ('orderSt', 'ORDER'), ('skipSt', 'SKIP_W'), ('limitSt', 'LIMIT')]:
    assert first[rule] == {token}, (rule, first[rule])

source = '// Code generated by generate_vocabulary.py from CypherParser.g4; DO NOT EDIT.\n\npackage antlr\n\n'
source += '// grammarFirstWords contains FIRST at rule entry, not internal decisions.\n'
source += 'var grammarFirstWords = map[int][]string{\n'
for rule in sorted(rules):
    words = sorted({literals[token] for token in first[rule] if token in literals})
    source += '\tCypherParserRULE_' + rule + ': {' + ', '.join('"' + word + '"' for word in words) + '},\n'
source += '}\n'
(root / 'rule_first_vocabulary_generated.go').write_text(source)

# A query's required direct rule alternatives are its statement bodies. The
# envelope's optional/repeated prefixes cannot become another body owner.
def required_rule_references(node):
    kind, value = node
    if kind == 'name':
        return {value} if value in rules else set()
    if kind in {'?', '*', '+'}:
        return set()
    return set().union(*(required_rule_references(child) for child in value))

bodies = required_rule_references(trees['query'])
assert 'regularQuery' in bodies and 'queryPrefix' not in bodies and 'useClause' not in bodies
source = '// Code generated by generate_vocabulary.py from CypherParser.g4; DO NOT EDIT.\n\npackage antlr\n\n'
source += '// statementBodyRules is the required body union of the query envelope.\n'
source += 'var statementBodyRules = map[int]bool{\n'
for rule in sorted(bodies):
    source += '\tCypherParserRULE_' + rule + ': true,\n'
source += '}\n'

def names_of(node):
    kind, value = node
    if kind == 'name':
        return {value}
    if kind in {'?', '*', '+'}:
        return names_of(value)
    return set().union(*(names_of(child) for child in value))

def alternatives_of(node):
    kind, value = node
    if kind == 'alt':
        yield from value
    if kind in {'?', '*', '+'}:
        yield from alternatives_of(value)
    elif kind in {'seq', 'alt'}:
        for child in value:
            yield from alternatives_of(child)

index_heads = [node for node in alternatives_of(trees['showCommand'])
               if {'INDEX', 'INDEXES'} <= names_of(node)]
index_head = min(index_heads, key=lambda node: len(names_of(node)))
index_starts, _ = first_of(index_head, first, nullable)
modifiers = sorted(literals[token] for token in index_starts - {'INDEX', 'INDEXES'} if token in literals)
source += '\nvar showIndexModifiers = []string{' + ', '.join('"' + word + '"' for word in modifiers) + '}\n'
(root / 'statement_entry_vocabulary_generated.go').write_text(source)
