// Every registered consumer supplies the positive fixture for its domain.
// Mutate each domain reference independently, without compiling fake packages
// or touching the production checkout. Assert the semantic diagnostic even
// where a mixed RawMessage envelope also has a frozen protocol exception.
func TestNumericDomainPolicyMutations(t *testing.T) {
	root := numericWireRoot()
	paths := map[string]jsonDataPath{}
	exceptions := map[string]wireException{}
	raw, err := os.ReadFile(filepath.Join(root, "pkg/convert/json_data_paths.json"))
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(raw, &paths))
	raw, err = os.ReadFile(filepath.Join(root, "pkg/convert/numeric_wire_exceptions.json"))
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(raw, &exceptions))
	for key, contract := range paths {
		t.Run(key, func(t *testing.T) {
			relative, name, _ := strings.Cut(key, ":")
			source, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(relative)))
			require.NoError(t, err)
			positions := token.NewFileSet()
			parsed, err := parser.ParseFile(positions, relative, source, 0)
			require.NoError(t, err)
			prefix := "package fixture\nimport (\n"
			convertAlias := ""
			for _, spec := range parsed.Imports {
				alias := ""
				if spec.Name != nil {
					alias = spec.Name.Name + " "
				}
				prefix += alias + spec.Path.Value + "\n"
				path, _ := strconv.Unquote(spec.Path.Value)
				if path == "github.com/orneryd/nornicdb/pkg/convert" {
					convertAlias = strings.TrimSpace(alias)
					if convertAlias == "" {
						convertAlias = "convert"
					}
				}
			}
			prefix += ")\n"
			var function *ast.FuncDecl
			for _, decl := range parsed.Decls {
				if candidate, ok := decl.(*ast.FuncDecl); ok && numericWireFunctionName(candidate) == name {
					function = candidate
					break
				}
			}
			require.NotNil(t, function)
			start, end := positions.Position(function.Pos()).Offset, positions.Position(function.End()).Offset
			definition := string(source[start:end])
			paths := map[string]jsonDataPath{key: contract}
			approved := map[string]wireException{}
			if exception, ok := exceptions[key]; ok {
				approved[key] = exception
			}
			positive := t.TempDir()
			writeNumericWireFixture(t, positive, relative, prefix+definition)
			require.Empty(t, inspectNumericWire(positive, paths, approved, true), "correct domain must be accepted")
			mutations := 0
			ast.Inspect(function.Body, func(node ast.Node) bool {
				if call, ok := node.(*ast.CallExpr); ok {
					var name *ast.Ident
					switch function := call.Fun.(type) {
					case *ast.Ident:
						name = function
					case *ast.SelectorExpr:
						name = function.Sel
					}
					if name != nil && (name.Name == "EncodeSchemaDefinition" || name.Name == "DecodeSchemaDefinition") {
						opposite := "EncodeSchemaDefinition"
						if name.Name == opposite {
							opposite = "DecodeSchemaDefinition"
						}
						at := positions.Position(name.Pos()).Offset - start
						mutated := definition[:at] + opposite + definition[at+len(name.Name):]
						target := t.TempDir()
						writeNumericWireFixture(t, target, relative, prefix+mutated)
						violations := inspectNumericWire(target, paths, approved, true)
						require.Contains(t, strings.Join(violations, "\n"), "NUMERIC_JSON_PATH "+key)
						mutations++
					}
				}
				selector, ok := node.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				owner, ok := selector.X.(*ast.Ident)
				if !ok || owner.Name != convertAlias {
					return true
				}
				opposite := ""
				switch selector.Sel.Name {
				case "PropertyJSON":
					opposite = "CypherInputJSON"
				case "CypherInputJSON":
					opposite = "PropertyJSON"
				default:
					return true
				}
				at := positions.Position(selector.Sel.Pos()).Offset - start
				mutated := definition[:at] + opposite + definition[at+len(selector.Sel.Name):]
				t.Run(fmt.Sprintf("wrong-domain-%d", mutations), func(t *testing.T) {
					target := t.TempDir()
					writeNumericWireFixture(t, target, relative, prefix+mutated)
					violations := inspectNumericWire(target, paths, approved, true)
					require.Contains(t, strings.Join(violations, "\n"), "NUMERIC_JSON_PATH "+key, "wrong policy must fail the semantic check")
				})
				mutations++
				return true
			})
			require.Greater(t, mutations, 0)
		})
	}
}
