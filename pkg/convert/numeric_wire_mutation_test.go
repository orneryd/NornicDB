func writeNumericWireFixture(t *testing.T, root, path, source string) {
	t.Helper()
	path = filepath.Join(root, filepath.FromSlash(path))
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0700))
	require.NoError(t, os.WriteFile(path, []byte(source), 0600))
}

func TestNumericDomainRawReaderMutations(t *testing.T) {
	for _, directory := range []string{"pkg/storage", "pkg/replication", "apoc/import", "pkg/new_property_boundary"} {
		for name, source := range map[string]string{
			"generated-reader": `// Code generated by an application tool. DO NOT EDIT.
import "encoding/json"
func bypass(data []byte) (any,error) {var value any;err:=json.Unmarshal(data,&value);return value,err}`,
			"unmarshal-any": `import "encoding/json"
func bypass(data []byte) (any,error) {var value any;err:=json.Unmarshal(data,&value);return value,err}`,
			"unmarshal-map": `import j "encoding/json"
func bypass(data []byte) (map[string]any,error) {var value map[string]any;err:=j.Unmarshal(data,&value);return value,err}`,
			"decoder-interface": `import("encoding/json";"io")
func bypass(reader io.Reader) (interface{},error) {var value interface{};err:=json.NewDecoder(reader).Decode(&value);return value,err}`,
			"method-value": `import "encoding/json"
func bypass(data []byte) (any,error) {read:=json.Unmarshal;var value any;err:=read(data,&value);return value,err}`,
			"initializer": `import "encoding/json"
var read=json.Unmarshal`,
			"writer-control": `import "encoding/json"
func bypass(value any) ([]byte,error) {return json.Marshal(value)}`,
			"numeric-writer": `import n "strconv"
func bypass(dst []byte, value int64) []byte {return n.AppendInt(dst,value,10)}`,
			"unclassified-domain": `import c "github.com/orneryd/nornicdb/pkg/convert"
func bypass(data []byte) error {var value any;return c.CypherInputJSON.Unmarshal(data,&value)}`,
			"escaped-domain": `import c "github.com/orneryd/nornicdb/pkg/convert"
func bypass(data []byte) error {codec:=c.PropertyJSON;var value any;return codec.Unmarshal(data,&value)}`,
		} {
			t.Run(directory+"/"+name, func(t *testing.T) {
				root := t.TempDir()
				writeNumericWireFixture(t, root, directory+"/new.go", "package fixture\n"+source)
				require.NotEmpty(t, inspectNumericWire(root, nil, nil, false), "a new reader/writer must not bypass ownership or classification")
			})
		}
		root := t.TempDir()
		writeNumericWireFixture(t, root, "pkg/convert/escape.go", `package convert
import "io"
func escape(reader io.Reader) { _ = newJSONDecoder(reader,jsonNumberPolicy{}) }`)
		require.Contains(t, strings.Join(inspectNumericWire(root, nil, nil, false), "\n"), "private codec accessed outside its domain owner")
	}
}

