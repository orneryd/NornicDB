package storage

import (
	"bytes"
	"encoding/gob"
	"fmt"
)

func encodeV4GobValue(value any) ([]byte, error) {
	var data bytes.Buffer
	if err := gob.NewEncoder(&data).Encode(value); err != nil {
		return nil, err
	}
	return data.Bytes(), nil
}

// encodeV4GobEntityTransactionChange creates the historical format explicitly,
// independent of the current runtime encoders.
func encodeV4GobEntityTransactionChange(op Operation) (v4GobEntityTransactionChange, error) {
	var change v4GobEntityTransactionChange
	var err error
	switch op.Type {
	case OpCreateNode, OpUpdateNode:
		if op.Node == nil {
			return change, ErrInvalidData
		}
		node := *op.Node
		change.NamedProperties, err = EncodeNamedProperties(node.Properties)
		if err != nil {
			return change, err
		}
		change.EmbedMeta, err = EncodeNamedProperties(node.EmbedMeta)
		if err != nil {
			return change, err
		}
		change.VisibilitySuppressed = node.RuntimeMetadata().VisibilitySuppressed
		node.Properties = nil
		change.Data, err = encodeV4GobValue(&v4GobNodePayload{
			ID: string(node.ID), Labels: node.Labels, Properties: node.Properties,
			NamedEmbeddings: node.NamedEmbeddings, ChunkEmbeddings: node.ChunkEmbeddings,
			CreatedAtUnixNs: node.CreatedAt.UnixNano(), UpdatedAtUnixNs: node.UpdatedAt.UnixNano(),
		})
		change.Type = EntityCreateNode
		if op.Type == OpUpdateNode {
			change.Type = EntityUpdateNode
		}
	case OpCreateEdge, OpUpdateEdge:
		if op.Edge == nil {
			return change, ErrInvalidData
		}
		edge := *op.Edge
		change.NamedProperties, err = EncodeNamedProperties(edge.Properties)
		if err != nil {
			return change, err
		}
		if !edge.UpdatedAt.IsZero() {
			change.UpdatedAtUnixNs = edge.UpdatedAt.UnixNano()
		}
		change.VisibilitySuppressed = edge.VisibilitySuppressed
		edge.Properties = nil
		payload := v4GobEdgePayload{ID: string(edge.ID), StartNode: string(edge.StartNode), EndNode: string(edge.EndNode), Type: edge.Type, Properties: edge.Properties, Confidence: edge.Confidence, AutoGenerated: edge.AutoGenerated}
		if !edge.CreatedAt.IsZero() {
			payload.CreatedAt = edge.CreatedAt.UnixNano()
		}
		change.Data, err = encodeV4GobValue(&payload)
		change.Type = EntityCreateEdge
		if op.Type == OpUpdateEdge {
			change.Type = EntityUpdateEdge
		}
	case OpDeleteNode:
		change.Type = EntityDeleteNode
		change.Data, err = encodeV4GobValue(struct{ NodeID string }{string(op.NodeID)})
	case OpDeleteEdge:
		change.Type = EntityDeleteEdge
		change.Data, err = encodeV4GobValue(struct{ EdgeID string }{string(op.EdgeID)})
	default:
		return change, fmt.Errorf("not an entity operation: %s", op.Type)
	}
	return change, err
}

// encodeV4GobEntityTransaction constructs a historical fixture only.
func encodeV4GobEntityTransaction(namespace, logicalID string, ops []Operation, modes ...EntityCommitMode) ([]byte, error) {
	envelope := v4GobEntityTransactionEnvelope{Version: entityTransactionV4GobVersion, Namespace: namespace, LogicalTxID: logicalID}
	if len(modes) > 1 {
		return nil, ErrInvalidData
	}
	if len(modes) == 1 {
		if !modes[0].valid() {
			return nil, ErrInvalidData
		}
		envelope.Mode = modes[0]
	}
	if len(ops) != 0 {
		envelope.Changes = make([]v4GobEntityTransactionChange, 0, len(ops))
	}
	for _, op := range ops {
		change, err := encodeV4GobEntityTransactionChange(op)
		if err != nil {
			return nil, err
		}
		envelope.Changes = append(envelope.Changes, change)
	}
	return encodeV4GobValue(envelope)
}
