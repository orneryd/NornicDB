// TestHiddenCreateConflictPolicy is the storage-owner contract shared by
// direct, bulk and explicit-transaction callers. A node's physical ID is
// never reusable. A relationship's physical ID is idempotent only when the
// stored hidden body has the same type, endpoints and properties. Creation
// timestamps and derived visibility/import bookkeeping are excluded because
// retries generate them anew and they do not identify the graph relationship.
func TestHiddenCreateConflictPolicy(t *testing.T) {
	type createRoute struct {
		name string
		node func(*testing.T, *BadgerEngine, *Node) error
		edge func(*testing.T, *BadgerEngine, *Edge) error
	}
	routes := []createRoute{
		{
			name: "direct",
			node: func(_ *testing.T, engine *BadgerEngine, node *Node) error {
				_, err := engine.CreateNode(node)
				return err
			},
			edge: func(_ *testing.T, engine *BadgerEngine, edge *Edge) error {
				return engine.CreateEdge(edge)
			},
		},
		{
			name: "bulk",
			node: func(_ *testing.T, engine *BadgerEngine, node *Node) error {
				return engine.BulkCreateNodes([]*Node{node})
			},
			edge: func(_ *testing.T, engine *BadgerEngine, edge *Edge) error {
				return engine.BulkCreateEdges([]*Edge{edge})
			},
		},
		{
			name: "explicit transaction",
			node: func(t *testing.T, engine *BadgerEngine, node *Node) error {
				tx, err := engine.BeginTransaction()
				require.NoError(t, err)
				require.NoError(t, tx.SetNamespace("test"))
				if _, err = tx.CreateNode(node); err != nil {
					_ = tx.Rollback()
					return err
				}
				return tx.Commit()
			},
			edge: func(t *testing.T, engine *BadgerEngine, edge *Edge) error {
				tx, err := engine.BeginTransaction()
				require.NoError(t, err)
				require.NoError(t, tx.SetNamespace("test"))
				if err = tx.CreateEdge(edge); err != nil {
					_ = tx.Rollback()
					return err
				}
				return tx.Commit()
			},
		},
	}

	for _, buffered := range []bool{false, true} {
		for _, route := range routes {
			name := route.name + "/sync"
			if buffered {
				name = route.name + "/write-behind"
			}
			t.Run(name, func(t *testing.T) {
				dir := t.TempDir()
				open := func() *BadgerEngine {
					engine, err := NewBadgerEngineWithOptions(BadgerOptions{
						DataDir: dir, WriteBehind: buffered, WriteBehindInterval: time.Hour,
					})
					require.NoError(t, err)
					return engine
				}
				engine := open()
				for _, node := range []*Node{
					{ID: "test:a", Labels: []string{"A"}},
					{ID: "test:b", Labels: []string{"B"}},
					{ID: "test:c", Labels: []string{"C"}},
					{ID: "test:d", Labels: []string{"D"}},
					{ID: "test:hidden-node", Labels: []string{"Original"}, Properties: map[string]any{"value": int64(1)}},
				} {
					_, err := engine.CreateNode(node)
					require.NoError(t, err)
				}
				createdAt := time.Now().Add(-time.Hour).UTC().Round(time.Microsecond)
				originals := []*Edge{
					{ID: "test:identical", StartNode: "test:a", EndNode: "test:b", Type: "LINK", Properties: map[string]any{"key": "same", "rank": int64(7)}, CreatedAt: createdAt, UpdatedAt: createdAt, Confidence: 0.25, AutoGenerated: true},
					{ID: "test:different", StartNode: "test:c", EndNode: "test:d", Type: "LINK", Properties: map[string]any{"key": "old"}, CreatedAt: createdAt, UpdatedAt: createdAt},
				}
				for _, edge := range originals {
					require.NoError(t, engine.CreateEdge(edge))
				}
				if buffered {
					require.NoError(t, engine.FlushWriteBehind())
				}
				require.NoError(t, engine.SetNodeManuallySuppressed("test:hidden-node", true))
				require.NoError(t, engine.SetEdgeManuallySuppressed("test:identical", true))
				require.NoError(t, engine.SetEdgeManuallySuppressed("test:different", true))

				beforeIdentical, err := engine.GetStoredEdge("test:identical")
				require.NoError(t, err)
				beforeIdentical = comparableStoredEdge(beforeIdentical)
				beforeDifferent, err := engine.GetStoredEdge("test:different")
				require.NoError(t, err)
				beforeDifferent = comparableStoredEdge(beforeDifferent)
				beforeNode, err := engine.GetStoredNode("test:hidden-node")
				require.NoError(t, err)
				beforeNode = comparableStoredNode(beforeNode)
				createdCallbacks, updatedCallbacks, deletedCallbacks := 0, 0, 0
				engine.OnEdgeCreated(func(*Edge) { createdCallbacks++ })
				engine.OnEdgeUpdated(func(*Edge) { updatedCallbacks++ })
				engine.OnEdgeDeleted(func(EdgeID) { deletedCallbacks++ })

				// Different timestamps, confidence, generated and suppression flags
				// are bookkeeping; the semantic relationship image is identical.
				retry := &Edge{
					ID: "test:identical", StartNode: "test:a", EndNode: "test:b", Type: "LINK",
					Properties: map[string]any{"rank": int64(7), "key": "same"},
					CreatedAt:  time.Now(), UpdatedAt: time.Now(), Confidence: 0.99,
				}
				require.NoError(t, route.edge(t, engine, retry))
				require.ErrorIs(t, route.edge(t, engine, &Edge{
					ID: "test:different", StartNode: "test:c", EndNode: "test:d", Type: "LINK",
					Properties: map[string]any{"key": "new"},
				}), ErrAlreadyExists)
				require.ErrorIs(t, route.node(t, engine, &Node{
					ID: "test:hidden-node", Labels: []string{"Replacement"}, Properties: map[string]any{"value": int64(2)},
				}), ErrAlreadyExists)

				check := func(stage string) {
					t.Helper()
					got, err := engine.GetStoredEdge("test:identical")
					require.NoError(t, err, stage)
					require.Equal(t, beforeIdentical, comparableStoredEdge(got), stage+": identical retry changed the stored body")
					got, err = engine.GetStoredEdge("test:different")
					require.NoError(t, err, stage)
					require.Equal(t, beforeDifferent, comparableStoredEdge(got), stage+": rejected retry changed the stored body")
					gotNode, err := engine.GetStoredNode("test:hidden-node")
					require.NoError(t, err, stage)
					require.Equal(t, beforeNode, comparableStoredNode(gotNode), stage+": rejected node retry changed the stored body")
					for _, id := range []EdgeID{"test:identical", "test:different"} {
						_, err = engine.GetEdge(id)
						require.ErrorIs(t, err, ErrNotFound, stage+": relationship must remain hidden")
					}
					_, err = engine.GetNode("test:hidden-node")
					require.ErrorIs(t, err, ErrNotFound, stage+": node must remain hidden")
					edgeCount, err := engine.EdgeCount()
					require.EqualValues(t, 2, mustCount(t, edgeCount, err), stage+": physical edge count")
					typeCount, err := engine.EdgeCountByType("LINK")
					require.EqualValues(t, 2, mustCount(t, typeCount, err), stage+": type count")
					outgoingA, err := engine.GetStoredOutgoingEdges("test:a")
					require.Equal(t, []string{"test:identical"}, sortedStoredEdgeIDs(t, outgoingA, err), stage+": old outgoing adjacency")
					incomingB, err := engine.GetStoredIncomingEdges("test:b")
					require.Equal(t, []string{"test:identical"}, sortedStoredEdgeIDs(t, incomingB, err), stage+": old incoming adjacency")
					outgoingC, err := engine.GetStoredOutgoingEdges("test:c")
					require.Equal(t, []string{"test:different"}, sortedStoredEdgeIDs(t, outgoingC, err), stage+": rejected outgoing adjacency")
					incomingD, err := engine.GetStoredIncomingEdges("test:d")
					require.Equal(t, []string{"test:different"}, sortedStoredEdgeIDs(t, incomingD, err), stage+": rejected incoming adjacency")
					byType, err := engine.GetStoredEdgesByType("LINK")
					require.Equal(t, []string{"test:different", "test:identical"}, sortedStoredEdgeIDs(t, byType, err), stage+": type index")
					all, err := CollectStoredEdges(context.Background(), engine)
					require.NoError(t, err)
					require.Len(t, all, 2, stage+": no second relationship")
				}
				check("acknowledged")
				require.Zero(t, createdCallbacks, "no CREATE callback/search publication")
				require.Zero(t, updatedCallbacks, "no UPDATE callback/search publication")
				require.Zero(t, deletedCallbacks, "no DELETE callback/search publication")
				if buffered {
					require.NoError(t, engine.FlushWriteBehind())
					check("flushed")
				}
				require.NoError(t, engine.Close())
				engine = open()
				t.Cleanup(func() { _ = engine.Close() })
				check("reopened")
			})
		}
	}
}

// A hidden-ID candidate is compared only after same-transaction writes have
// produced the image commit would publish. This is the storage owner used by
// MERGE ... ON CREATE SET and later SET clauses.
func TestHiddenEdgeCreateUsesFinalTransactionImage(t *testing.T) {
	for _, buffered := range []bool{false, true} {
		name := "sync"
		if buffered {
			name = "write-behind"
		}
		t.Run(name, func(t *testing.T) {
			engine, err := NewBadgerEngineWithOptions(BadgerOptions{
				DataDir: t.TempDir(), WriteBehind: buffered, WriteBehindInterval: time.Hour,
			})
			require.NoError(t, err)
			t.Cleanup(func() { _ = engine.Close() })
			for _, id := range []NodeID{"test:a", "test:b"} {
				_, err := engine.CreateNode(&Node{ID: id})
				require.NoError(t, err)
			}
			stored := &Edge{
				ID: "test:r", StartNode: "test:a", EndNode: "test:b", Type: "LINK",
				Properties: map[string]any{"key": "same", "payload": "stored"},
			}
			require.NoError(t, engine.CreateEdge(stored))
			if buffered {
				require.NoError(t, engine.FlushWriteBehind())
			}
			require.NoError(t, engine.SetEdgeManuallySuppressed(stored.ID, true))
			before, err := engine.GetStoredEdge(stored.ID)
			require.NoError(t, err)
			before = comparableStoredEdge(before)

			begin := func() *BadgerTransaction {
				t.Helper()
				tx, err := engine.BeginTransaction()
				require.NoError(t, err)
				require.NoError(t, tx.SetNamespace("test"))
				return tx
			}
			candidate := &Edge{
				ID: stored.ID, StartNode: stored.StartNode, EndNode: stored.EndNode, Type: stored.Type,
				Properties: map[string]any{"key": "same"},
			}
			tx := begin()
			require.NoError(t, tx.CreateEdge(candidate))
			require.True(t, tx.EdgeCreateWasNoOp(candidate.ID))
			_, err = tx.GetEdge(candidate.ID)
			require.ErrorIs(t, err, ErrNotFound, "the hidden-only candidate must not enter the visible point-read overlay")
			between, err := tx.GetEdgesBetween(candidate.StartNode, candidate.EndNode)
			require.NoError(t, err)
			require.Empty(t, between, "the hidden-only candidate must not enter relationship matching")
			candidate.Properties["payload"] = "stored"
			require.NoError(t, tx.UpdateEdge(candidate))
			repeated := &Edge{
				ID: stored.ID, StartNode: stored.StartNode, EndNode: stored.EndNode, Type: stored.Type,
				Properties: map[string]any{"key": "same"},
			}
			require.NoError(t, tx.CreateEdge(repeated), "a repeated hidden-ID admission reuses the hidden-only disposition")
			repeated.Properties["payload"] = "stored"
			require.NoError(t, tx.UpdateEdge(repeated))
			require.NoError(t, tx.Commit(), "the final image, not the intermediate CREATE image, decides identity")

			different := &Edge{
				ID: stored.ID, StartNode: stored.StartNode, EndNode: stored.EndNode, Type: stored.Type,
				Properties: map[string]any{"key": "same"},
			}
			tx = begin()
			require.NoError(t, tx.CreateEdge(different))
			different.Properties["payload"] = "different"
			require.NoError(t, tx.UpdateEdge(different))
			err = tx.Commit()
			var conflict *HiddenEdgeIdentityConflictError
			require.ErrorAs(t, err, &conflict)
			require.ErrorIs(t, err, ErrAlreadyExists)
			require.Equal(t, "Neo.ClientError.Schema.ConstraintValidationFailed", conflict.BoltErrorCode())

			if buffered {
				require.NoError(t, engine.FlushWriteBehind())
			}
			after, err := engine.GetStoredEdge(stored.ID)
			require.NoError(t, err)
			require.Equal(t, before, comparableStoredEdge(after))
			count, err := engine.EdgeCount()
			require.NoError(t, err)
			require.EqualValues(t, 1, count)
		})
	}
}

func mustCount(t *testing.T, count int64, err error) int64 {
	t.Helper()
	require.NoError(t, err)
	return count
}

func sortedStoredEdgeIDs(t *testing.T, edges []*Edge, err error) []string {
	t.Helper()
	require.NoError(t, err)
	ids := make([]string, 0, len(edges))
	for _, edge := range edges {
		ids = append(ids, string(edge.ID))
	}
	sort.Strings(ids)
	return ids
}

func comparableStoredNode(node *Node) *Node {
	out := copyNode(node)
	if out != nil {
		out.CreatedAt = out.CreatedAt.Round(0)
		out.UpdatedAt = out.UpdatedAt.Round(0)
	}
	return out
}

func comparableStoredEdge(edge *Edge) *Edge {
	out := copyEdge(edge)
	if out != nil {
		out.CreatedAt = out.CreatedAt.Round(0)
		out.UpdatedAt = out.UpdatedAt.Round(0)
	}
	return out
}

// A hidden-ID candidate is transaction state with its own lifecycle: it keeps
// an operation-free transaction on the commit path, a DELETE drops it, and the
// commit owner re-reads the predecessor, so a candidate whose predecessor was
// revealed or replaced by another writer is not acknowledged as a no-op.
func TestHiddenEdgeCandidateLifecycle(t *testing.T) {
	engine, err := NewBadgerEngineWithOptions(BadgerOptions{DataDir: t.TempDir()})
	require.NoError(t, err)
	t.Cleanup(func() { _ = engine.Close() })
	for _, id := range []NodeID{"test:a", "test:b"} {
		_, err := engine.CreateNode(&Node{ID: id})
		require.NoError(t, err)
	}
	stored := &Edge{ID: "test:r", StartNode: "test:a", EndNode: "test:b", Type: "LINK", Properties: map[string]any{"key": "same"}}
	require.NoError(t, engine.CreateEdge(stored))
	require.NoError(t, engine.SetEdgeManuallySuppressed(stored.ID, true))
	before, err := engine.GetStoredEdge(stored.ID)
	require.NoError(t, err)
	before = comparableStoredEdge(before)
	begin := func() *BadgerTransaction {
		t.Helper()
		tx, err := engine.BeginTransaction()
		require.NoError(t, err)
		require.NoError(t, tx.SetNamespace("test"))
		return tx
	}
	candidate := func(edgeType string) *Edge {
		return &Edge{ID: stored.ID, StartNode: stored.StartNode, EndNode: stored.EndNode, Type: edgeType, Properties: map[string]any{"key": "same"}}
	}
	var none *BadgerTransaction
	require.False(t, none.EdgeCreateWasNoOp(stored.ID))

	t.Run("delete drops the candidate", func(t *testing.T) {
		tx := begin()
		require.False(t, tx.RequiresCommitValidation())
		require.NoError(t, tx.CreateEdge(candidate("LINK")))
		require.True(t, tx.RequiresCommitValidation(), "an operation-free candidate still needs the commit owner")
		require.Zero(t, tx.OperationCount())
		require.NoError(t, tx.DeleteEdge(stored.ID))
		require.False(t, tx.EdgeCreateWasNoOp(stored.ID))
		require.False(t, tx.RequiresCommitValidation())
		require.NoError(t, tx.Commit())
		after, err := engine.GetStoredEdge(stored.ID)
		require.NoError(t, err)
		require.Equal(t, before, comparableStoredEdge(after), "CREATE then DELETE of a hidden candidate leaves its predecessor untouched")
	})

	t.Run("different type conflicts", func(t *testing.T) {
		tx := begin()
		require.NoError(t, tx.CreateEdge(candidate("OTHER")))
		err := tx.Commit()
		var conflict *HiddenEdgeIdentityConflictError
		require.ErrorAs(t, err, &conflict)
		require.Contains(t, conflict.Error(), "stored hidden relationship r ", "the client message names the user-space ID")
		require.Equal(t, "RelationshipIdentityConflict", conflict.BoltErrorDetail())
	})

	t.Run("re-create after delete checks endpoints", func(t *testing.T) {
		visible := &Edge{ID: "test:v", StartNode: "test:a", EndNode: "test:b", Type: "LINK"}
		require.NoError(t, engine.CreateEdge(visible))
		tx := begin()
		defer func() { _ = tx.Rollback() }()
		require.NoError(t, tx.DeleteEdge(visible.ID))
		err := tx.CreateEdge(&Edge{ID: visible.ID, StartNode: "test:missing", EndNode: "test:b", Type: "LINK"})
		require.ErrorIs(t, err, ErrNotFound)
		err = tx.CreateEdge(&Edge{ID: visible.ID, StartNode: "test:a", EndNode: "test:missing", Type: "LINK"})
		require.ErrorIs(t, err, ErrNotFound)
		require.NoError(t, tx.CreateEdge(&Edge{ID: visible.ID, StartNode: "test:a", EndNode: "test:b", Type: "LINK"}))
	})

	t.Run("empty property sets are identical", func(t *testing.T) {
		require.NoError(t, engine.CreateEdge(&Edge{ID: "test:empty", StartNode: "test:a", EndNode: "test:b", Type: "LINK"}))
		require.NoError(t, engine.SetEdgeManuallySuppressed("test:empty", true))
		tx := begin()
		require.NoError(t, tx.CreateEdge(&Edge{ID: "test:empty", StartNode: "test:a", EndNode: "test:b", Type: "LINK", Properties: map[string]any{}}))
		require.NoError(t, tx.Commit())
	})

	t.Run("a candidate the codec cannot store fails at commit", func(t *testing.T) {
		tx := begin()
		unstorable := candidate("LINK")
		unstorable.Properties["value"] = make(chan int)
		require.NoError(t, tx.CreateEdge(unstorable))
		err := tx.Commit()
		require.Error(t, err)
		var conflict *HiddenEdgeIdentityConflictError
		require.False(t, errors.As(err, &conflict), "an encoding failure is not an identity verdict")
		after, err := engine.GetStoredEdge(stored.ID)
		require.NoError(t, err)
		require.Equal(t, before, comparableStoredEdge(after))
	})

	t.Run("revealed predecessor is not a no-op", func(t *testing.T) {
		tx := begin()
		require.NoError(t, tx.CreateEdge(candidate("LINK")))
		require.NoError(t, engine.SetEdgeManuallySuppressed(stored.ID, false))
		t.Cleanup(func() { require.NoError(t, engine.SetEdgeManuallySuppressed(stored.ID, true)) })
		require.ErrorIs(t, tx.Commit(), ErrAlreadyExists)
	})
}

// The commit owner compares a candidate with the stored body as the property
// codec would commit it, for every value kind the codec transforms: typed and
// generic lists, nested lists and maps, numeric widths, temporal values and
// byte arrays. Direct, bulk and transaction creates share that owner.
func TestHiddenEdgeIdentityUsesStoredValueRepresentation(t *testing.T) {
	zone := time.FixedZone("plus-one", 3600)
	cases := []struct {
		name            string
		same, different func() any
	}{
		{"generic string list", func() any { return []interface{}{"a", "b"} }, func() any { return []interface{}{"a"} }},
		{"Go int list", func() any { return []int{1, 2} }, func() any { return []int{2, 1} }},
		{"int32", func() any { return int32(7) }, func() any { return int32(8) }},
		{"float32", func() any { return float32(1.5) }, func() any { return float32(2.5) }},
		{"uint64", func() any { return uint64(1) << 63 }, func() any { return uint64(1)<<63 + 1 }},
		{"mixed list", func() any { return []interface{}{int64(1), "a", true} }, func() any { return []interface{}{int64(1), "a", false} }},
		{"nested lists", func() any { return []interface{}{[]interface{}{1.5, 2.5}, []interface{}{"x"}} }, func() any { return []interface{}{[]interface{}{1.5}, []interface{}{"x"}} }},
		{"nested map", func() any {
			return map[string]interface{}{"a": []interface{}{int64(1), int64(2)}, "b": map[string]interface{}{"c": "d"}}
		}, func() any {
			return map[string]interface{}{"a": []interface{}{int64(1), int64(2)}, "b": map[string]interface{}{"c": "e"}}
		}},
		{"byte array", func() any { return []byte{1, 2, 3} }, func() any { return []byte{1, 2, 4} }},
		{"zoned time", func() any { return time.Date(2024, 1, 2, 3, 4, 5, 6, zone) }, func() any { return time.Date(2024, 1, 2, 3, 4, 5, 7, zone) }},
		{"time list", func() any { return []interface{}{time.Date(2024, 1, 2, 0, 0, 0, 0, time.UTC)} }, func() any {
			return []interface{}{time.Date(2024, 1, 3, 0, 0, 0, 0, time.UTC)}
		}},
	}
	for _, buffered := range []bool{false, true} {
		for _, tc := range cases {
			t.Run(fmt.Sprintf("write-behind=%v/%s", buffered, tc.name), func(t *testing.T) {
				engine, err := NewBadgerEngineWithOptions(BadgerOptions{
					DataDir: t.TempDir(), WriteBehind: buffered, WriteBehindInterval: time.Hour,
				})
				require.NoError(t, err)
				t.Cleanup(func() { _ = engine.Close() })
				for _, id := range []NodeID{"test:a", "test:b"} {
					_, err := engine.CreateNode(&Node{ID: id})
					require.NoError(t, err)
				}
				edge := func(value any) *Edge {
					return &Edge{ID: "test:r", StartNode: "test:a", EndNode: "test:b", Type: "LINK",
						Properties: map[string]any{"key": "same", "value": value}}
				}
				require.NoError(t, engine.CreateEdge(edge(tc.same())))
				if buffered {
					require.NoError(t, engine.FlushWriteBehind())
				}
				require.NoError(t, engine.SetEdgeManuallySuppressed("test:r", true))
				before, err := engine.GetStoredEdge("test:r")
				require.NoError(t, err)
				before = comparableStoredEdge(before)

				require.NoError(t, engine.CreateEdge(edge(tc.same())), "the same value is the permitted no-op")
				require.NoError(t, engine.BulkCreateEdges([]*Edge{edge(tc.same())}))
				err = engine.CreateEdge(edge(tc.different()))
				var conflict *HiddenEdgeIdentityConflictError
				require.ErrorAs(t, err, &conflict, "a different value is a permanent conflict")

				if buffered {
					require.NoError(t, engine.FlushWriteBehind())
				}
				after, err := engine.GetStoredEdge("test:r")
				require.NoError(t, err)
				require.Equal(t, before, comparableStoredEdge(after))
				count, err := engine.EdgeCount()
				require.NoError(t, err)
				require.EqualValues(t, 1, count)
			})
		}
	}
}
