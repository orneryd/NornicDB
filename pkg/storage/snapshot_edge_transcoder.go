package storage

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"slices"
	"strings"

	"github.com/vmihailenco/msgpack/v5"
	"github.com/vmihailenco/msgpack/v5/msgpcode"
)

type snapshotRawProperty struct {
	name  string
	value []byte
}

// snapshotEdgeTranscoder belongs to one snapshot stream. Values borrow the
// Badger item only until writeBody returns; scratch never crosses a callback.
type snapshotEdgeTranscoder struct {
	edge       Edge
	reader     bytes.Reader
	decoder    *msgpack.Decoder
	properties []snapshotRawProperty
}

// writeBody expands the V2 header and dictionary names, copying property bytes
// only when the strict property reader would reproduce them exactly. Complex
// values whose normalization has not been proved use the ordinary frame writer.
func (t *snapshotEdgeTranscoder) writeBody(b *BadgerEngine, id EdgeID, body []byte, ids *NamespacedEngine, write func(byte, any) error) (bool, error) {
	namespace := namespaceForEdgeID(id)
	edge := &t.edge
	start, end, offset, err := decodeEdgeCompactHeaderInto(body, edgeFormatCompactV2, edge)
	if err != nil {
		return false, err
	}
	var ok bool
	edge.ID = id
	edge.StartNode, ok = b.idDict.lookupNodeIDByNum(start)
	if !ok {
		return false, fmt.Errorf("compact edge: start numID %d not in dict", start)
	}
	edge.EndNode, ok = b.idDict.lookupNodeIDByNum(end)
	if !ok {
		return false, fmt.Errorf("compact edge: end numID %d not in dict", end)
	}
	t.properties = t.properties[:0]
	defer func() {
		clear(t.properties)
		t.reader.Reset(nil)
	}()
	data := body[offset:]
	if len(data) != 0 {
		count, n, err := readUvarint(data)
		if err != nil {
			return false, err
		}
		t.reader.Reset(data[n:])
		if t.decoder == nil {
			t.decoder = msgpack.NewDecoder(&t.reader)
		} else {
			t.decoder.Reset(&t.reader)
		}
		for i := uint64(0); i < count; i++ {
			token, err := binary.ReadUvarint(&t.reader)
			if err != nil {
				return false, err
			}
			name, found := b.propKeyDict.lookup(namespace, token)
			if !found {
				return false, fmt.Errorf("property key id %d not in dictionary for namespace %q", token, namespace)
			}
			pos := len(data) - t.reader.Len()
			if err := t.decoder.Skip(); err != nil {
				return false, err
			}
			value := data[pos : len(data)-t.reader.Len()]
			if !snapshotValueIdentity(value) {
				return false, nil
			}
			t.properties = append(t.properties, snapshotRawProperty{name, value})
		}
		if t.reader.Len() != 0 {
			return false, fmt.Errorf("decoding tokenized properties: %d trailing bytes", t.reader.Len())
		}
	}
	slices.SortFunc(t.properties, func(a, b snapshotRawProperty) int { return strings.Compare(a.name, b.name) })
	for i := 1; i < len(t.properties); i++ {
		// The ordinary map reader retains only the last duplicate key.
		if t.properties[i-1].name == t.properties[i].name {
			return false, nil
		}
	}
	if ids != nil {
		*edge = *ids.toUserEdge(edge)
	}
	return true, write(streamSnapshotEdge, t)
}

// encodeSnapshotStoredEdge mirrors msgpack's reflected Edge field order. The
// differential compares complete frames against that independent encoder.
func encodeSnapshotStoredEdge(enc *msgpack.Encoder, edge *Edge, props []snapshotRawProperty) error {
	if err := enc.EncodeMapLen(10); err != nil {
		return err
	}
	for _, field := range [...]struct{ name, value string }{
		{"ID", string(edge.ID)}, {"StartNode", string(edge.StartNode)},
		{"EndNode", string(edge.EndNode)}, {"Type", edge.Type},
	} {
		if err := enc.EncodeString(field.name); err != nil {
			return err
		}
		if err := enc.EncodeString(field.value); err != nil {
			return err
		}
	}
	if err := enc.EncodeString("Properties"); err != nil {
		return err
	}
	if err := enc.EncodeMapLen(len(props)); err != nil {
		return err
	}
	for _, prop := range props {
		if err := enc.EncodeString(prop.name); err != nil {
			return err
		}
		if _, err := enc.Writer().Write(prop.value); err != nil {
			return err
		}
	}
	if err := enc.EncodeString("CreatedAt"); err != nil {
		return err
	}
	if err := enc.EncodeTime(edge.CreatedAt); err != nil {
		return err
	}
	if err := enc.EncodeString("UpdatedAt"); err != nil {
		return err
	}
	if err := enc.EncodeTime(edge.UpdatedAt); err != nil {
		return err
	}
	if err := enc.EncodeString("Confidence"); err != nil {
		return err
	}
	if err := enc.EncodeFloat64(edge.Confidence); err != nil {
		return err
	}
	if err := enc.EncodeString("AutoGenerated"); err != nil {
		return err
	}
	if err := enc.EncodeBool(edge.AutoGenerated); err != nil {
		return err
	}
	if err := enc.EncodeString("VisibilitySuppressed"); err != nil {
		return err
	}
	return enc.EncodeBool(edge.VisibilitySuppressed)
}

// snapshotValueIdentity is deliberately narrower than the supported property
// domain. In particular narrow integers widen to int64,
// maps change key order, and extension decoders may normalize their payloads.
// The fallback owns all those cases; this predicate never changes a value.
func snapshotValueIdentity(raw []byte) bool {
	if len(raw) == 0 {
		return false
	}
	code := raw[0]
	if msgpcode.IsFixedArray(code) || code == msgpcode.Array16 || code == msgpcode.Array32 {
		// Only scalar arrays: excluding narrow ints also covers mixed arrays
		// whose signed/unsigned prefix the strict reader widens before a mix.
		count, offset := 0, 1
		switch code {
		case msgpcode.Array16:
			if len(raw) < 3 {
				return false
			}
			count, offset = int(binary.BigEndian.Uint16(raw[1:])), 3
			if count < 16 {
				return false
			}
		case msgpcode.Array32:
			if len(raw) < 5 {
				return false
			}
			count, offset = int(binary.BigEndian.Uint32(raw[1:])), 5
			if count <= 65535 {
				return false
			}
		default:
			count = int(code & 15)
		}
		for i := 0; i < count; i++ {
			if offset >= len(raw) {
				return false
			}
			c := raw[offset]
			if (isSignedIntegerCode(c) && c != msgpcode.Int64) || (isUnsignedIntegerCode(c) && c != msgpcode.Uint64) {
				return false
			}
			n := snapshotScalarIdentitySize(raw[offset:])
			if n == 0 {
				return false
			}
			offset += n
		}
		return offset == len(raw)
	}
	return snapshotScalarIdentitySize(raw) == len(raw)
}

func snapshotScalarIdentitySize(raw []byte) int {
	if len(raw) == 0 {
		return 0
	}
	c, size := raw[0], 0
	switch {
	case c == msgpcode.Nil || c == msgpcode.False || c == msgpcode.True:
		size = 1
	case c == msgpcode.Float:
		size = 5
	case c == msgpcode.Uint64:
		if len(raw) < 9 || binary.BigEndian.Uint64(raw[1:]) <= uint64(1<<63-1) {
			return 0
		}
		size = 9
	case c == msgpcode.Int64 || c == msgpcode.Double:
		size = 9
	case c >= msgpcode.FixedStrLow && c <= msgpcode.FixedStrHigh:
		size = 1 + int(c&31)
	case c == msgpcode.Str8 || c == msgpcode.Bin8:
		if len(raw) < 2 {
			return 0
		}
		n := int(raw[1])
		if c == msgpcode.Str8 && n < 32 {
			return 0
		}
		size = 2 + n
	case c == msgpcode.Str16 || c == msgpcode.Bin16:
		if len(raw) < 3 {
			return 0
		}
		n := int(binary.BigEndian.Uint16(raw[1:]))
		if n <= 255 {
			return 0
		}
		size = 3 + n
	case c == msgpcode.Str32 || c == msgpcode.Bin32:
		if len(raw) < 5 {
			return 0
		}
		n := int(binary.BigEndian.Uint32(raw[1:]))
		if n <= 65535 {
			return 0
		}
		size = 5 + n
	default:
		return 0
	}
	if size > len(raw) {
		return 0
	}
	return size
}
