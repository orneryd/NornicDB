func snapshotTranscoderCorpus() []any {
	return []any{
		nil, true, false, "", "<>&\"\\\n☃", strings.Repeat("x", 128<<10), []byte{0, 255}, []byte(nil),
		int(1), int(-1), int8(-7), int16(-300), int32(-70000), int64(1 << 55),
		uint(1), uint8(250), uint16(60000), uint32(1 << 31), uint64(1 << 63),
		float32(1.25), float64(1.5), math.Inf(1), math.Copysign(0, -1),
		[]any{int8(1), int8(-2)}, []any{int16(3), int16(-4)}, []int32{5, -6}, []int64{7, 1 << 55},
		[]uint8{1, 2}, []any{uint16(3), uint16(4)}, []any{uint32(5), uint32(6)}, []any{uint64(7), uint64(1 << 63)},
		[]int{1, 2}, []float32{1.5, 2.5}, []float64{3.5, 4.5}, []string{"a", "b"}, []bool{true, false},
		[]any{}, []any(nil), []string(nil), []any{int8(1), int16(2), "mix"},
		[]any{int64(1), "mix", false}, []any{[]int32{1, 2}, map[string]any{"a": nil}},
		map[string]any{}, map[string]any(nil), map[string]any{"z": "last", "a": []int64{1, 2}},
		time.Unix(123, 456).UTC(), time.Unix(123, 456).In(time.FixedZone("", 19800)),
		[]any{time.Unix(123, 456).UTC(), map[string]any{"stamp": time.Unix(567, 890).UTC()}},
	}
}

func snapshotTranscoderBody(t *testing.T, engine *BadgerEngine, edge *Edge) []byte {
	t.Helper()
	var body []byte
	require.NoError(t, engine.withUpdate(func(txn *badger.Txn) error {
		var err error
		body, err = engine.encodeEdgeInTxn(txn, namespaceForEdgeID(edge.ID), edge)
		return err
	}))
	return body
}

func checkSnapshotTranscoder(t *testing.T, engine *BadgerEngine, edge *Edge, strip string) bool {
	t.Helper()
	body := snapshotTranscoderBody(t, engine, edge)
	decoded, err := engine.decodeEdgeBodyByID(body, edge.ID)
	require.NoError(t, err)
	if strip != "" {
		decoded.ID = EdgeID(strings.TrimPrefix(string(decoded.ID), strip))
		decoded.StartNode = NodeID(strings.TrimPrefix(string(decoded.StartNode), strip))
		decoded.EndNode = NodeID(strings.TrimPrefix(string(decoded.EndNode), strip))
	}
	var want, got bytes.Buffer
	oracle := snapshotFrameWriter{writer: &want}
	require.NoError(t, oracle.write(streamSnapshotEdge, decoded, defaultSnapshotRecordSize))
	frames := snapshotFrameWriter{writer: &got}
	transcoder := snapshotEdgeTranscoder{}
	var ids *NamespacedEngine
	if strip != "" {
		ids = NewNamespacedEngine(engine, strings.TrimSuffix(strip, ":"))
	}
	fast, err := transcoder.writeBody(engine, edge.ID, body, ids, func(kind byte, value any) error { return frames.write(kind, value, defaultSnapshotRecordSize) })
	require.NoError(t, err)
	if !fast {
		require.Zero(t, got.Len(), "fallback must not emit a partial frame")
		require.NoError(t, frames.write(streamSnapshotEdge, decoded, defaultSnapshotRecordSize))
	}
	require.Equal(t, want.Bytes(), got.Bytes(), "complete frames, including length and CRC, must be byte-identical")
	_, payload, err := readSnapshotFrame(&got)
	require.NoError(t, err)
	var recovered Edge
	require.NoError(t, decodeRecoveryPayload(payload, &recovered))
	// The standard recovery decoder is also the oracle for strict array shape.
	_, referencePayload, err := readSnapshotFrame(&want)
	require.NoError(t, err)
	var reference Edge
	require.NoError(t, decodeRecoveryPayload(referencePayload, &reference))
	require.Equal(t, reference, recovered)
	return fast
}

func TestSnapshotTranscoderDifferential(t *testing.T) {
	engine := newTestEngine(t)
	zone, err := time.LoadLocation("America/Phoenix")
	require.NoError(t, err)
	corpus := append(snapshotTranscoderCorpus(), time.Date(2026, 2, 3, 4, 5, 6, 7, zone))
	fastCount, fallbackCount := 0, 0
	for i, value := range corpus {
		t.Run(fmt.Sprintf("type-%d-%T", i, value), func(t *testing.T) {
			edge := &Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Type: "CALLS",
				Properties: map[string]any{"value": value, "z": "last", "a": int64(7)},
				CreatedAt:  time.Unix(-123, 456).UTC(), UpdatedAt: time.Unix(123, 789).UTC(),
				Confidence: .25, AutoGenerated: i%2 == 0, VisibilitySuppressed: i%3 == 0}
			if checkSnapshotTranscoder(t, engine, edge, "test:") {
				fastCount++
			} else {
				fallbackCount++
			}
		})
	}
	require.Positive(t, fastCount)
	require.Positive(t, fallbackCount)
	for _, value := range []any{[]any{int8(1), int8(2)}, []int32{3, 4}, time.Unix(1, 2).UTC(), map[string]any{"x": 1}} {
		require.False(t, checkSnapshotTranscoder(t, engine, &Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Properties: map[string]any{"value": value}}, ""))
	}
	for _, props := range []map[string]any{nil, {}, {"v": int64(7)}, {"v": []int64{1, 2}}} {
		require.True(t, checkSnapshotTranscoder(t, engine, &Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Properties: props}, ""))
	}
}

func TestSnapshotTranscoderPropertyCorpus(t *testing.T) {
	engine := newTestEngine(t)
	corpus := snapshotTranscoderCorpus()
	rng := rand.New(rand.NewSource(7731))
	for i := 0; i < 300; i++ {
		props := make(map[string]any)
		for j := 0; j < rng.Intn(18); j++ {
			props[fmt.Sprintf("key-%02d", j)] = corpus[rng.Intn(len(corpus))]
		}
		checkSnapshotTranscoder(t, engine, &Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Type: fmt.Sprintf("TYPE-%d", i), Properties: props, VisibilitySuppressed: i%2 == 0}, "")
	}
}

func FuzzSnapshotTranscoderDifferential(f *testing.F) {
	for _, seed := range [][]byte{{}, {0}, {1, 7, 2, 255}, []byte("snapshot-properties"), bytes.Repeat([]byte{9, 17, 33}, 30)} {
		f.Add(seed)
	}
	f.Fuzz(func(t *testing.T, input []byte) {
		if len(input) > 128 {
			input = input[:128]
		}
		engine := newTestEngine(t)
		corpus := snapshotTranscoderCorpus()
		props := map[string]any{}
		for i, v := range input {
			props[fmt.Sprintf("p-%d", i)] = corpus[int(v)%len(corpus)]
		}
		checkSnapshotTranscoder(t, engine, &Edge{ID: "fuzz:e", StartNode: "fuzz:a", EndNode: "fuzz:b", Properties: props, VisibilitySuppressed: true}, "")
	})
}

// This independent byte-level oracle also explores noncanonical MessagePack
// and floating-point bit patterns, without a database startup per fuzz input.
func FuzzSnapshotValueIdentity(f *testing.F) {
	corpus := append(snapshotTranscoderCorpus(), math.Float32frombits(0x7fa00001), math.Float64frombits(0x7ff0000000000001), math.NaN())
	for _, value := range corpus {
		raw, err := msgpack.Marshal(encodeStoredTemporalValue(value))
		if err != nil {
			f.Fatal(err)
		}
		f.Add(raw)
	}
	f.Fuzz(func(t *testing.T, raw []byte) {
		if !snapshotValueIdentity(raw) {
			return
		}
		reader := bytes.NewReader(raw)
		value, err := decodeStrictTypedValue(msgpack.NewDecoder(reader))
		require.NoError(t, err)
		require.Zero(t, reader.Len())
		var output bytes.Buffer
		encoder := msgpack.NewEncoder(&output).SetSortMapKeys(true)
		require.NoError(t, encoder.Encode(encodeStoredTemporalValue(restoreStoredTemporalValue(value))))
		require.Equal(t, raw, output.Bytes(), "accepted values must survive the actual strict reader and general encoder byte-for-byte")
	})
}
