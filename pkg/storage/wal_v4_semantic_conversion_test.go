package storage

import (
	"testing"
	"time"

	"github.com/stretchr/testify/require"
)

func TestConvertV4SemanticWALRecordRewritesHistoricalEntityCommit(t *testing.T) {
	stamp := time.Date(2024, 3, 5, 10, 20, 30, 123456789, time.UTC)
	node := &Node{
		ID: "test:n", Labels: []string{"Item"},
		Properties:           map[string]any{"count": int64(9), "name": "café", "when": stamp},
		EmbedMeta:            map[string]any{"source": "fixture"},
		NamedEmbeddings:      map[string][]float32{"vector": {1, 2}},
		ChunkEmbeddings:      [][]float32{{3, 4}},
		CreatedAt:            stamp,
		UpdatedAt:            stamp,
		VisibilitySuppressed: true,
	}
	edge := &Edge{
		ID: "test:e", StartNode: "test:n", EndNode: "test:other", Type: "LINK",
		Properties:    map[string]any{"weight": float64(0.5)},
		CreatedAt:     stamp,
		UpdatedAt:     stamp,
		Confidence:    0.75,
		AutoGenerated: true,
	}
	ops := []Operation{
		{Type: OpCreateNode, Node: node},
		{Type: OpCreateEdge, Edge: edge},
	}

	historical, err := encodeV4GobEntityTransaction("test", "historical-tx", ops, CommitModeImplicit)
	require.NoError(t, err)
	originalData, err := marshalWALRecoveryPayload(nil, walEntityCommitData{Payload: historical})
	require.NoError(t, err)
	originalDataCopy := append([]byte(nil), originalData...)

	entry := WALEntry{
		Sequence: 7, Timestamp: stamp, Operation: OpEntityCommit, Database: "test",
		Data: originalData, Checksum: crc32Checksum(originalData),
	}
	originalPayloadCopy := append([]byte(nil), historical...)

	wantEnvelope, want, err := decodeV4GobEntityTransaction(originalPayloadCopy)
	require.NoError(t, err)

	converted, err := convertV4SemanticWALRecord(entry)
	require.NoError(t, err)

	require.Equal(t, entry.Sequence, converted.Sequence)
	require.Equal(t, entry.Timestamp, converted.Timestamp)
	require.Equal(t, entry.Operation, converted.Operation)
	require.Equal(t, entry.Database, converted.Database)
	require.Equal(t, crc32Checksum(converted.Data), converted.Checksum)

	// The input record and its bytes must be untouched.
	require.Equal(t, originalDataCopy, entry.Data)
	require.Equal(t, crc32Checksum(originalDataCopy), entry.Checksum)
	require.Equal(t, originalPayloadCopy, historical)

	var commit walEntityCommitData
	require.NoError(t, decodeRecoveryPayload(converted.Data, &commit))
	wire, got, err := DecodeEntityTransaction(commit.Payload)
	require.NoError(t, err)
	require.Equal(t, wantEnvelope.Mode, wire.Mode)
	require.Equal(t, wantEnvelope.Namespace, wire.Namespace)
	require.Equal(t, wantEnvelope.LogicalTxID, wire.LogicalTxID)
	require.Equal(t, want, got)
}

func TestConvertV4SemanticWALRecordLeavesOtherRecordsUnchanged(t *testing.T) {
	data, err := marshalWALRecoveryPayload(nil, WALDeleteData{ID: "test:n"})
	require.NoError(t, err)
	entry := WALEntry{Sequence: 3, Operation: OpDeleteNode, Database: "test", Data: data, Checksum: crc32Checksum(data)}

	converted, err := convertV4SemanticWALRecord(entry)
	require.NoError(t, err)
	require.Equal(t, entry, converted)
}

func TestConvertV4SemanticWALRecordRejectsMalformedHistoricalData(t *testing.T) {
	malformed, err := marshalWALRecoveryPayload(nil, walEntityCommitData{Payload: []byte("not a gob envelope")})
	require.NoError(t, err)
	entry := WALEntry{Sequence: 9, Operation: OpEntityCommit, Database: "test", Data: malformed, Checksum: crc32Checksum(malformed)}
	before := append([]byte(nil), malformed...)

	converted, err := convertV4SemanticWALRecord(entry)
	require.Error(t, err)
	require.Contains(t, err.Error(), "historical entity transaction")
	require.Equal(t, entry, converted)
	require.Equal(t, before, entry.Data)
}
