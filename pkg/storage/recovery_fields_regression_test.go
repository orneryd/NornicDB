func recoveryFieldFixture() (*Node, *Edge) {
	created := time.Date(2026, 1, 2, 3, 4, 5, 123, time.UTC)
	updated := created.Add(time.Hour)
	node := &Node{runtime: &nodeRuntime{metadata: NodeRuntimeMetadata{VisibilitySuppressed: true}},
		ID: "test:a", Labels: []string{"Doc"}, Properties: map[string]any{
			"integer": int64(9007199254740993), "float": float64(7), "nested": map[string]any{"count": int64(11)},
		}, CreatedAt: created, UpdatedAt: updated, NamedEmbeddings: map[string][]float32{"title": {1, 2}}, ChunkEmbeddings: [][]float32{{3, 4}},
		EmbedMeta: map[string]any{"chunk_count": int64(1), "has_embedding": true}}
	edge := &Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Type: "LINKS", Properties: map[string]any{"integer": int64(9007199254740993), "float": float64(7)}, CreatedAt: created, UpdatedAt: updated, Confidence: 0.7, AutoGenerated: true, VisibilitySuppressed: true}
	return node, edge
}

