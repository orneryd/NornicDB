func TestRecoveryPayloadPreservesRedoUndoEntityFields(t *testing.T) {
	n, e := recoveryFieldFixture()
	type payloadCase struct {
		name   string
		source any
		target any
		check  func(*testing.T)
	}
	cases := []payloadCase{}
	nd := &WALNodeData{}
	cases = append(cases, payloadCase{"node", WALNodeData{Node: n, OldNode: n, TxID: "tx"}, nd, func(t *testing.T) {
		assertRecoveryNodeFields(t, n, nd.Node)
		assertRecoveryNodeFields(t, n, nd.OldNode)
		assert.Equal(t, "tx", nd.TxID)
	}})
	ed := &WALEdgeData{}
	cases = append(cases, payloadCase{"edge", WALEdgeData{Edge: e, OldEdge: e, TxID: "tx"}, ed, func(t *testing.T) {
		assertRecoveryEdgeFields(t, e, ed.Edge)
		assertRecoveryEdgeFields(t, e, ed.OldEdge)
	}})
	dd := &WALDeleteData{}
	cases = append(cases, payloadCase{"delete", WALDeleteData{ID: "a", OldNode: n, OldEdge: e}, dd, func(t *testing.T) {
		assertRecoveryNodeFields(t, n, dd.OldNode)
		assertRecoveryEdgeFields(t, e, dd.OldEdge)
	}})
	bn := &WALBulkNodesData{}
	cases = append(cases, payloadCase{"bulk-nodes", WALBulkNodesData{Nodes: []*Node{n}}, bn, func(t *testing.T) { require.Len(t, bn.Nodes, 1); assertRecoveryNodeFields(t, n, bn.Nodes[0]) }})
	be := &WALBulkEdgesData{}
	cases = append(cases, payloadCase{"bulk-edges", WALBulkEdgesData{Edges: []*Edge{e}}, be, func(t *testing.T) { require.Len(t, be.Edges, 1); assertRecoveryEdgeFields(t, e, be.Edges[0]) }})
	dn := &WALBulkDeleteNodesData{}
	cases = append(cases, payloadCase{"bulk-delete-nodes", WALBulkDeleteNodesData{IDs: []string{"a"}, OldNodes: []*Node{n}}, dn, func(t *testing.T) { require.Len(t, dn.OldNodes, 1); assertRecoveryNodeFields(t, n, dn.OldNodes[0]) }})
	de := &WALBulkDeleteEdgesData{}
	cases = append(cases, payloadCase{"bulk-delete-edges", WALBulkDeleteEdgesData{IDs: []string{"e"}, OldEdges: []*Edge{e}}, de, func(t *testing.T) { require.Len(t, de.OldEdges, 1); assertRecoveryEdgeFields(t, e, de.OldEdges[0]) }})
	for _, tt := range cases {
		t.Run(tt.name, func(t *testing.T) {
			// The binary route is valueEncoder.recovery, the WAL route its JSON
			// sidecar projection; the encoder owns its bytes only until reuse.
			encoder := getValueEncoder()
			defer putValueEncoder(encoder)
			encoders := map[string]func(any) ([]byte, error){
				"wal-sidecar": func(value any) ([]byte, error) { return marshalWALRecoveryPayload(nil, value) },
				"binary":      encoder.recovery,
			}
			for name, encode := range encoders {
				t.Run(name, func(t *testing.T) {
					raw, err := encode(tt.source)
					require.NoError(t, err)
					require.NoError(t, decodeRecoveryPayload(raw, tt.target))
					tt.check(t)
				})
			}
		})
	}
}

func TestRecoverySnapshotPreservesFieldsAndPropertyTypes(t *testing.T) {
	n, e := recoveryFieldFixture()
	path := filepath.Join(t.TempDir(), "snapshot.json")
	require.NoError(t, SaveSnapshot(&Snapshot{Sequence: 17, Version: "1.0", Nodes: []*Node{n}, Edges: []*Edge{e}}, path))
	got, err := LoadSnapshot(path)
	require.NoError(t, err)
	assert.Equal(t, uint64(17), got.Sequence)
	require.Len(t, got.Nodes, 1)
	require.Len(t, got.Edges, 1)
	assertRecoveryNodeFields(t, n, got.Nodes[0])
	assertRecoveryEdgeFields(t, e, got.Edges[0])
}

func TestWALEngineRecoveryPreservesSuppliedTimes(t *testing.T) {
	enabled := config.IsWALEnabled()
	config.EnableWAL()
	t.Cleanup(func() {
		if !enabled {
			config.DisableWAL()
		}
	})
	dir := t.TempDir()
	wal, err := NewWAL("", &WALConfig{Dir: dir, SyncMode: "immediate"})
	require.NoError(t, err)
	live := NewWALEngine(newTestMemoryEngine(t), wal)
	t.Cleanup(func() { _ = live.Close() })
	n, e := recoveryFieldFixture()
	_, err = live.CreateNode(n)
	require.NoError(t, err)
	_, err = live.CreateNode(&Node{ID: "test:b"})
	require.NoError(t, err)
	require.NoError(t, live.CreateEdge(e))
	require.NoError(t, wal.Close())
	recovered, err := fixtureowner.OwnResult[*MemoryEngine](t, ErrStorageClosed)(RecoverFromWAL(dir, ""))
	require.NoError(t, err)
	t.Cleanup(func() { _ = recovered.Close() })
	gotN, err := recovered.GetNode(n.ID)
	require.NoError(t, err)
	gotE, err := recovered.GetEdge(e.ID)
	require.NoError(t, err)
	assertRecoveryNodeFields(t, n, gotN)
	assertRecoveryEdgeFields(t, e, gotE)
}

func TestRecoveryStreamingSnapshotPreservesFields(t *testing.T) {
	eng := newTestEngine(t)
	n, e := recoveryFieldFixture()
	_, err := eng.CreateNode(n)
	require.NoError(t, err)
	_, err = eng.CreateNode(&Node{ID: "test:b"})
	require.NoError(t, err)
	require.NoError(t, eng.CreateEdge(e))
	var raw bytes.Buffer
	require.NoError(t, WriteSnapshot(context.Background(), eng, &raw, SnapshotOptions{Sequence: 19}))
	visitor := &recoveryFieldsVisitor{}
	metadata, err := ReadSnapshot(&raw, visitor)
	require.NoError(t, err)
	assert.Equal(t, uint64(19), metadata.Sequence)
	require.Len(t, visitor.nodes, 2)
	require.Len(t, visitor.edges, 1)
	expected := *n
	// The light route can still return inline vectors; everything supplied
	// by that route must survive. Separately stored vectors are not loaded.
	var got *Node
	for _, node := range visitor.nodes {
		if node.ID == n.ID {
			got = node
		}
	}
	assertRecoveryNodeFields(t, &expected, got)
	assertRecoveryEdgeFields(t, e, visitor.edges[0])
}

type recoveryFieldsVisitor struct {
	nodes []*Node
	edges []*Edge
}

func (v *recoveryFieldsVisitor) VisitNode(n *Node) error { v.nodes = append(v.nodes, n); return nil }
func (v *recoveryFieldsVisitor) VisitEdge(e *Edge) error { v.edges = append(v.edges, e); return nil }

func TestWALEngineDefaultTimesRecordedBeforeCreation(t *testing.T) {
	enabled := config.IsWALEnabled()
	config.EnableWAL()
	t.Cleanup(func() {
		if !enabled {
			config.DisableWAL()
		}
	})
	dir := t.TempDir()
	wal, err := NewWAL("", &WALConfig{Dir: dir, SyncMode: "immediate"})
	require.NoError(t, err)
	live := NewWALEngine(newTestMemoryEngine(t), wal)
	t.Cleanup(func() { _ = live.Close() })
	for _, id := range []NodeID{"test:a", "test:b"} {
		_, err = live.CreateNode(&Node{ID: id})
		require.NoError(t, err)
	}
	require.NoError(t, live.CreateEdge(&Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Type: "LINKS"}))
	n, err := live.GetNode("test:a")
	require.NoError(t, err)
	e, err := live.GetEdge("test:e")
	require.NoError(t, err)
	require.NoError(t, wal.Close())
	recovered, err := fixtureowner.OwnResult[*MemoryEngine](t, ErrStorageClosed)(RecoverFromWAL(dir, ""))
	require.NoError(t, err)
	t.Cleanup(func() { _ = recovered.Close() })
	gotN, err := recovered.GetNode(n.ID)
	require.NoError(t, err)
	gotE, err := recovered.GetEdge(e.ID)
	require.NoError(t, err)
	assert.True(t, n.CreatedAt.Equal(gotN.CreatedAt), "WAL must record live creation time")
	assert.True(t, n.UpdatedAt.Equal(gotN.UpdatedAt))
	assert.True(t, e.CreatedAt.Equal(gotE.CreatedAt), "WAL must record live edge creation time")
	assert.True(t, e.UpdatedAt.Equal(gotE.UpdatedAt))
}

func TestWALEngineDefaultUpdateTimeRecordedBeforeMutation(t *testing.T) {
	enabled := config.IsWALEnabled()
	config.EnableWAL()
	t.Cleanup(func() {
		if !enabled {
			config.DisableWAL()
		}
	})
	dir := t.TempDir()
	wal, err := NewWAL(dir, &WALConfig{SyncMode: "immediate"})
	require.NoError(t, err)
	live := NewWALEngine(newTestMemoryEngine(t), wal)
	t.Cleanup(func() { _ = live.Close() })
	_, err = live.CreateNode(&Node{ID: "test:a"})
	require.NoError(t, err)
	node, err := live.GetNode("test:a")
	require.NoError(t, err)
	node.UpdatedAt = time.Time{}
	node.Properties = map[string]any{"changed": true}
	require.NoError(t, live.UpdateNode(node))
	want, err := live.GetNode(node.ID)
	require.NoError(t, err)
	require.False(t, want.UpdatedAt.IsZero())
	require.NoError(t, wal.Close())
	recovered, err := fixtureowner.OwnResult[*MemoryEngine](t, ErrStorageClosed)(RecoverFromWAL(dir, ""))
	require.NoError(t, err)
	t.Cleanup(func() { _ = recovered.Close() })
	got, err := recovered.GetNode(node.ID)
	require.NoError(t, err)
	assert.True(t, want.UpdatedAt.Equal(got.UpdatedAt), "default update time must be stamped before appending, not independently at replay")
}
