func TestSemanticTransactionWireMatchesCurrentEntityContract(t *testing.T) {
	stamp := time.Date(2024, 3, 5, 10, 20, 30, 123456789, time.FixedZone("fixture-zone", 3600))
	node := &Node{
		ID: "test:n", Labels: []string{"Fixture"},
		Properties:      map[string]any{"int32": int32(9), "int64": int64(1 << 40), "float32": float32(1.25), "bytes": []byte{0, 1, 255}, "list": []int64{1, 2}, "when": stamp, "nested": map[string]any{"count": int64(7)}},
		EmbedMeta:       map[string]any{"source": "fixture", "count": int32(2)},
		NamedEmbeddings: map[string][]float32{"named": {0, 1}}, ChunkEmbeddings: [][]float32{{1, 0}},
		CreatedAt: stamp, UpdatedAt: stamp, VisibilitySuppressed: true,
	}
	edge := &Edge{ID: "test:e", StartNode: "test:n", EndNode: "test:other", Type: "LINK", Properties: map[string]any{"values": []int64{1, 2}, "at": stamp}, CreatedAt: stamp, UpdatedAt: stamp, Confidence: 0.75, AutoGenerated: true, VisibilitySuppressed: true}
	ops := []Operation{{Type: OpCreateNode, Node: node}, {Type: OpUpdateEdge, Edge: edge}, {Type: OpDeleteNode, NodeID: "test:deleted-node"}, {Type: OpDeleteEdge, EdgeID: "test:deleted-edge"}}
	current, err := encodeV4GobEntityTransaction("test", "tx", ops, CommitModeImplicit)
	require.NoError(t, err)
	oldEnvelope, want, err := decodeV4GobEntityTransaction(current)
	require.NoError(t, err)
	payload, err := EncodeEntityTransaction("test", "tx", ops, CommitModeImplicit)
	require.NoError(t, err)
	wire, got, err := DecodeEntityTransaction(payload)
	require.NoError(t, err)
	require.Equal(t, oldEnvelope.Mode, wire.Mode)
	require.Equal(t, oldEnvelope.Namespace, wire.Namespace)
	require.Equal(t, oldEnvelope.LogicalTxID, wire.LogicalTxID)
	require.Equal(t, want, got)
	_, _, err = DecodeEntityTransaction(append(payload, 0))
	require.Error(t, err, "trailing bytes must not be accepted")
}

func TestSemanticTransactionRejectsPathologicalPropertyNesting(t *testing.T) {
	node := &Node{ID: "test:n", Properties: map[string]any{"x": "normal"}}
	payload, err := EncodeEntityTransaction("test", "depth", []Operation{{Type: OpCreateNode, Node: node}})
	require.NoError(t, err)
	var raw map[string]any
	require.NoError(t, msgpack.Unmarshal(payload, &raw))
	changes := raw["Changes"].([]any)
	image := changes[0].(map[string]any)["Node"].(map[string]any)
	nested := append(bytes.Repeat([]byte{0x91}, 1050), 0xc0)
	image["Properties"] = map[string]any{"x": msgpack.RawMessage(nested)}
	payload, err = msgpack.Marshal(raw)
	require.NoError(t, err)
	_, _, err = DecodeEntityTransaction(payload)
	require.ErrorContains(t, err, "nesting depth")
}

func TestSemanticTransactionEncoderRejectsPathologicalPropertyNesting(t *testing.T) {
	value := any(nil)
	for range 1025 {
		value = []any{value}
	}
	node := &Node{ID: "test:n", Properties: map[string]any{"x": value}}
	_, err := EncodeEntityTransaction("test", "depth", []Operation{{Type: OpCreateNode, Node: node}})
	require.ErrorContains(t, err, "nesting depth")
}

func TestSemanticTransactionPropertyDepthBoundary(t *testing.T) {
	node := &Node{ID: "test:n", Properties: map[string]any{"x": "normal"}}
	payload, err := EncodeEntityTransaction("test", "depth", []Operation{{Type: OpCreateNode, Node: node}})
	require.NoError(t, err)
	for _, tc := range []struct {
		depth int
		valid bool
	}{{1024, true}, {1025, false}} {
		var raw map[string]any
		require.NoError(t, msgpack.Unmarshal(payload, &raw))
		changes := raw["Changes"].([]any)
		image := changes[0].(map[string]any)["Node"].(map[string]any)
		image["Properties"] = map[string]any{"x": msgpack.RawMessage(append(bytes.Repeat([]byte{0x91}, tc.depth), 0xc0))}
		encoded, err := msgpack.Marshal(raw)
		require.NoError(t, err)
		_, _, err = DecodeEntityTransaction(encoded)
		if tc.valid {
			require.NoError(t, err, "depth %d", tc.depth)
		} else {
			require.ErrorContains(t, err, "nesting depth")
		}
	}
	value := any(nil)
	for range 1024 {
		value = []any{value}
	}
	node.Properties["x"] = value
	encoded, err := EncodeEntityTransaction("test", "depth", []Operation{{Type: OpCreateNode, Node: node}})
	require.NoError(t, err)
	_, _, err = DecodeEntityTransaction(encoded)
	require.NoError(t, err)
}
