package storage

import (
	"bytes"
	"encoding/gob"
	"encoding/json"
	"fmt"
	"io"
	"time"
)

// NodePayload is the replication-safe representation of Node, including embeddings.
type NodePayload struct {
	ID              string
	Labels          []string
	Properties      map[string]any
	NamedEmbeddings map[string][]float32
	ChunkEmbeddings [][]float32
	CreatedAtUnixNs int64
	UpdatedAtUnixNs int64
}

// EdgePayload is the replication-safe representation of Edge.
type EdgePayload struct {
	ID            string
	StartNode     string
	EndNode       string
	Type          string
	Properties    map[string]any
	CreatedAt     int64
	Confidence    float64
	AutoGenerated bool
}

func init() {
	// Register common concrete types used in Properties to help gob handle interface{} values.
	gob.Register(map[string]any{})
	gob.Register([]any{})
	gob.Register([]string{})
	gob.Register([]float64{})
	gob.Register([]float32{})
	gob.Register([]int{})
	gob.Register([]int64{})
}

func EncodeCommandPayload(v any) ([]byte, error) {
	var buf bytes.Buffer
	if err := gob.NewEncoder(&buf).Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func DecodeCommandPayload(data []byte, v any) error { return decodeCommandPayload(data, v, true) }
func decodeCommandPayload(data []byte, v any, legacy bool) error {
	decoder := gob.NewDecoder(bytes.NewReader(data))
	err := decoder.Decode(v)
	if err == nil {
		if !legacy {
			var trailing any
			if tailErr := decoder.Decode(&trailing); tailErr != io.EOF {
				return fmt.Errorf("trailing entity payload")
			}
		}
		return nil
	}
	if legacy {
		return json.Unmarshal(data, v)
	}
	return err
}

func EncodeNodePayload(node *Node) ([]byte, error) {
	if node == nil {
		return nil, fmt.Errorf("nil node")
	}
	payload := NodePayload{
		ID:              string(node.ID),
		Labels:          node.Labels,
		Properties:      node.Properties,
		NamedEmbeddings: node.NamedEmbeddings,
		ChunkEmbeddings: node.ChunkEmbeddings,
		CreatedAtUnixNs: node.CreatedAt.UnixNano(),
		UpdatedAtUnixNs: node.UpdatedAt.UnixNano(),
	}
	return EncodeCommandPayload(&payload)
}

func DecodeNodePayload(data []byte) (*Node, error) { return decodeNodePayload(data, true) }
func decodeNodePayload(data []byte, legacyAllowed bool) (*Node, error) {
	var payload NodePayload
	if err := decodeCommandPayload(data, &payload, legacyAllowed); err == nil && payload.ID != "" {
		node := &Node{
			ID:              NodeID(payload.ID),
			Labels:          payload.Labels,
			Properties:      payload.Properties,
			NamedEmbeddings: payload.NamedEmbeddings,
			ChunkEmbeddings: payload.ChunkEmbeddings,
		}
		if payload.CreatedAtUnixNs != 0 {
			node.CreatedAt = time.Unix(0, payload.CreatedAtUnixNs)
		}
		if payload.UpdatedAtUnixNs != 0 {
			node.UpdatedAt = time.Unix(0, payload.UpdatedAtUnixNs)
		}
		return node, nil
	}
	if !legacyAllowed {
		return nil, fmt.Errorf("invalid strict entity payload")
	}
	// Fallback: legacy JSON encoding of Node (no embeddings).
	var legacy Node
	if err := json.Unmarshal(data, &legacy); err != nil {
		return nil, err
	}
	return &legacy, nil
}

func EncodeEdgePayload(edge *Edge) ([]byte, error) {
	if edge == nil {
		return nil, fmt.Errorf("nil edge")
	}
	payload := EdgePayload{
		ID:            string(edge.ID),
		StartNode:     string(edge.StartNode),
		EndNode:       string(edge.EndNode),
		Type:          edge.Type,
		Properties:    edge.Properties,
		Confidence:    edge.Confidence,
		AutoGenerated: edge.AutoGenerated,
	}
	if !edge.CreatedAt.IsZero() {
		payload.CreatedAt = edge.CreatedAt.UnixNano()
	}
	return EncodeCommandPayload(&payload)
}

func DecodeEdgePayload(data []byte) (*Edge, error) { return decodeEdgePayload(data, true) }
func decodeEdgePayload(data []byte, legacyAllowed bool) (*Edge, error) {
	var payload EdgePayload
	if err := decodeCommandPayload(data, &payload, legacyAllowed); err == nil && payload.ID != "" {
		edge := &Edge{
			ID:            EdgeID(payload.ID),
			StartNode:     NodeID(payload.StartNode),
			EndNode:       NodeID(payload.EndNode),
			Type:          payload.Type,
			Properties:    payload.Properties,
			Confidence:    payload.Confidence,
			AutoGenerated: payload.AutoGenerated,
		}
		if payload.CreatedAt != 0 {
			edge.CreatedAt = time.Unix(0, payload.CreatedAt)
		}
		return edge, nil
	}
	if !legacyAllowed {
		return nil, fmt.Errorf("invalid strict entity payload")
	}
	// Fallback legacy JSON encoding of Edge.
	var legacy Edge
	if err := json.Unmarshal(data, &legacy); err != nil {
		return nil, err
	}
	return &legacy, nil
}
