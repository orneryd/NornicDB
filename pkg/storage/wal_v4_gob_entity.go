package storage

import (
	"bytes"
	"encoding/gob"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"time"
)

const entityTransactionV4GobVersion uint16 = 1

type v4GobNodePayload struct {
	ID              string
	Labels          []string
	Properties      map[string]any
	NamedEmbeddings map[string][]float32
	ChunkEmbeddings [][]float32
	CreatedAtUnixNs int64
	UpdatedAtUnixNs int64
}

type v4GobEdgePayload struct {
	ID            string
	StartNode     string
	EndNode       string
	Type          string
	Properties    map[string]any
	CreatedAt     int64
	Confidence    float64
	AutoGenerated bool
}

// The original gob structures exist only at the V4 WAL migration boundary.
type v4GobEntityTransactionChange struct {
	Type                 EntityCommandKind
	Data                 []byte
	NamedProperties      []byte
	EmbedMeta            []byte
	UpdatedAtUnixNs      int64
	VisibilitySuppressed bool
}
type v4GobEntityTransactionEnvelope struct {
	Mode        EntityCommitMode
	Version     uint16
	Namespace   string
	LogicalTxID string
	Changes     []v4GobEntityTransactionChange
}

// decodeV4GobValue is deliberately confined to the V4 upgrade path. It
// rejects concatenated values so a successful migration accounts for every
// byte in a historical payload.
func decodeV4GobValue(data []byte, value any) error {
	dec := gob.NewDecoder(bytes.NewReader(data))
	if err := dec.Decode(value); err != nil {
		return err
	}
	var extra any
	if err := dec.Decode(&extra); err != io.EOF {
		return fmt.Errorf("trailing historical gob payload")
	}
	return nil
}

func decodeV4Value(data []byte, value any, allowJSON bool) error {
	err := decodeV4GobValue(data, value)
	if err != nil && allowJSON {
		return json.Unmarshal(data, value)
	}
	return err
}

// decodeV4EntityChange preserves the former direct-command formats solely
// while upgrading old WAL records. Semantic transaction leaves were gob;
// older direct commands also accepted JSON and raw node-deletion IDs.
func decodeV4EntityChange(kind EntityCommandKind, data []byte, allowJSON bool) (Operation, error) {
	var op Operation
	switch kind {
	case EntityCreateNode, EntityUpdateNode:
		var payload v4GobNodePayload
		err := decodeV4Value(data, &payload, allowJSON)
		if err != nil || payload.ID == "" {
			if !allowJSON {
				return op, fmt.Errorf("invalid historical node payload: %v", err)
			}
			var node Node
			if err := json.Unmarshal(data, &node); err != nil || node.ID == "" {
				return op, fmt.Errorf("invalid historical node payload")
			}
			op.Node = &node
		} else {
			node := &Node{ID: NodeID(payload.ID), Labels: payload.Labels, Properties: payload.Properties, NamedEmbeddings: payload.NamedEmbeddings, ChunkEmbeddings: payload.ChunkEmbeddings}
			if payload.CreatedAtUnixNs != 0 {
				node.CreatedAt = time.Unix(0, payload.CreatedAtUnixNs)
			}
			if payload.UpdatedAtUnixNs != 0 {
				node.UpdatedAt = time.Unix(0, payload.UpdatedAtUnixNs)
			}
			op.Node = node
		}
		op.NodeID, op.Type = op.Node.ID, OpCreateNode
		if kind == EntityUpdateNode {
			op.Type = OpUpdateNode
		}
	case EntityCreateEdge, EntityUpdateEdge:
		var payload v4GobEdgePayload
		err := decodeV4Value(data, &payload, allowJSON)
		if err != nil || payload.ID == "" {
			if !allowJSON {
				return op, fmt.Errorf("invalid historical edge payload: %v", err)
			}
			var edge Edge
			if err := json.Unmarshal(data, &edge); err != nil || edge.ID == "" {
				return op, fmt.Errorf("invalid historical edge payload")
			}
			op.Edge = &edge
		} else {
			edge := &Edge{ID: EdgeID(payload.ID), StartNode: NodeID(payload.StartNode), EndNode: NodeID(payload.EndNode), Type: payload.Type, Properties: payload.Properties, Confidence: payload.Confidence, AutoGenerated: payload.AutoGenerated}
			if payload.CreatedAt != 0 {
				edge.CreatedAt = time.Unix(0, payload.CreatedAt)
			}
			op.Edge = edge
		}
		op.EdgeID, op.Type = op.Edge.ID, OpCreateEdge
		if kind == EntityUpdateEdge {
			op.Type = OpUpdateEdge
		}
	case EntityDeleteNode:
		var req struct{ NodeID string }
		if err := decodeV4Value(data, &req, allowJSON); err != nil || req.NodeID == "" {
			if !allowJSON {
				return op, fmt.Errorf("invalid historical node deletion")
			}
			req.NodeID = string(data)
		}
		op.Type, op.NodeID = OpDeleteNode, NodeID(req.NodeID)
	case EntityDeleteEdge:
		var req struct{ EdgeID string }
		if err := decodeV4Value(data, &req, allowJSON); err != nil {
			return op, err
		}
		op.Type, op.EdgeID = OpDeleteEdge, EdgeID(req.EdgeID)
	default:
		return op, fmt.Errorf("not an entity operation: %d", kind)
	}
	return op, nil
}

// TranscodeV4EntityChange upgrades a historical direct entity command for
// replication WAL migration. Current command readers never invoke gob.
func TranscodeV4EntityChange(kind EntityCommandKind, data []byte) ([]byte, error) {
	op, err := decodeV4EntityChange(kind, data, true)
	if err != nil {
		return nil, err
	}
	switch kind {
	case EntityCreateNode, EntityUpdateNode:
		return EncodeNodePayload(op.Node)
	case EntityCreateEdge, EntityUpdateEdge:
		return EncodeEdgePayload(op.Edge)
	case EntityDeleteNode:
		return []byte(op.NodeID), nil
	case EntityDeleteEdge:
		return EncodeCommandPayload(struct{ EdgeID string }{string(op.EdgeID)})
	default:
		return nil, ErrInvalidData
	}
}

// decodeV4GobEntityTransaction reads the historical envelope only while V4
// startup migration rewrites a WAL record to the current semantic format.
func decodeV4GobEntityTransaction(data []byte) (EntityTransactionEnvelope, []Operation, error) {
	var envelope EntityTransactionEnvelope
	var historical v4GobEntityTransactionEnvelope
	if err := decodeV4GobValue(data, &historical); err != nil {
		return envelope, nil, err
	}
	envelope = EntityTransactionEnvelope{Mode: historical.Mode, Version: historical.Version, Namespace: historical.Namespace, LogicalTxID: historical.LogicalTxID}
	if !envelope.Mode.valid() {
		return envelope, nil, ErrInvalidData
	}
	if envelope.Version != entityTransactionV4GobVersion {
		return envelope, nil, errors.New("unsupported entity transaction version")
	}
	if envelope.Namespace == "" || envelope.LogicalTxID == "" || len(historical.Changes) == 0 {
		return envelope, nil, errors.New("entity transaction requires namespace, logical ID and changes")
	}
	ops := make([]Operation, len(historical.Changes))
	sameNamespace := func(id string) bool {
		ns, _, ok := ParseDatabasePrefix(id)
		return ok && ns == envelope.Namespace
	}
	for i, change := range historical.Changes {
		op, err := decodeV4EntityChange(change.Type, change.Data, false)
		if err != nil {
			return envelope, nil, err
		}
		if op.Node != nil || op.Edge != nil {
			properties, err := DecodeNamedProperties(change.NamedProperties)
			if err != nil {
				return envelope, nil, err
			}
			if op.Node != nil {
				op.Node.Properties = properties
				op.Node.EmbedMeta, err = DecodeNamedMetadata(change.EmbedMeta)
				if err != nil {
					return envelope, nil, err
				}
				op.Node.VisibilitySuppressed = change.VisibilitySuppressed
			} else {
				op.Edge.Properties = properties
				if change.UpdatedAtUnixNs != 0 {
					op.Edge.UpdatedAt = time.Unix(0, change.UpdatedAtUnixNs)
				}
				op.Edge.VisibilitySuppressed = change.VisibilitySuppressed
			}
		}

		if op.Node != nil {
			if !sameNamespace(string(op.Node.ID)) {
				return envelope, nil, ErrCrossNamespaceTransaction
			}
		}
		if op.Type == OpDeleteNode && !sameNamespace(string(op.NodeID)) {
			return envelope, nil, ErrCrossNamespaceTransaction
		}
		if op.Edge != nil {
			if !sameNamespace(string(op.Edge.ID)) || !sameNamespace(string(op.Edge.StartNode)) || !sameNamespace(string(op.Edge.EndNode)) {
				return envelope, nil, ErrCrossNamespaceTransaction
			}
		}
		if op.Type == OpDeleteEdge && !sameNamespace(string(op.EdgeID)) {
			return envelope, nil, ErrCrossNamespaceTransaction
		}
		ops[i] = op
	}
	return envelope, ops, nil
}
