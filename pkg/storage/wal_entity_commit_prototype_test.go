func TestAcceptedWALRoutesAndRecoversAtomicSemanticImage(t *testing.T) {
	// The semantic WAL route requires journaling even when a preceding test
	// disabled it. Restore the incoming feature state after resource cleanup.
	t.Cleanup(config.WithWALEnabled())
	dir := t.TempDir()
	wal, err := NewWAL(dir, &WALConfig{Dir: dir, SyncMode: "immediate"})
	require.NoError(t, err)
	t.Cleanup(func() { _ = wal.Close() })
	base, err := fixtureowner.OwnResult[*BadgerEngine](t, ErrStorageClosed)(NewBadgerEngine(t.TempDir()))
	require.NoError(t, err)
	owner := NewWALEngine(base, wal)
	route, found := EntityCommitSubmitterFor(owner)
	require.True(t, found)
	require.True(t, route.RequiresSubmission)
	tx, err := base.BeginTransaction()
	require.NoError(t, err)
	defer tx.Rollback()
	require.NoError(t, tx.SetNamespace("test"))
	require.NoError(t, tx.SetValidationSetting(DeferredConstraintValidation, true))
	zone, err := time.LoadLocation("Europe/London")
	require.NoError(t, err)
	vector := make([]float32, 16000)
	for i := range vector {
		vector[i] = float32(i) / 1000
	}
	_, err = tx.CreateNode(&Node{runtime: &nodeRuntime{metadata: NodeRuntimeMetadata{VisibilitySuppressed: true}}, ID: "test:a", Labels: []string{"Doc"}, Properties: map[string]any{"when": time.Date(2026, 7, 2, 3, 4, 5, 123, zone), "count": int64(123)}, ChunkEmbeddings: [][]float32{vector}, EmbedMeta: map[string]any{"embedding_model": "test-model", "chunk_count": 1}})
	require.NoError(t, err)
	_, err = tx.CreateNode(&Node{ID: "test:b", Properties: map[string]any{"text": "endpoint"}})
	require.NoError(t, err)
	require.NoError(t, tx.CreateEdge(&Edge{ID: "test:e", StartNode: "test:a", EndNode: "test:b", Type: "REL", Properties: map[string]any{"weight": float64(1.5)}, Confidence: 0.7, AutoGenerated: true, VisibilitySuppressed: true, CreatedAt: time.Unix(1700000000, 1).UTC(), UpdatedAt: time.Unix(1700000001, 2).UTC()}))
	prepared, err := tx.PrepareEntityCommit(context.Background(), EntityCommitRequest{LogicalID: "wal-logical"})
	require.NoError(t, err)
	defer prepared.Abort()
	// A caller may edit the exported snapshot without changing the accepted
	// private image that is journaled and ultimately applied.
	for _, op := range prepared.Operations() {
		if op.Node != nil && op.Node.ID == "test:a" {
			op.Node.Properties["count"] = int64(999)
			op.Node.Labels[0] = "changed"
		}
		if op.Edge != nil && op.Edge.ID == "test:e" {
			op.Edge.Properties["weight"] = float64(999)
		}
	}
	receipt, err := route.Submitter.SubmitEntityCommit(context.Background(), prepared, nil)
	require.NoError(t, err)
	require.NoError(t, receipt.Wait(context.Background()))
	require.Equal(t, CommitApplied, receipt.Outcome().State)
	sourceNode, err := base.GetStoredNode("test:a")
	require.NoError(t, err)
	require.EqualValues(t, 123, sourceNode.Properties["count"])
	require.Equal(t, []string{"Doc"}, sourceNode.Labels)
	sourceEdge, err := base.GetStoredEdge("test:e")
	require.NoError(t, err)
	require.Equal(t, float64(1.5), sourceEdge.Properties["weight"])
	require.NoError(t, wal.Close())
	recovered, result, err := fixtureowner.OwnResult3[*MemoryEngine, ReplayResult](t, ErrStorageClosed)(RecoverFromWALWithResult(dir, ""))
	require.NoError(t, err)
	require.Empty(t, result.Errors)
	got, err := recovered.GetStoredNode("test:a")
	require.NoError(t, err)
	assertAcceptedStoredImage(t, sourceNode, got)
	edge, err := recovered.GetStoredEdge("test:e")
	require.NoError(t, err)
	assertAcceptedStoredImage(t, sourceEdge, edge)
	// Replaying the identical record has a same-commit logical receipt.
	beforeNodes, err := recovered.NodeCount()
	require.NoError(t, err)
	beforeEdges, err := recovered.EdgeCount()
	require.NoError(t, err)
	payload, err := EncodeEntityTransaction(EntityTransactionRequest{Namespace: prepared.Namespace(), LogicalID: prepared.LogicalID(), Operations: prepared.Operations()})
	require.NoError(t, err)
	require.NoError(t, ApplyAcceptedEntityTransaction(recovered, payload))
	afterNodes, err := recovered.NodeCount()
	require.NoError(t, err)
	require.Equal(t, beforeNodes, afterNodes)
	afterEdges, err := recovered.EdgeCount()
	require.NoError(t, err)
	require.Equal(t, beforeEdges, afterEdges)
}

func assertAcceptedStoredImage(t *testing.T, want, got any) {
	t.Helper()
	if node, ok := want.(*Node); ok {
		actual, valid := got.(*Node)
		require.True(t, valid)
		require.Equal(t, node.RuntimeMetadata().VisibilitySuppressed, actual.RuntimeMetadata().VisibilitySuppressed,
			"persisted semantic field VisibilitySuppressed differs")
	}
	a, b := reflect.ValueOf(want).Elem(), reflect.ValueOf(got).Elem()
	for i := 0; i < a.NumField(); i++ {
		field := a.Type().Field(i)
		if !field.IsExported() || field.Name == "Database" || field.Name == "EmbeddingsStoredSeparately" {
			continue
		}
		left, right := a.Field(i).Interface(), b.Field(i).Interface()
		if timestamp, ok := left.(time.Time); ok {
			require.True(t, timestamp.Equal(right.(time.Time)), "persisted timestamp %s", field.Name)
			continue
		}
		require.True(t, reflect.DeepEqual(left, right), "persisted semantic field %s differs", field.Name)
	}
}

// WAL fixtures must own the feature they require, independently of preceding
// tests, and restore the exact incoming state after all store cleanup.
func TestAcceptedWALFixtureOwnsFeatureState(t *testing.T) {
	for _, enabled := range []bool{false, true} {
		name := "disabled"
		if enabled {
			name = "enabled"
		}
		t.Run(name, func(t *testing.T) {
			restore := config.WithWALDisabled
			if enabled {
				restore = config.WithWALEnabled
			}
			t.Cleanup(restore())
			t.Run("semantic_image", TestAcceptedWALRoutesAndRecoversAtomicSemanticImage)
			t.Run("pending_close", TestAcceptedWALCloseRetiresPendingNativeFrameWithoutDiscard)
			require.Equal(t, enabled, config.IsWALEnabled(), "semantic fixture must restore incoming WAL policy")
		})
	}
}
